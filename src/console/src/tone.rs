//! Тестовый звук без эмулятора: тон и мелодия прямо в аудиокодек.
//!
//! Зачем отдельно от `nes::speaker`: там сэмплы приходят из APU в темпе
//! эмуляции и пересчитываются в частоту кодека дробным шагом. Здесь ничего
//! этого нет — генератор считает сэмпл ровно на сетке кодека и кладёт его в
//! FIFO, когда там появилось место. Это разделяет две причины плохого звука:
//!
//! - тут чисто, а в игре нет → виновата выдача сэмплов из эмулятора;
//! - плохо и тут → дело в железе: перегрузка входа усилителя, акустика,
//!   питание выходного каскада.
//!
//! Ничего из этого не вызывается при загрузке (см. `main.rs`) — слушать
//! тестовые сигналы на каждой прошивке невыносимо.

use crate::codec;

/// Нарастание и затухание каждой ноты. Без него скачок уровня на старте и в
/// конце слышен как щелчок.
const RAMP_MS: u32 = 5;

/// Пауза между нотами — чтобы одинаковые ноты подряд не слипались.
const GAP_MS: u32 = 15;

