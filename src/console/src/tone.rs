/// Форма волны.
#[derive(Clone, Copy)]
pub enum Wave {
  /// Чистый синус — эталон для оценки шума, самый тихий.
  Sine,
  /// Меандр 50% — громко и разборчиво.
  Square,
  /// Импульс 25% — тембр «как в NES», чуть тоньше меандра.
  Pulse25,
}

/// Ноты второй октавы, Гц (равномерный строй, A4 = 440). Именно этот регистр
/// маленький динамик отдаёт лучше всего.
const C5: u32 = 523;
const D5: u32 = 587;
const E5: u32 = 659;
const F5: u32 = 698;
const G5: u32 = 784;

/// «Ода к радости», две фразы: (частота, длительность в мс).
const ODE: [(u32, u32); 16] = [
  (E5, Q),
  (E5, Q),
  (F5, Q),
  (G5, Q),
  (G5, Q),
  (F5, Q),
  (E5, Q),
  (D5, Q),
  (C5, Q),
  (C5, Q),
  (D5, Q),
  (E5, Q),
  (E5, Q + E),
  (D5, E),
  (D5, H),
  (C5, H),
];

const Q: u32 = 300; // четверть
const E: u32 = 150; // восьмая
const H: u32 = 600; // половина

/// Значение волны в точке фазы, ±127.
#[inline(always)]
fn wave_at(wave: Wave, phase: u64) -> i32 {
  match wave {
    Wave::Sine => SINE[((phase >> 24) & 0xff) as usize] as i32,
    Wave::Square => {
      if phase & 0x8000_0000 != 0 {
        127
      } else {
        -127
      }
    }
    Wave::Pulse25 => {
      if (phase >> 30) == 0 {
        127
      } else {
        -127
      }
    }
  }
}

/// Нота: форма `wave`, частота `freq_hz`, длительность `ms`, амплитуда
/// `amp` (0..127).
///
/// Фаза — 32-битный аккумулятор: шаг за сэмпл равен `freq × 2^32 / Fs`, так
/// частота задаётся точно и без плавающей точки.
pub fn tone(wave: Wave, freq_hz: u32, ms: u32, amp: u8) {
  let fs = codec::SAMPLE_HZ;
  let total = (fs as u64 * ms as u64 / 1000) as u32;
  if total == 0 || freq_hz == 0 {
    return;
  }
  let amp = if amp > 127 { 127u32 } else { amp as u32 };

  let ramp = {
    let r = fs / 1000 * RAMP_MS;
    let half = total / 2;
    let r = if r > half { half } else { r };
    if r == 0 {
      1
    } else {
      r
    }
  };

  let inc = ((freq_hz as u64) << 32) / fs as u64;
  let mut phase: u64 = 0;

  for n in 0..total {
    let env = if n < ramp {
      amp * n / ramp
    } else if total - n <= ramp {
      amp * (total - n) / ramp
    } else {
      amp
    };

    // wave_at даёт ±127, env ≤ 127 → произведение ±16129. Умножаем на 2 и
    // получаем ±32258, почти полную шкалу i16.
    let s = wave_at(wave, phase) * env as i32 * 2;
    codec::push_blocking(s as i16);

    phase = (phase + inc) & 0xffff_ffff;
  }
}

/// Тишина: реальные нули в FIFO, а не остановка вывода.
fn rest_ms(ms: u32) {
  let total = codec::SAMPLE_HZ as u64 * ms as u64 / 1000;
  for _ in 0..total {
    codec::push_blocking(0);
  }
}

/// Один и тот же тон на трёх уровнях громкости ЦАПа.
///
/// Отделяет перегрузку от акустики. Уровень меняется до ЦАПа, то есть
/// разрядность не теряется и сам сигнал остаётся одинаково чистым — если
/// громкий вариант хрипит, а тихий нет, упирается в потолок аналоговый тракт
/// (вход PAM8301 через R20 150К или сам усилитель). Если все три звучат
/// одинаково шершаво, тракт ни при чём и дело в динамике или его оформлении.
pub fn level_test() {
  const LEVELS: [(u8, &str); 3] = [(0xa0, "0 dB"), (0x94, "-9 dB"), (0x88, "-18 dB")];

  for (v, name) in LEVELS {
    println!("codec: 1 kHz @ {}", name);
    codec::set_volume(v);
    tone(Wave::Sine, 1000, 1500, 127);
    rest_ms(400);
  }
  codec::set_volume(0xa0);
}

/// «Ода к радости», две фразы. Проверка «звук вообще есть и высота верная»;
/// о качестве по ней судить нельзя — см. `music()`.
pub fn melody() {
  const AMP: u8 = 100;

  for (freq, ms) in ODE {
    tone(Wave::Sine, freq, ms - GAP_MS, AMP);
    rest_ms(GAP_MS);
  }
}

/// Настоящая запись — 6 секунд фортепиано, 24 кГц моно 16 бит.
///
/// Зачем не синтезированные ноты: у голого генератора спектр из одной линии и
/// пары гармоник, и на нём динамик звучит «нормально» практически всегда. Про
/// качество говорит только широкополосный сигнал с резкими атаками — на нём
/// слышно и дребезг подвеса, и обрезанный низ, и призвуки корпуса. Фортепиано
/// для этого удобно: удар молоточка это почти щелчок, то есть весь диапазон
/// сразу, а звучание всем знакомо и отклонения слышны без эталона.
///
/// Шуберт, соната для фортепиано №16 ля минор D845, I. Moderato, исполнитель
/// Paul Pitman. Public domain (Musopen, через Wikimedia Commons). Готовилось
/// так, фрагмент с 40-й секунды:
///
/// ```text
/// ffmpeg -i sonata.flac -ac 1 -ar 24000 -f s16le probe.pcm
/// # вырезать 40..46 с, нормировать по пику до 29000, фейды 15 мс
/// ```
///
/// 288 КБ в прошивке — это половина её размера, но памяти 64 МБ, а ассет
/// нужен ровно для отладки звука.
pub fn music() {
  static PCM: &[u8] = include_bytes!("../assets/piano_24k_mono.pcm");

  for s in PCM.chunks_exact(2) {
    codec::push_blocking(i16::from_le_bytes([s[0], s[1]]));
  }
}

/// Экспоненциальный свип от `f0` до `f1` — главный инструмент для оценки
/// динамика.
///
/// По нему слышно то, чего не слышно ни на одной мелодии: на какой частоте
/// низ пропадает совсем (у маленького динамика без корпуса это обычно
/// 400-700 Гц), где подвес начинает дребезжать, где сидят резонансы. Свип
/// именно экспоненциальный, а не линейный: слух логарифмический, и при
/// линейном почти всё время уходило бы на верх диапазона.
///
/// Считается без плавающей точки: частота умножается на постоянный
/// коэффициент каждый сэмпл (`freq += freq / div`), а `div` подбирается из
/// нужного отношения частот и длительности через целочисленный логарифм. Из-за
/// грубой интерполяции логарифма конец свипа приходит на 3-4% ниже
/// запрошенного — для тестового сигнала это ничего не меняет.
///
/// Уровень заметно ниже полной шкалы: непрерывный синус на резонансе утомляет
/// куда сильнее музыки той же амплитуды.
pub fn sweep(f0: u32, f1: u32, ms: u32) {
  const AMP: i32 = 16_000;

  let fs = codec::SAMPLE_HZ;
  let total = fs as u64 * ms as u64 / 1000;
  if total == 0 || f0 == 0 || f1 <= f0 {
    return;
  }

  // ln(f1/f0) в формате 8.8. log2 берём по позиции старшего бита, дробную
  // часть — линейной интерполяцией по следующим битам: точности «плюс-минус
  // процент» для тестового сигнала более чем достаточно.
  let ratio = f1 / f0;
  let log2_int = 31 - ratio.leading_zeros();
  let frac = if log2_int > 0 {
    ((ratio << (31 - log2_int)) & 0x7fff_ffff) >> 23
  } else {
    0
  };
  let log2_q8 = (log2_int << 8) | frac;
  let ln_q8 = (log2_q8 as u64 * 177) / 256; // ln(x) = log2(x) × 0.693

  // (1 + 1/div)^total = ratio → div = total / ln(ratio)
  let div = ((total << 8) / ln_q8.max(1)).max(64);

  // Частота в формате 16.16, чтобы деление на div не съедало её целиком.
  let mut freq_q16 = (f0 as u64) << 16;
  let mut phase: u64 = 0;

  for _ in 0..total {
    // Дробную часть частоты не теряем: на 50 Гц округление до целых Гц это
    // уже 2%, и низ свипа шёл бы ступеньками.
    let inc = (freq_q16 << 16) / fs as u64;
    let s = SINE[((phase >> 24) & 0xff) as usize] as i32 * AMP / 127;
    codec::push_blocking(s as i16);
    phase = (phase + inc) & 0xffff_ffff;
    freq_q16 += freq_q16 / div;
  }
}

/// Полный набор для оценки динамика: свип, потом музыка.
pub fn quality_test() {
  println!("codec: sweep 50 Hz -> 12 kHz, 8 s");
  sweep(50, 12_000, 8000);
  rest_ms(500);
  println!("codec: piano, 6 s");
  music();
}

/// Одна и та же фраза тремя тембрами подряд — синус, меандр, импульс 25%.
///
/// Нужна, чтобы на слух отделить акустику от кода: если синус слышно заметно
/// хуже меандра, дело в динамике (маленький диффузор без корпуса почти не
/// отдаёт ниже ~500 Гц, а меандр богат гармониками выше). Ровно поэтому NES
/// играет музыку импульсными каналами, а не синусами.
pub fn compare_waves() {
  const AMP: u8 = 100;
  const NOTES: [u32; 4] = [C5, E5, G5, C5 * 2];

  for wave in [Wave::Sine, Wave::Square, Wave::Pulse25] {
    for freq in NOTES {
      tone(wave, freq, 200, AMP);
      rest_ms(GAP_MS);
    }
    rest_ms(250);
  }
}
