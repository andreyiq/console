//! Кэши ядра C906 (XuanTie RISC-V) — включение и поддержание когерентности.
//!
//! # Зачем это вообще
//!
//! C906 стартует с `MHCR = 0`, то есть **I-cache и D-cache выключены**.
//! Обычно их включает boot0 от Allwinner, но мы грузимся через `xfel exec`
//! и boot0 пропускаем. `riscv-rt` их тоже не трогает — он вендоронейтральный
//! и знает только стандартные CSR (из вендорских лезет лишь в `mstatus.FS`).
//!
//! В результате весь код и данные лежат в DDR2-528 по 0x40000000, и каждая
//! выборка инструкции и каждый доступ к данным реально идёт в DDR. Замер до
//! включения кэшей: эмуляция кадра NES — 724 мс, то есть ~8100 такт на одну
//! точку PPU при норме 40–80. Кэши дают тут десятки раз.
//!
//! # Вендорские CSR C906
//!
//! Их нет в стандарте RISC-V, поэтому обращаемся по номерам:
//!
//! | CSR    | Имя      | Что делает                                  |
//! |--------|----------|---------------------------------------------|
//! | 0x7c0  | MXSTATUS | расширенный статус (T-Head ISA, unaligned)  |
//! | 0x7c1  | MHCR     | конфигурация железа — вкл/выкл кэшей        |
//! | 0x7c2  | MCOR     | операции над кэшем (инвалидация)            |
//! | 0x7c3  | MCCR2    | доп. управление кэшем (way, prefetch)       |
//! | 0x7c5  | MHINT    | подсказки: префетч, предсказание way        |
//!
//! Значения взяты из mainline u-boot (`arch/riscv/cpu/c906/cpu.c`,
//! `harts_early_init`) — это known-good набор именно для этого ядра.
//!
//! # Когерентность с DMA
//!
//! D-cache работает в режиме write-back + write-allocate: запись CPU оседает
//! в кэше и в DDR попадает не сразу. DMAC читает DDR **напрямую**, кэш он не
//! видит. Значит перед каждым DMA-переносом грязные строки надо вытолкнуть в
//! память — это `clean_dcache()`. Иначе DMAC прочитает устаревшие данные:
//! и дескриптор (`dma.rs`), и сам кадр. Симптом — мусор или замерший кадр
//! на дисплее.
//!
//! Обратное направление (устройство пишет, CPU читает) нам пока не нужно —
//! мы только передаём. Если появится RX, там понадобится invalidate.
//!
//! # Почему MMIO не ломается
//!
//! Регистры периферии (CCU 0x02001000, SPI0, DMAC 0x03002000) лежат ниже
//! 0x40000000. MMU у нас выключен, и в этом режиме кэшируемость определяется
//! дефолтной PMA-картой C906, где область ниже DDR — non-cacheable device
//! space. Поэтому `read_volatile`/`write_volatile` по регистрам продолжают
//! ходить прямо в железо. (`volatile` в Rust запрещает компилятору убирать и
//! переставлять доступы, но на аппаратное кэширование не влияет — за это
//! отвечает именно PMA.)

use core::arch::asm;

// --- Номера вендорских CSR ---
// (в inline asm подставляются литералами, констант тут нет — asm! требует
//  литерал в позиции CSR)

// --- Биты MXSTATUS ---
/// THEADISAEE (бит 22) — разрешить расширенные инструкции T-Head.
/// Без него `dcache.call` падает как illegal instruction.
const MXSTATUS_THEADISAEE: u64 = 1 << 22;
/// MM (бит 21) — аппаратная обработка невыровненных доступов.
/// Без него unaligned load/store уходит в trap, а обработчика у нас нет.
const MXSTATUS_MM: u64 = 1 << 21;

// --- Биты MHCR ---
// bit0 IE  — I-cache enable          bit4 RS  — return address stack
// bit1 DE  — D-cache enable          bit5 BPE — branch prediction enable
// bit2 WA  — write allocate          bit6 BTB — branch target buffer
// bit3 WB  — write back              bit8 WBR — write burst enable
/// Полный набор, как ставит u-boot для C906: кэши + write-back/allocate +
/// предсказание переходов + burst-записи.
const MHCR_ENABLE_ALL: u64 = 0x11ff;

/// MCOR: инвалидировать I-cache и D-cache, а также BTB/BHT.
/// Содержимое кэшей после сброса не определено, поэтому перед включением
/// их обязательно надо инвалидировать.
const MCOR_INVALIDATE_ALL: u64 = 0x7_0013;

/// MCCR2 — конфигурация way/prefetch. Значение из u-boot для C906.
const MCCR2_INIT: u64 = 0xe041_0009;

/// MHINT — префетч D-cache, предсказание way. Значение из u-boot для C906.
const MHINT_INIT: u64 = 0x16_e30c;

// --- Сырые кодировки инструкций T-Head ---
//
// Этих мнемоник нет в базовом RISC-V, а рассчитывать на поддержку расширения
// `xtheadcmo` в ассемблере не хочется. Поэтому кладём машинные слова через
// `.insn 4, ...` — она пишет ровно 4 байта инструкции и, в отличие от
// `.word`, не вставляет выравнивающий паддинг (при включённом C-расширении
// PC может быть выровнен на 2 байта, и паддинг попал бы в поток инструкций).
//
//   dcache.call = 0x0010000b — вытолкнуть (writeback) все грязные строки D$
//   sync.s      = 0x0190000b — дождаться завершения, в т.ч. видимости для шины
//
// (кодировки подставлены прямо в `asm!` ниже — шаблон `asm!` принимает только
//  строковые литералы, константу `&str` туда передать нельзя)

/// Включить I-cache и D-cache. Вызывать как можно раньше в `main`.
///
/// Порядок важен: сначала разрешаем расширения T-Head, потом инвалидируем
/// кэши, и только потом включаем — иначе ядро начнёт попадать в
/// неинициализированные строки.
pub fn enable() {
  unsafe {
    // 1. Расширения T-Head + аппаратный unaligned.
    //    csrs (set bits), а не csrw — в MXSTATUS есть и другие поля
    //    (например текущий режим привилегий), их затирать нельзя.
    asm!(
      "csrs 0x7c0, {0}",
      in(reg) MXSTATUS_THEADISAEE | MXSTATUS_MM,
      options(nomem, nostack)
    );

    // 2. Инвалидировать I$/D$/BTB/BHT перед включением.
    asm!("csrw 0x7c2, {0}", in(reg) MCOR_INVALIDATE_ALL, options(nomem, nostack));

    // 3. Включить кэши.
    asm!("csrw 0x7c1, {0}", in(reg) MHCR_ENABLE_ALL, options(nomem, nostack));

    // 4. Тонкая настройка: way/prefetch.
    asm!("csrw 0x7c3, {0}", in(reg) MCCR2_INIT, options(nomem, nostack));
    asm!("csrw 0x7c5, {0}", in(reg) MHINT_INIT, options(nomem, nostack));
  }
}

/// Вытолкнуть все грязные строки D-cache в память (writeback) и дождаться
/// завершения. Вызывать перед любым DMA-переносом, который читает
/// подготовленные CPU данные.
///
/// Чистит кэш целиком (32 КБ), а не диапазон: `dcache.call` — одна
/// инструкция вместо цикла по 2880 строкам буфера кадра, и по времени это
/// единицы микросекунд против 73 мс самого переноса. Строки остаются
/// валидными (clean, не invalidate), так что холодного кэша после этого нет.
#[inline]
pub fn clean_dcache() {
  unsafe {
    // fence перед выталкиванием — чтобы все записи CPU уже были в кэше
    // к моменту dcache.call, а не висели в store buffer.
    asm!(
      "fence rw, rw",
      ".insn 4, 0x0010000b", // dcache.call — writeback всех грязных строк
      ".insn 4, 0x0190000b", // sync.s      — дождаться завершения
      options(nostack, preserves_flags)
    );
  }
}

/// Прочитать MHCR (0x7c1) — для отладки. Биты 0/1 = I-cache/D-cache enable.
pub fn read_mhcr() -> u64 {
  let v: u64;
  unsafe { asm!("csrr {0}, 0x7c1", out(reg) v, options(nomem, nostack)) };
  v
}

/// Прочитать MXSTATUS (0x7c0) — для отладки. Бит 22 = THEADISAEE.
pub fn read_mxstatus() -> u64 {
  let v: u64;
  unsafe { asm!("csrr {0}, 0x7c0", out(reg) v, options(nomem, nostack)) };
  v
}

/// Прочитать MHINT (0x7c5) — для отладки.
pub fn read_mhint() -> u64 {
  let v: u64;
  unsafe { asm!("csrr {0}, 0x7c5", out(reg) v, options(nomem, nostack)) };
  v
}
