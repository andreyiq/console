//! Вывод звука NES на PWM7 (пин PD22, гребёнка P2 пин 19).
//!
//! APU крейта `runes` сам считает сэмплы и зовёт `Speaker::queue` на частоте
//! 44100 Гц (`apu::AUDIO_SAMPLE_FREQ`), диапазон — полный i16 вокруг нуля.
//! Наше дело — превратить сэмпл в скважность PWM.
//!
//! Подключение для теста (пока нет усилителя):
//! ```text
//! PD22 ──[470 Ом]── динамик ── GND
//! ```
//! Резистор обязателен: динамик 8 Ом напрямую на 3.3 В это ~400 мА, а пин
//! F133 отдаёт 10-20 мА. С 470 Ом получается ~7 мА — тихо, но безопасно.
//! Фильтр не нужен, несущую 390 кГц гасит сама катушка динамика.
//!
//! ВАЖНО про темп: сэмплы привязаны к эмулируемому времени, а эмуляция идёт
//! примерно на 55% реальной скорости (см. AGENTS.md). Значит звук будет ниже
//! и медленнее, пока эмулятор не выйдет на 60 FPS. Это не поломка вывода.

use core::sync::atomic::{AtomicU32, Ordering};

use runes::apu;

use crate::pwm;

/// Программное усиление сэмпла перед выводом.
///
/// Замерено на Mario (поле `peak=` в строке `nes: frame ...`, это пик |сэмпла|
/// до усиления): средний пик по окну — 12089, максимум в музыке — 23027 из
/// 32768. То есть APU и так занимает ~70% шкалы, большого запаса нет.
///
/// Значение подобрано под компрессор ниже: с мягким коленом пики не бьются
/// в потолок, поэтому усиление можно держать выше, чем при простом обрезании.
const GAIN: i32 = 3;

/// Порог компрессора: до него сигнал идёт как есть.
const KNEE: i32 = 20_000;
/// Во сколько раз поджимается всё, что выше порога.
///
/// Максимум, который может прийти после усиления, — 23027 × 3 ≈ 69000
/// (23027 это замеренный пик на Mario). Колено отображает его в
/// 20000 + 49000/4 ≈ 32250, то есть в потолок 32767 мы не упираемся вообще и
/// жёсткого обрезания нет.
const RATIO: i32 = 4;

/// Пик |сэмпла| до усиления, с момента прошлого чтения. Для подбора GAIN.
static PEAK: AtomicU32 = AtomicU32::new(0);

/// Забрать и обнулить пик.
pub fn take_peak() -> u32 {
  PEAK.swap(0, Ordering::Relaxed)
}

/// Заглушка: сэмплы в никуда. Оставлена, чтобы можно было быстро отключить
/// звук и сравнить время кадра.
#[allow(dead_code)]
pub struct NoAudio;

impl apu::Speaker for NoAudio {
  #[inline(always)]
  fn queue(&mut self, _sample: i16) {}
}

/// Компрессор с мягким коленом: до `KNEE` линейно, выше — поджимаем в `RATIO`
/// раз, и только в самом конце ограничиваем.
///
/// Зачем не простое обрезание: у музыки NES пик втрое выше среднего уровня.
/// Чтобы поднять слышимую громкость, надо усиливать по среднему — а тогда
/// пики уходят за потолок, и жёсткое обрезание превращает их в квадрат, что
/// слышно как хрип. Колено делает то же самое плавно: тихое становится
/// громче, громкое просто перестаёт расти.
#[inline(always)]
fn compress(x: i32) -> i32 {
  let mag = if x < 0 { -x } else { x };
  let out = if mag <= KNEE {
    mag
  } else {
    KNEE + (mag - KNEE) / RATIO
  };
  // Страховка на случай неожиданно громкого сэмпла.
  let out = if out > 32767 { 32767 } else { out };
  if x < 0 {
    -out
  } else {
    out
  }
}

/// Вывод сэмплов на PWM7.
pub struct PwmSpeaker;

impl PwmSpeaker {
  pub fn new() -> Self {
    pwm::init();
    Self
  }
}

impl apu::Speaker for PwmSpeaker {
  /// i16 вокруг нуля → усиление с ограничением → 8-битная скважность
  /// вокруг 128.
  ///
  /// Сдвиг на 8 вместо деления: `x + 32768` даёт 0..65535, старший байт и
  /// есть нужные 0..255.
  #[inline(always)]
  fn queue(&mut self, sample: i16) {
    let mag = sample.unsigned_abs() as u32;
    PEAK.fetch_max(mag, Ordering::Relaxed);

    pwm::set_duty(((compress(sample as i32 * GAIN) + 32768) >> 8) as u8);
  }
}
