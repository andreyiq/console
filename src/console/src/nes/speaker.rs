//! Вывод звука NES на аудиокодек F133 (`crate::codec`) — пины HPOUTL/R, дальше
//! на плате штатный усилитель PAM8301 и гребёнка P6 «AUDIO».
//!
//! APU крейта `runes` сам считает сэмплы и зовёт `Speaker::queue` на частоте
//! 44100 Гц (`apu::AUDIO_SAMPLE_FREQ`), диапазон — полный i16 вокруг нуля.
//!
//! # Две частоты, которые не совпадают
//!
//! Кодек играет ровно 24 000 сэмплов в секунду реального времени. APU выдаёт
//! 44100 сэмплов на секунду *эмулируемого* времени, а эмуляция идёт медленнее
//! реальной (сейчас ~33 FPS из 60), то есть реально приходит ~24-25 тысяч
//! сэмплов в секунду, и это число плавает от сцены к сцене.
//!
//! Разница лечится не подгонкой частоты вывода (её задаёт железо), а
//! пересчётом: читаем буфер с дробным шагом и линейно интерполируем между
//! соседними сэмплами. Шаг `STEP` (16.16) равен «сколько сэмплов источника
//! приходится на один сэмпл кодека» и уточняется раз в кадр по факту
//! выработки. Ошибка в шаге это ошибка в высоте звука; полутон — 6%, а замер
//! даёт точность лучше 0.5%, так что расстройка не слышна.
//!
//! Почему не проще — выбрасывать лишние сэмплы: при расхождении 3% пришлось бы
//! выбрасывать каждый 33-й, а это широкополосный треск. Интерполяция стоит
//! одно умножение на сэмпл и не вносит слышимых искажений на 24 кГц.
//!
//! # Кто задаёт темп
//!
//! Темп задаёт FIFO кодека, а не наш код:
//!
//! - `queue()` кладёт сэмпл в кольцевой буфер;
//! - `pump()` перекладывает из буфера в FIFO, пока в FIFO есть место.
//!
//! `pump()` можно звать когда угодно и как угодно неравномерно — сетку
//! отсчётов держит железо. Важно только, чтобы FIFO не опустел: запас 128
//! сэмплов на 24 кГц это 5.3 мс, поэтому `pump()` вызывается ещё и из
//! ожидания DMA-флаша и из ожидания FIFO UART, где мы стоим по несколько мс.
//!
//! Это главное отличие от прежнего вывода на PWM, где момент каждого сэмпла
//! приходилось выставлять вручную по `mcycle`: любое дрожание вызова было
//! слышно как шум, а провал на время флаша кадра — как призвук на частоте
//! кадров.

use core::sync::atomic::{AtomicBool, AtomicU16, AtomicU32, AtomicU64, Ordering};

use runes::apu;

use crate::codec;
use crate::utils::CPU_HZ;

/// Программное усиление сэмпла перед выводом.
///
/// Замерено на Mario (поле `peak=` в строке `nes: frame ...`): средний пик по
/// окну — 12089, максимум в музыке — 23027 из 32768. То есть APU занимает
/// ~70% шкалы и усиливать почти нечего.
///
/// На PWM усиление было нужно (там громкость упиралась в 8 бит и в 470 Ом).
/// Здесь тракт 16-битный и громкость задаётся аналоговым усилителем, поэтому
/// правильный порядок: сначала пробуем 1 и штатную громкость ЦАПа
/// (`codec::set_volume`), и только если тихо — поднимаем. Цифровое усиление
/// портит сигнал, аналоговое нет.
const GAIN: i32 = 1;

/// Порог компрессора: до него сигнал идёт как есть.
const KNEE: i32 = 20_000;
/// Во сколько раз поджимается всё, что выше порога.
const RATIO: i32 = 4;

/// Пик |сэмпла| до усиления, с момента прошлого чтения. Для подбора GAIN.
static PEAK: AtomicU32 = AtomicU32::new(0);

/// Забрать и обнулить пик.
pub fn take_peak() -> u32 {
  PEAK.swap(0, Ordering::Relaxed)
}

/// Размер кольцевого буфера в сэмплах, степень двойки.
///
/// 2048 сэмплов на ~24 кГц это 85 мс звука. Целимся держать заполнение около
/// четверти (~21 мс задержки): меньше — рискуем опустошением на всплесках
/// времени кадра (в логе бывают кадры по 50 мс), больше — звук начинает
/// заметно отставать от картинки.
const CAP: usize = 2048;
const CAP_MASK: u32 = (CAP - 1) as u32;

/// Сэмплы, готовые к выводу (i16, хранится как u16).
static BUF: [AtomicU16; CAP] = [const { AtomicU16::new(0) }; CAP];
/// Счётчик записи, монотонный.
static WPOS: AtomicU32 = AtomicU32::new(0);
/// Позиция чтения в формате 16.16: старшие биты — индекс, младшие — дробная
/// часть между двумя сэмплами.
static POSF: AtomicU64 = AtomicU64::new(0);

/// Сколько сэмплов источника на один сэмпл кодека, 16.16. Старт — 1.0, дальше
/// `retune()` заменяет измеренным значением.
static STEP: AtomicU32 = AtomicU32::new(1 << 16);

/// Границы шага: от 0.25× до 4×. Защита от разгона в никуда, если эмуляция
/// встанет или наоборот резко ускорится.
const STEP_MIN: u32 = 1 << 14;
const STEP_MAX: u32 = 1 << 18;

/// Целевое заполнение буфера — четверть, ~21 мс задержки.
const TARGET_FILL: u32 = CAP as u32 / 4;

/// Набрал ли буфер стартовый запас. Пока не набрал, не выводим ничего: иначе
/// первые кадры (они идут по 70 мс, пока греются кэши) звучат как заикание.
static PRIMED: AtomicBool = AtomicBool::new(false);

/// Сколько сэмплов APU **предложил** — включая выброшенные при переполнении.
///
/// Считать выработку по `WPOS` нельзя: при полном буфере он стоит, замер
/// занижает темп, шаг чтения уменьшается, буфер переполняется ещё сильнее.
/// Это положительная обратная связь, на живой плате она за 0.1 с уводила
/// вывод в упор.
static PRODUCED: AtomicU32 = AtomicU32::new(0);

/// Состояние измерителя темпа: счётчик выработки и момент прошлого замера.
static LAST_P: AtomicU32 = AtomicU32::new(0);
static LAST_T: AtomicU64 = AtomicU64::new(0);

/// Сколько раз пришлось выбрасывать накопившееся, чтобы вернуть задержку.
static RESYNC: AtomicU32 = AtomicU32::new(0);

/// Сколько раз буфер оказался пуст, когда в FIFO было место (звук заминается —
/// кодек повторяет последний сэмпл, см. `SEND_LASAT`).
static UNDERRUN: AtomicU32 = AtomicU32::new(0);
/// Сколько сэмплов APU выбросил из-за полного буфера.
static OVERRUN: AtomicU32 = AtomicU32::new(0);

/// Статистика для лога: (темп источника в Гц, заполнение буфера, опустошений,
/// потерянных сэмплов, сбросов задержки). Счётчики обнуляются.
pub fn take_stats() -> (u32, u32, u32, u32, u32) {
  let step = STEP.load(Ordering::Relaxed) as u64;
  let rate = (step * codec::SAMPLE_HZ as u64 >> 16) as u32;
  let fill = WPOS
    .load(Ordering::Relaxed)
    .wrapping_sub((POSF.load(Ordering::Relaxed) >> 16) as u32);
  (
    rate,
    fill,
    UNDERRUN.swap(0, Ordering::Relaxed),
    OVERRUN.swap(0, Ordering::Relaxed),
    RESYNC.swap(0, Ordering::Relaxed),
  )
}

/// Уточнить шаг чтения по факту выработки. Зовётся раз в кадр.
///
/// Прямой замер, а не регулятор по заполнению буфера: первая версия крутила
/// темп вывода по заполнению и получился релейный регулятор, который метался
/// между границами — на слух высота звука уезжала на пол-октавы. Здесь
/// отношение «сэмплов выработано / тактов прошло» сразу даёт правильную
/// высоту, а заполнение правит только медленный дрейф смещением на 0.4%.
pub fn retune() {
  let now = riscv::register::mcycle::read64();
  let p = PRODUCED.load(Ordering::Relaxed);

  let last_t = LAST_T.load(Ordering::Relaxed);
  let last_p = LAST_P.load(Ordering::Relaxed);
  LAST_T.store(now, Ordering::Relaxed);
  LAST_P.store(p, Ordering::Relaxed);

  if last_t == 0 {
    return;
  }
  // Именно PRODUCED, а не WPOS: см. комментарий у счётчика.
  let produced = p.wrapping_sub(last_p) as u64;
  let elapsed = now.wrapping_sub(last_t);
  if produced == 0 || elapsed == 0 {
    return;
  }

  // Сэмплов источника в секунду реального времени.
  let rate = produced * CPU_HZ / elapsed;
  let mut step = (rate << 16) / codec::SAMPLE_HZ as u64;

  // Смещение на 1/256 (~0.4%) в сторону, которая тянет буфер к цели: читаем
  // чуть быстрее, если накопилось лишнее, и чуть медленнее, если мало.
  let w = WPOS.load(Ordering::Relaxed);
  let fill = w.wrapping_sub((POSF.load(Ordering::Relaxed) >> 16) as u32);
  if fill > TARGET_FILL {
    step += step / 256;
  } else {
    step -= step / 256;
  }

  STEP.store(
    step.clamp(STEP_MIN as u64, STEP_MAX as u64) as u32,
    Ordering::Relaxed,
  );

  // Страховка от залипания. Смещения 0.4% хватает на медленный дрейф, но не
  // на разовый скачок: первые кадры идут по 70 мс, потом темп выработки
  // удваивается, и буфер успевает забиться. Если он почти полон —
  // выбрасываем накопившееся и продолжаем от целевой задержки. Один щелчок
  // против постоянно растущего отставания звука от картинки.
  if fill > CAP as u32 - CAP as u32 / 8 {
    POSF.store(
      ((w.wrapping_sub(TARGET_FILL)) as u64) << 16,
      Ordering::Relaxed,
    );
    RESYNC.fetch_add(1, Ordering::Relaxed);
  }
}

/// Долить FIFO кодека из кольцевого буфера.
///
/// Зовётся из главного цикла эмулятора (после каждой инструкции 6502) и из
/// всех мест, где код блокируется на несколько миллисекунд. Быстрый выход
/// вперёд: одно чтение регистра состояния FIFO.
#[inline]
pub fn pump() {
  let w = WPOS.load(Ordering::Relaxed);
  let mut posf = POSF.load(Ordering::Relaxed);

  if !PRIMED.load(Ordering::Relaxed) {
    // Ждём стартовый запас, ничего не выводя.
    if w.wrapping_sub((posf >> 16) as u32) < TARGET_FILL {
      return;
    }
    // Набрали: начинаем ровно с целевой задержки, чтобы играть свежий звук,
    // а не тот, что накопился за время ожидания.
    posf = ((w.wrapping_sub(TARGET_FILL)) as u64) << 16;
    PRIMED.store(true, Ordering::Relaxed);
  }

  let step = STEP.load(Ordering::Relaxed) as u64;
  let mut room = codec::fifo_room();

  while room > 0 {
    let i = (posf >> 16) as u32;
    // Для интерполяции нужны два соседних сэмпла.
    if w.wrapping_sub(i) < 2 {
      UNDERRUN.fetch_add(1, Ordering::Relaxed);
      // Заново набрать запас: пока буфер пуст, доливать нечем, а кодек и так
      // тянет последний сэмпл (`SEND_LASAT`).
      PRIMED.store(false, Ordering::Relaxed);
      break;
    }

    let a = BUF[(i & CAP_MASK) as usize].load(Ordering::Relaxed) as i16 as i32;
    let b = BUF[(i.wrapping_add(1) & CAP_MASK) as usize].load(Ordering::Relaxed) as i16 as i32;
    let f = (posf & 0xffff) as i32;
    codec::push((a + ((b - a) * f >> 16)) as i16);

    posf += step;
    room -= 1;
  }

  POSF.store(posf, Ordering::Relaxed);
}

/// Заглушка: сэмплы в никуда. Оставлена, чтобы можно было быстро отключить
/// звук и сравнить время кадра.
#[allow(dead_code)]
pub struct NoAudio;

impl apu::Speaker for NoAudio {
  #[inline(always)]
  fn queue(&mut self, _sample: i16) {}
}

/// Компрессор с мягким коленом: до `KNEE` линейно, выше — поджимаем в `RATIO`
/// раз, и только в самом конце ограничиваем.
///
/// При `GAIN = 1` он почти не работает (пики APU до 23000 против колена
/// 20000) и стоит здесь как страховка от жёсткого обрезания, если усиление
/// придётся поднять.
#[inline(always)]
fn compress(x: i32) -> i32 {
  let mag = if x < 0 { -x } else { x };
  let out = if mag <= KNEE {
    mag
  } else {
    KNEE + (mag - KNEE) / RATIO
  };
  let out = if out > 32767 { 32767 } else { out };
  if x < 0 {
    -out
  } else {
    out
  }
}

/// Вывод сэмплов на аудиокодек.
pub struct CodecSpeaker;

impl CodecSpeaker {
  pub fn new() -> Self {
    codec::init();
    Self
  }
}

impl apu::Speaker for CodecSpeaker {
  /// i16 вокруг нуля → усиление с компрессией → кольцевой буфер.
  ///
  /// В железо здесь ничего не пишется: этим занят `pump()`. Разделение нужно
  /// потому, что FIFO кодека вмещает 5 мс, а APU выдаёт сэмплы рывками — по
  /// целому кадру за раз.
  #[inline(always)]
  fn queue(&mut self, sample: i16) {
    let mag = sample.unsigned_abs() as u32;
    PEAK.fetch_max(mag, Ordering::Relaxed);

    let s = compress(sample as i32 * GAIN) as i16;

    // Считаем выработку до проверки на переполнение — от этого счётчика
    // зависит замер темпа в `retune()`.
    PRODUCED.fetch_add(1, Ordering::Relaxed);

    let w = WPOS.load(Ordering::Relaxed);
    let r = (POSF.load(Ordering::Relaxed) >> 16) as u32;
    if w.wrapping_sub(r) >= CAP as u32 {
      // Буфер полон: вывод не успевает. Теряем сэмпл — это лучше, чем
      // тормозить эмуляцию, и видно в логе по полю `or=`.
      OVERRUN.fetch_add(1, Ordering::Relaxed);
      return;
    }
    BUF[(w & CAP_MASK) as usize].store(s as u16, Ordering::Relaxed);
    WPOS.store(w.wrapping_add(1), Ordering::Relaxed);
  }
}
