//! Ввод: три кнопки на GPIO (влево, вправо, прыжок) + автонажатие START.
//!
//! ## Как подключено
//!
//! Кнопки на гребёнке P3, сразу за PE2/PE3 (UART0). Каждая замкнута между своим
//! пином и GND, внутри F133 включён pull-up — значит отпущенная кнопка читается
//! как 1, нажатая как 0. Внешние резисторы не нужны, GND у всех кнопок общий.
//!
//! | пин | кнопка NES | зачем       |
//! |-----|------------|-------------|
//! | PE4 | LEFT       | идти назад  |
//! | PE5 | RIGHT      | идти вперёд |
//! | PE6 | A          | прыжок      |
//!
//! Физической кнопки START нет — он по-прежнему нажимается сам на 120-м кадре
//! (см. `START_AT`). Без него Mario стоит на заставке, где APU молчит, и
//! «тишина» неотличима от неработающего звука.
//!
//! ## Почему опрос раз в кадр, а не внутри `poll()`
//!
//! `poll()` зовётся из `Joystick`, когда игра дёргает strobe — то есть в
//! произвольной точке кадра, а иногда не зовётся вовсе. Читать пины там значит
//! получить неопределённый момент сэмплирования. Поэтому пины читаются ровно
//! один раз за кадр в `tick_frame()`, результат лежит в `STATE`, а `poll()`
//! его просто отдаёт.
//!
//! Дребезг не гасим: опрос идёт раз в кадр (~30 мс), дребезг тактовой кнопки
//! короче 1 мс, попасть в него практически невозможно. Если провода длинные и
//! появятся ложные нажатия — 100 нФ с пина на GND.

use core::sync::atomic::{AtomicU32, AtomicU8, Ordering};

use runes::controller::stdctl;
use runes::controller::InputPoller;

use crate::gpio::{Func, Pin, Pull, PE4, PE5, PE6};

/// Счётчик кадров — его двигает главный цикл через `tick_frame()`.
static FRAME: AtomicU32 = AtomicU32::new(0);

/// Состояние кнопок, снятое последним `tick_frame()`. Биты — `stdctl::*`.
static STATE: AtomicU8 = AtomicU8::new(0);

/// Все кнопки, замеченные с прошлого `take_seen()` (OR по кадрам).
///
/// Нужно для отладки пайки: лог печатается раз в 10 кадров, а нажатие может
/// быть короче — по мгновенному состоянию не понять, читается ли пин вообще.
static SEEN: AtomicU8 = AtomicU8::new(0);

/// С какого кадра начинать «жать» START и сколько кадров держать.
///
/// Ждём 120 кадров, чтобы игра успела инициализироваться и показать заставку,
/// потом держим START 10 кадров — этого хватает, опрос идёт каждый кадр.
const START_AT: u32 = 120;
const START_LEN: u32 = 10;

/// Кнопки: пин → бит кнопки NES. Добавить кнопку = добавить строку сюда
/// (и константу пина в `gpio.rs`).
const BUTTONS: [(Pin, u8); 3] = [(PE4, stdctl::LEFT), (PE5, stdctl::RIGHT), (PE6, stdctl::A)];

/// Печатать каждое изменение состояния кнопок в UART.
///
/// Включать при отладке пайки: сразу видно, какой пин какой бит даёт и
/// отпускается ли кнопка вообще (именно так нашлись две кнопки, припаянные к
/// внутренне замкнутой паре ног — они висели в нуле с первого кадра).
///
/// В игре держать выключенным: на 115200 одна строка блокирует ~5 мс, а нажатий
/// в секунду бывает много. Для обычной проверки хватает `btn=` в периодическом
/// логе `nes/mod.rs` — это OR по окну в 10 кадров.
const LOG_CHANGES: bool = false;

/// Настроить пины кнопок: вход + подтяжка вверх. Зовётся один раз до старта
/// эмуляции.
pub fn init() {
  for (pin, _) in BUTTONS {
    pin.set_func(Func::Input);
    pin.set_pull(Pull::Up);
  }

  // Отладка пайки: печатаем, что реально легло в регистры.
  //
  // Ожидаем cfg=0xf0006611 — по 4 бита на пин в PE_CFG0:
  //   PE0=1 (out, DCX), PE1=1 (out, RST), PE2=6, PE3=6 (UART0),
  //   PE4=PE5=PE6=0 (Input), PE7=0xF (IO disable, дефолт).
  // Ожидаем pull=0x1500 — по 2 бита на пин: PE4/PE5/PE6 = 01 (pull-up).
  // dat — уровни всех пинов порта E: биты 4,5,6 должны быть в 1, пока
  // кнопки отпущены.
  println!(
    "input: cfg=0x{:08x} pull=0x{:08x} dat=0x{:08x}",
    PE4.read_cfg(),
    PE4.read_pull(),
    PE4.read_dat()
  );
}

/// Отметить, что прошёл кадр, и снять состояние кнопок. Зовётся из главного
/// цикла ровно один раз на кадр.
pub fn tick_frame() {
  let f = FRAME.fetch_add(1, Ordering::Relaxed) + 1;

  let mut s = 0u8;
  for (pin, mask) in BUTTONS {
    if pin.is_low() {
      s |= mask;
    }
  }
  if f >= START_AT && f < START_AT + START_LEN {
    s |= stdctl::START;
  }

  let prev = STATE.swap(s, Ordering::Relaxed);
  if LOG_CHANGES && s != prev {
    println!(
      "input: frame {} btn 0x{:02x} -> 0x{:02x} (dat=0x{:08x})",
      f,
      prev,
      s,
      PE4.read_dat()
    );
  }
  SEEN.fetch_or(s, Ordering::Relaxed);
}

/// Забрать и обнулить набор замеченных кнопок (для лога).
pub fn take_seen() -> u8 {
  SEEN.swap(0, Ordering::Relaxed)
}

/// Опрос кнопок для `runes`. Отдаёт то, что снял `tick_frame()`.
pub struct Buttons;

impl InputPoller for Buttons {
  #[inline(always)]
  fn poll(&self) -> u8 {
    STATE.load(Ordering::Relaxed)
  }
}

/// Заглушка «все кнопки отпущены». Оставлена для сравнения.
#[allow(dead_code)]
pub struct NoInput;

impl InputPoller for NoInput {
  #[inline(always)]
  fn poll(&self) -> u8 {
    0
  }
}
