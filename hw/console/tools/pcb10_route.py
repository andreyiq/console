class Grid:
    """Занятость клеток на двух слоях, в двух уровнях.

    `own[L][k]`: 0 свободно, >0 — клетка принадлежит одной цепи, −1 — на неё
    претендуют две и более, значит закрыта для всех. Слой 0 — лицо, 1 —
    изнанка.

    Тонкость, из-за которой первая версия провалила почти всё: раздутие на
    зазор нельзя считать глухой стеной. Зазор вокруг площадки — это место, куда
    **своей** цепи ходить можно, а чужой нельзя. Пока раздутие блокировало всё
    подряд, дорожка не могла выйти даже из собственной площадки.

    Уровней два, и это не запас, а разная геометрия:

    * `own` — расстояние ровно по правилу (`d`). Годится для ПРЯМОГО шага:
      дорожка, идущая вдоль препятствия на расстоянии `d`, соблюдает `d` на
      всей длине, никакого провиса нет.
    * `diag` — расстояние с поправкой на провис (`axis_clear(d)`). Нужно для
      ДИАГОНАЛЬНОГО шага: у выпуклого угла отрезок между двумя клетками
      проходит ближе к углу, чем любая из них.

    Одним уровнем это не выражается, и попытка обошлась дорого. Поправка
    стояла на все клетки сразу — тогда полоса между двумя соседними линиями
    шины, ровно 0.4 мм, объявлялась непроходимой, хотя прямой шаг по ней
    законен. А из таких полос состоит весь веер из-под F133: замер на пустой
    плате, где мешать некому, давал 25 связей шины из 36, и все одиннадцать
    неудач упирались в конец собственного луча.
    """

    def __init__(self):
        self.own = [[0] * (NX * NY), [0] * (NX * NY)]
        self.diag = [[0] * (NX * NY), [0] * (NX * NY)]
        # Куда заклёпку ставить нельзя из-за уже стоящей рядом. Правило не про
        # медь, а про СВЕРЛО: между кромками отверстий нужно 0.2495 мм
        # (console.kicad_dru), сверло 0.4 — значит между центрами 0.65. Своей
        # цепи это не прощается тоже: две заклёпки `+1V8` встали в 0.6 друг от
        # друга, и DRC назвал это `hole_to_hole`. Раньше здесь стоял только
        # счётчик «ближе миллиметра» — он честно печатал 1 и ничего не менял.
        self.nohole = bytearray(NX * NY)
        # Реальная медь каждой цепи — площадки и уже проложенные дорожки.
        # Ветка цепи должна стартовать от НЕЁ, а не от ближайшей площадки:
        # иначе питание с 38 площадками растёт змеёй через полплаты вместо
        # аккуратного дерева. Это как раз тот случай, когда одна дорожка,
        # проложенная не оттуда, перекрывает коридор десятку соседей.
        self.copper = {}

    def idx(self, i, j):
        return i * NY + j

    def wall(self, i, j, layer=None):
        for L in ((0, 1) if layer is None else (layer,)):
            self.own[L][self.idx(i, j)] = -1
            self.diag[L][self.idx(i, j)] = -1

    def _mark(self, o, k, net):
        if o[k] == 0:
            o[k] = net
        elif o[k] != net:
            o[k] = -1

    def fill_near(self, x, y, net, layer, d, sag=False):
        """Занять клетки ближе `d` миллиметров к точке `(x, y)`.

        Отличается от `fill_box` тем, что меряет по НАСТОЯЩИМ координатам, а не
        по номеру клетки. Это нужно там, где медь стоит не по узлам сетки:
        площадки разъёма шлейфа идут с шагом 0.5 при шаге сетки 0.2.

        Округлять такую медь к узлу нельзя — модель ошибётся на полшага в свою
        пользу. Но и закрывать «на клетку больше» тоже нельзя, и это оказалось
        дороже: лишняя клетка требует 0.6 мм между осями, а соседние лучи
        разъёма стоят в 0.5, и гребёнка целиком превращалась в стену. Шина
        проходила одной линией из шестнадцати.

        Расстояние в миллиметрах даёт ровно правило и ни клеткой больше.

        `d` — правило для прямого шага. Поправку на провис (`sag`) сюда НЕ
        передаём, и это не забывчивость: препятствие здесь — дорожка, то есть
        линия, а провис появляется у ВЫПУКЛОГО УГЛА. Две дорожки, идущие
        рядом в 0.4 мм, соблюдают 0.4 на всей длине под любым углом шага.
        Поправка нужна углу площадки — там её и ставим (`fill_rect_near`).

        Замерено, вся плата, три прохода: поправка и на дорожки тоже — 189
        связей, поправка только на площадки — 191. DRC по зазорам чист в обоих
        случаях, то есть на дорожках поправка защищала от того, чего не бывает.
        """
        i0, j0 = to_cell(x, y)
        ac = axis_clear(d) if sag else d
        r = int(math.ceil(ac / STEP))
        ac2 = ac * ac
        d2 = ac2 if ONE_LEVEL else d * d
        for L in ((0, 1) if layer is None else (layer,)):
            o, g = self.own[L], self.diag[L]
            for i in range(max(0, i0 - r), min(NX, i0 + r + 1)):
                ddx = (i * STEP - x) ** 2
                for j in range(max(0, j0 - r), min(NY, j0 + r + 1)):
                    q = ddx + (j * STEP - y) ** 2
                    if q >= ac2:
                        continue
                    k = self.idx(i, j)
                    self._mark(g, k, net)
                    if q < d2:
                        self._mark(o, k, net)

    def fill_rect_near(self, x1, y1, x2, y2, net, layer, d):
        """Занять клетки ближе `d` миллиметров к прямоугольнику площадки.

        То же лекарство, что `fill_near` для дорожек, и по той же причине.
        Раздутие по числу клеток врёт в свою пользу: правило требует зазор
        0.2 плюс полдорожки 0.1, то есть 0.3 мм, а клетка 0.2 — округляется до
        двух клеток, 0.4. Лишняя десятая с каждой стороны, две десятых на
        щель. Ровно на этом закрывался проход между площадкой `C10` и
        площадкой розетки USB: настоящий просвет 0.9 мм, дорожке нужно 0.6,
        а модель требовала 1.1 — и `VBUS` не выходил из розетки вовсе.

        Как и `fill_near`, заполняет оба уровня: `d` для прямого шага,
        `axis_clear(d)` для диагонального.
        """
        ac = axis_clear(d)
        i1, j1 = to_cell(x1 - ac, y1 - ac)
        i2, j2 = to_cell(x2 + ac, y2 + ac)
        ac2 = ac * ac
        d2 = ac2 if ONE_LEVEL else d * d
        for L in ((0, 1) if layer is None else (layer,)):
            o, g = self.own[L], self.diag[L]
            for i in range(max(0, i1), min(NX, i2 + 1)):
                x = i * STEP
                dx = max(x1 - x, x - x2, 0.0)
                dx *= dx
                for j in range(max(0, j1), min(NY, j2 + 1)):
                    y = j * STEP
                    dy = max(y1 - y, y - y2, 0.0)
                    q = dx + dy * dy
                    if q >= ac2:
                        continue
                    k = self.idx(i, j)
                    self._mark(g, k, net)
                    if q < d2:
                        self._mark(o, k, net)

    def fill_box(self, x1, y1, x2, y2, net, layer=None, pad=PAD):
        """Занять клетки по НОМЕРУ клетки — для переходных: они круглые и стоят
        по узлам сетки, мерить их в миллиметрах смысла нет. Оба уровня одинаково:
        заклёпка препятствие грубое, экономить на её краю нечего."""
        i1, j1 = to_cell(x1, y1)
        i2, j2 = to_cell(x2, y2)
        for L in ((0, 1) if layer is None else (layer,)):
            o, g = self.own[L], self.diag[L]
            for i in range(max(0, i1 - pad), min(NX, i2 + pad + 1)):
                for j in range(max(0, j1 - pad), min(NY, j2 + pad + 1)):
                    k = self.idx(i, j)
                    self._mark(o, k, net)
                    self._mark(g, k, net)

    def add_copper(self, i, j, L, net):
        self.copper.setdefault(net, set()).add((i, j, L))

    def free(self, i, j, L, net):
        """Можно ли встать в клетку и уйти из неё ПРЯМЫМ шагом."""
        if not (0 <= i < NX and 0 <= j < NY):
            return False
        o = self.own[L][self.idx(i, j)]
        return o == 0 or o == net

    def free_diag(self, i, j, L, net):
        """Можно ли пройти через клетку ДИАГОНАЛЬНЫМ отрезком."""
        if not (0 <= i < NX and 0 <= j < NY):
            return False
        o = self.diag[L][self.idx(i, j)]
        return o == 0 or o == net

    def add_hole(self, x, y):
        """Запретить заклёпки вокруг отверстия в `(x, y)` — по кромкам свёрел."""
        i0, j0 = to_cell(x, y)
        r = int(math.ceil(HOLE / STEP))
        for i in range(max(0, i0 - r), min(NX, i0 + r + 1)):
            dx = (i * STEP - x) ** 2
            for j in range(max(0, j0 - r), min(NY, j0 + r + 1)):
                if dx + (j * STEP - y) ** 2 < HOLE * HOLE:
                    self.nohole[self.idx(i, j)] = 1

    def can_via(self, i, j, net):
        """Переходная занимает обе стороны и шире дорожки."""
        if self.nohole[self.idx(i, j)]:
            return False
        for L in (0, 1):
            o = self.own[L]
            for di in range(-VIA_PAD_CELLS, VIA_PAD_CELLS + 1):
                for dj in range(-VIA_PAD_CELLS, VIA_PAD_CELLS + 1):
                    ii, jj = i + di, j + dj
                    if not (0 <= ii < NX and 0 <= jj < NY):
                        return False
                    v = o[self.idx(ii, jj)]
                    if v != 0 and v != net:
                        return False
        return True


def pad_box(p):
    """Настоящий габарит площадки, без запаса.

    Запас в полклетки здесь был, и он был нужен: `to_cell` округляет края к
    ближайшему узлу и мог срезать до половины шага, то есть дорожка ложилась в
    0.175 от чужой площадки при правиле 0.2. Полклетки убирали округление в
    безопасную сторону.

    Теперь округления нет вовсе: `fill_rect_near` меряет расстояние от клетки
    до самого прямоугольника, в миллиметрах. Запас стал не страховкой, а
    ошибкой — он складывался с округлением зазора и съедал по 0.2 мм с каждой
    щели.
    """
    bb = p.GetBoundingBox()
    return (pcbnew.ToMM(bb.GetLeft()) - OX,
            pcbnew.ToMM(bb.GetTop()) - OY,
            pcbnew.ToMM(bb.GetRight()) - OX,
            pcbnew.ToMM(bb.GetBottom()) - OY)


def build(board, pads, vias, keepouts, wires=(), tips=()):
    g = Grid()
    # поле за контуром платы
    for i in range(NX):
        for j in range(NY):
            x, y = to_mm(i, j)
            if not (EDGE < x < BOARD_W - EDGE and EDGE < y < BOARD_H - EDGE):
                g.wall(i, j)
    for code, box in pads:
        if code:
            i1, j1 = to_cell(box[0], box[1])
            i2, j2 = to_cell(box[2], box[3])
            for i in range(max(0, i1), min(NX, i2 + 1)):
                for j in range(max(0, j1), min(NY, j2 + 1)):
                    g.add_copper(i, j, 0, code)
        if code == 0:
            # Площадка без цепи — это механика: неметаллизированные отверстия
            # движка, крепёж, установочные штыри. Ноль в модели означает
            # «свободно», поэтому такие площадки надо ставить стеной явно,
            # иначе дорожка проходит прямо сквозь отверстие.
            i1, j1 = to_cell(box[0], box[1])
            i2, j2 = to_cell(box[2], box[3])
            for i in range(max(0, i1 - PAD), min(NX, i2 + PAD + 1)):
                for j in range(max(0, j1 - PAD), min(NY, j2 + PAD + 1)):
                    g.wall(i, j)
        else:
            # Раздутие площадки — ровно по правилу, в миллиметрах: зазор плюс
            # полдорожки. Через число клеток это округлялось вверх и врало.
            g.fill_rect_near(*box, code, None, CLEAR + TRACK / 2)
    for x1, y1, x2, y2 in keepouts:
        # Зоны запрета живут внутри футпринтов — у `J401` это «No conductive
        # traces» из каталога Hirose, стр. 3, под механикой лотка. Закрываем
        # наглухо: там нельзя вести медь никакой цепи.
        i1, j1 = to_cell(x1, y1)
        i2, j2 = to_cell(x2, y2)
        for i in range(max(0, i1 - PAD), min(NX, i2 + PAD + 1)):
            for j in range(max(0, j1 - PAD), min(NY, j2 + PAD + 1)):
                g.wall(i, j)
    for code, x, y in vias:
        r = 0.45          # переходная 0.9, см. pcb06_planes.py
        g.fill_box(x - r, y - r, x + r, y + r, code)
        g.add_hole(x, y)
    for code, x1, y1, x2, y2, L, w in wires:
        # Чужая медь, уже лежащая на плате: лучи из-под F133 и то, что развёл
        # freerouting. Идём по отрезку с шагом в клетку — габаритный
        # прямоугольник у косой дорожки захватывает вчетверо больше места.
        # Шаг обхода — ПОЛКЛЕТКИ, а не клетка. Ровно клетка кажется достаточной
        # и не является: `to_cell` округляет, и при шаге чуть больше клетки
        # очередной узел перепрыгивается. Луч `LCD-DB9` идёт от 88.45 до 90.38,
        # это 1.93 мм, `int(1.93 / 0.2)` даёт 9 шагов по 0.2144 — и клетка
        # x = 89.2 не помечается ничем. Клетка спорная (её просят соседние
        # лучи в 0.4 мм), значит остаётся стеной, и стена эта режет луч
        # пополам: конец луча оказывается ОТДЕЛЬНЫМ куском меди, до которого
        # «нет пути». Половина неудач шины дисплея — ровно это.
        n = max(1, int(math.ceil(math.dist((x1, y1), (x2, y2)) / (STEP / 2))))
        # Луч веера начинается на площадке, а площадки стоят где угодно, не по
        # узлам сетки: у разъёма шлейфа они идут с шагом 0.5 при шаге сетки
        # 0.2. Округлять к ближайшему узлу нельзя — модель ошибётся на полшага
        # в свою пользу, и дорожка ляжет в 0.1…0.18 мм от луча при правиле 0.2
        # (восемь нарушений зазора на плате, и в каждом одна из двух дорожек —
        # луч с дробной координатой).
        #
        # Поэтому чужую медь занимаем по НАСТОЯЩЕМУ расстоянию, а не по числу
        # клеток: `fill_near`. Там же записано, почему «на клетку больше» —
        # неверное лекарство.
        d = w / 2 + CLEAR + TRACK / 2
        for k in range(n + 1):
            x = x1 + (x2 - x1) * k / n
            y = y1 + (y2 - y1) * k / n
            g.fill_near(x, y, code, L, d)
            g.add_copper(*to_cell(x, y), L, code)

    # ВТОРОЙ ПРОХОД: клетку, где своя медь лежит НА САМОМ ДЕЛЕ, возвращаем её
    # цепи. Без этого модель запирает цепь внутри её же разъёма.
    #
    # Причина такая. `fill_box` пишет в клетку -1, если за неё спорят две
    # цепи, а -1 непроходимо для всех, включая ту, чья медь там лежит. Пока
    # площадки редкие, спорят только поля зазоров, и это правильно. У
    # реверсивной розетки USB-C шаг площадок 0.25 мм, зазор требует 0.4 — и
    # раздутия всех шестнадцати площадок перекрывают друг друга. Разъём
    # целиком становился стеной: `VBUS` не кладёт НИ ОДНОГО отрезка даже в
    # одиночку на пустой плате, восемь связей из девяти «нет пути».
    #
    # Порядок важен: сперва зазоры (они спорные), потом медь (она факт).
    # Клетка своей меди свободна для своей цепи и закрыта для чужих — ровно
    # то, что есть на плате.
    for L in (0, 1):
        o, dg = g.own[L], g.diag[L]
        for code, cells in g.copper.items():
            for i, j, cl in cells:
                if cl == L:
                    o[g.idx(i, j)] = code
                    dg[g.idx(i, j)] = code

    # ТРЕТИЙ ПРОХОД: коридор выхода перед концом каждого луча — см. `ESCAPE`.
    # Забираем только ничьё и спорное; чужую настоящую медь не трогаем, иначе
    # модель начнёт врать в свою пользу ровно там, где мы её только починили.
    for code, tx, ty, di, dj in tips:
        i0, j0 = to_cell(tx, ty)
        for k in range(1, ESCAPE + 1):
            i, j = i0 + di * k, j0 + dj * k
            if not (0 <= i < NX and 0 <= j < NY):
                break
            n = g.own[0][g.idx(i, j)]
            if n > 0 and n != code:
                break
            g.own[0][g.idx(i, j)] = code
            g.diag[0][g.idx(i, j)] = code
    return g


def components(edge_list):
    """Связные куски меди цепи: клетка -> корень, и корень -> клетки.

    Обычное объединение-поиск по рёбрам «конец дорожки — конец дорожки» и
    «лицо — изнанка в точке переходной». Нужно оно ровно затем, чтобы не
    принять два отдельных куска одной цепи за соединённое целое.
    """
    root = {}

    def find(a):
        root.setdefault(a, a)
        while root[a] != a:
            root[a] = root[root[a]]
            a = root[a]
        return a

    for a, b in edge_list:
        ra, rb = find(a), find(b)
        if ra != rb:
            root[ra] = rb
    out = {}
    for cell in list(root):
        out.setdefault(find(cell), set()).add(cell)
    return {c: find(c) for c in root}, out


def route(g, starts, goals, net, margin=60, toll=()):
    """A* от множества стартов к множеству целей. Возвращает путь `(i, j, слой)`.

    Поиск ограничен прямоугольником вокруг концов, раздутым на `margin` клеток.
    Без ограничения волна расходится по всей плате, и одна длинная связь
    считается дольше, чем вся остальная разводка вместе взятая. А обход в
    двенадцать миллиметров — это уже не «обошёл препятствие», это «пути нет».

    `toll` — чужие коридоры в клетках, `(i1, j1, i2, j2)`. Платится один раз,
    на входе, а не за каждую клетку внутри: нам всё равно, сколько цепь пройдёт
    по чужому коридору, важно только, что она его пересекла.

    Причину неудачи кладём в `route.why`. Разница существенная: «волна дошла
    до края и пути нет» лечится размещением, «кончился бюджет» — числом в
    настройке, и путать их значит чинить не то.
    """
    goal = set(goals)
    route.why = "нет пути"
    if not starts or not goal:
        return None
    xs = [c[0] for c in list(starts) + list(goals)]
    ys = [c[1] for c in list(starts) + list(goals)]
    lo_i, hi_i = min(xs) - margin, max(xs) + margin
    lo_j, hi_j = min(ys) - margin, max(ys) + margin
    gx = sum(i for i, _ in goals) / len(goals)
    gy = sum(j for _, j in goals) / len(goals)

    def h(i, j):
        dx, dy = abs(i - gx), abs(j - gy)
        return (dx + dy) + (1.4142 - 2) * min(dx, dy)

    def inside(i, j):
        return any(a <= i <= c and b <= j <= d for a, b, c, d in toll)

    # Направление входа в состояние НЕ входит: с ним одна и та же клетка
    # снимается до девяти раз, и `can_via` — самая дорогая проверка поиска —
    # считается для неё столько же раз. Штраф за поворот при этом никуда не
    # делся, он остался в стоимости. Померено: втрое быстрее и чуть лучший
    # результат.
    best, heap, seen, via_ok = {}, [], {}, {}
    for c in starts:
        i, j, L = c if len(c) == 3 else (c[0], c[1], 0)
        best[(i, j, L)] = 0.0
        heapq.heappush(heap, (h(i, j), 0.0, (i, j, L), -1, None))
    budget = NODE_BUDGET
    while heap:
        budget -= 1
        if budget < 0:
            route.why = "кончился бюджет"
            return None
        _, cost, cur, d, parent = heapq.heappop(heap)
        if cur in seen:
            continue
        seen[cur] = parent
        i, j, L = cur
        if (i, j) in goal and L == 0:
            path, key = [], cur
            while key is not None:
                path.append(key)
                key = seen[key]
            return path[::-1]
        for k, (di, dj, w) in enumerate(DIRS):
            ni, nj = i + di, j + dj
            if not (lo_i <= ni <= hi_i and lo_j <= nj <= hi_j):
                continue
            if not g.free(ni, nj, L, net):
                continue
            # Диагональный отрезок провисает к препятствию, прямой нет. Спрос
            # разный, поэтому и уровень занятости разный, и спрашиваем оба
            # конца отрезка: провис посередине зависит от обоих.
            if di and dj and not (g.free_diag(ni, nj, L, net)
                                  and g.free_diag(i, j, L, net)):
                continue
            nc = cost + w * (BACK_COST if L else 1.0) + (TURN if d != -1 and k != d else 0.0)
            if toll and inside(ni, nj) and not inside(i, j):
                nc += TOLL
            key = (ni, nj, L)
            if key in best and best[key] <= nc:
                continue
            best[key] = nc
            heapq.heappush(heap, (nc + h(ni, nj), nc, key, k, cur))
        # перескок на другую сторону
        ok = via_ok.get((i, j))
        if ok is None:
            ok = via_ok[(i, j)] = g.can_via(i, j, net)
        if ok:
            # Переходная в чужом коридоре платит отдельно, даже если цепь уже
            # внутри и за вход заплатила: она съедает 1.1 мм поперёк, то есть
            # почти три линии шины — дороже, чем просто пройти насквозь.
            nc = cost + VIA_COST + (TOLL if toll and inside(i, j) else 0.0)
            key = (i, j, 1 - L)
            if not (key in best and best[key] <= nc):
                best[key] = nc
                heapq.heappush(heap, (nc + h(i, j), nc, key, -1, cur))
    return None


def simplify(path):
    """Сжать путь до изломов и смен слоя — иначе дорожка станет тысячей отрезков."""
    if len(path) < 3:
        return path
    out = [path[0]]
    for a, b, c in zip(path, path[1:], path[2:]):
        if a[2] != b[2] or b[2] != c[2]:
            out.append(b)
        elif (b[0] - a[0], b[1] - a[1]) != (c[0] - b[0], c[1] - b[1]):
            out.append(b)
    out.append(path[-1])
    return out


def lay_rec(out, path, width, code):
    """Записать путь в список (а не на плату): проходов несколько, кладём лучший.

    Номер цепи записывается здесь же. Пока его не было, укладка на плату
    молча не делала ничего — при том что счётчик рапортовал успех.
    """
    pts = simplify(path)
    vias = 0
    for a, b in zip(pts, pts[1:]):
        if a[2] != b[2]:
            out.append(("via", to_mm(a[0], a[1]), None, width, a[2], code))
            vias += 1
        else:
            out.append(("seg", to_mm(a[0], a[1]), to_mm(b[0], b[1]),
                        width, a[2], code))
    return vias


def lay(board, path, net, g, width=TRACK):
    """Положить путь: отрезки по слоям, переходная на каждой смене стороны."""
    pts = simplify(path)
    layer_of = (pcbnew.F_Cu, pcbnew.B_Cu)
    vias = 0
    for a, b in zip(pts, pts[1:]):
        if a[2] != b[2]:
            v = pcbnew.PCB_VIA(board)
            x, y = to_mm(a[0], a[1])
            v.SetPosition(pcbnew.VECTOR2I(mm(OX + x), mm(OY + y)))
            v.SetWidth(mm(0.7))
            v.SetDrill(mm(0.4))
            v.SetNet(net)
            v.SetLayerPair(pcbnew.F_Cu, pcbnew.B_Cu)
            v.SetLocked(True)
            board.Add(v)
            g.fill_box(x, y, x, y, net.GetNetCode(), pad=VIA_PAD_CELLS)
            vias += 1
            continue
        tr = pcbnew.PCB_TRACK(board)
        x1, y1 = to_mm(a[0], a[1])
        x2, y2 = to_mm(b[0], b[1])
        tr.SetStart(pcbnew.VECTOR2I(mm(OX + x1), mm(OY + y1)))
        tr.SetEnd(pcbnew.VECTOR2I(mm(OX + x2), mm(OY + y2)))
        tr.SetWidth(mm(width))
        tr.SetLayer(layer_of[a[2]])
        tr.SetNet(net)
        board.Add(tr)
    code = net.GetNetCode()
    for i, j, L in path:
        x, y = to_mm(i, j)
        g.fill_near(x, y, code, L, width / 2 + CLEAR + TRACK / 2)
        g.add_copper(i, j, L, code)
    return vias


def main():
    board = pcbnew.LoadBoard(str(BOARD))

    # Сначала СНИМАЕМ данные, потом трогаем плату. Повторный `LoadBoard` в том
    # же процессе pcbnew не переживает — отдаёт сырой SwigPyObject, — а
    # `Remove` ломает контейнеры. Поэтому один проход: собрали, почистили,
    # разложили.
    wanted = set(sys.argv[1:])
    pads, vias, by_net, pad_at = [], [], {}, {}
    for f in board.GetFootprints():
        for p in f.Pads():
            code = p.GetNetCode()
            pads.append((code, pad_box(p)))
            name = p.GetNetname()
            if not name or name == "GND" or name.startswith("unconnected"):
                continue
            pos = p.GetPosition()
            by_net.setdefault((code, name), []).append(
                (pcbnew.ToMM(pos.x) - OX, pcbnew.ToMM(pos.y) - OY))
            pad_at[(code, round(pcbnew.ToMM(pos.x) - OX, 2),
                    round(pcbnew.ToMM(pos.y) - OY, 2))] = (code, name)
    wires, mine, edges, tips = [], [], {}, []
    for t in board.GetTracks():
        if isinstance(t, pcbnew.PCB_VIA):
            pos = t.GetPosition()
            vx = pcbnew.ToMM(pos.x) - OX
            vy = pcbnew.ToMM(pos.y) - OY
            vias.append((t.GetNetCode(), vx, vy))
            # переходная связывает стороны в одной точке
            edges.setdefault(t.GetNetCode(), []).append(
                (to_cell(vx, vy) + (0,), to_cell(vx, vy) + (1,)))
            continue
        name = t.GetNetname()
        if wanted and name in wanted and not t.IsLocked():
            mine.append(t)          # своё прежнее — снимем и проложим заново
            continue
        a, b = t.GetStart(), t.GetEnd()
        wires.append((t.GetNetCode(),
                      pcbnew.ToMM(a.x) - OX, pcbnew.ToMM(a.y) - OY,
                      pcbnew.ToMM(b.x) - OX, pcbnew.ToMM(b.y) - OY,
                      0 if t.GetLayer() == pcbnew.F_Cu else 1,
                      pcbnew.ToMM(t.GetWidth())))
        # Конец луча веера и куда он смотрит. Луч рисует `pcb07_fanout.py` от
        # центра площадки к концу и помечает `locked` — по метке и узнаём.
        # Направление берём по главной оси: `SKEW` уводит конец вбок на
        # десятые, и от этого луч слегка косой, но выходит он всё равно от
        # корпуса поперёк своей стороны.
        if t.IsLocked() and ESCAPE:
            ax, ay = pcbnew.ToMM(a.x) - OX, pcbnew.ToMM(a.y) - OY
            bx, by = pcbnew.ToMM(b.x) - OX, pcbnew.ToMM(b.y) - OY
            dx, dy = bx - ax, by - ay
            if abs(dx) >= abs(dy):
                step = (1 if dx > 0 else -1, 0)
            else:
                step = (0, 1 if dy > 0 else -1)
            tips.append((t.GetNetCode(), bx, by) + step)
        # Своя медь прошлого захода — это соединённое, но НЕ ЦЕЛИКОМ. Она
        # лежит отдельными кусками, и считать её одним блобом нельзя: у `+3V3`
        # тридцать восемь площадок, дерево собрано наполовину, а трассировщик
        # видел сплошное «уже соединено» и не делал ничего. Отсюда и
        # расхождение: он рапортовал успех, DRC показывал сорок разрывов.
        # Копим рёбра, связность считаем ниже.
        L = 0 if t.GetLayer() == pcbnew.F_Cu else 1
        edges.setdefault(t.GetNetCode(), []).append(
            (to_cell(pcbnew.ToMM(a.x) - OX, pcbnew.ToMM(a.y) - OY) + (L,),
             to_cell(pcbnew.ToMM(b.x) - OX, pcbnew.ToMM(b.y) - OY) + (L,)))

    keepouts = []
    for z in list(board.Zones()) + [z for f in board.GetFootprints()
                                    for z in f.Zones()]:
        if z.GetIsRuleArea():
            bb = z.GetBoundingBox()
            keepouts.append((pcbnew.ToMM(bb.GetLeft()) - OX,
                             pcbnew.ToMM(bb.GetTop()) - OY,
                             pcbnew.ToMM(bb.GetRight()) - OX,
                             pcbnew.ToMM(bb.GetBottom()) - OY))

    # Объекты цепей берём ДО любых правок платы. После `Remove` контейнеры
    # pcbnew портятся, и `FindNet` начинает отдавать сырой SwigPyObject —
    # прогон падал ровно на этом, уже проложив половину дорожек.
    netobj = {name: board.FindNet(name) for _, name in by_net}
    codeobj = {code: netobj[name] for code, name in by_net}

    # Целиться надо в КОНЕЦ ЛУЧА, а не в площадку. Площадки мелкого шага
    # замурованы соседями — к ним не подойти, для того лучи и выведены
    # (`pcb07_fanout.py`). Пока цель оставалась площадкой, лучи не помогали
    # вовсе: шина дисплея, пущенная первой по пустой плате, разводилась на
    # шесть связей из тридцати шести.
    moved = 0
    for code, x1, y1, x2, y2, L, w in wires:
        key = (code, round(x1, 2), round(y1, 2))
        if key not in pad_at:
            continue
        pts = by_net.get(pad_at[key])
        if pts is None:
            continue
        for i, q in enumerate(pts):
            if abs(q[0] - x1) < 0.01 and abs(q[1] - y1) < 0.01:
                pts[i] = (x2, y2)
                moved += 1
                break
    if moved:
        print(f"  целей перенесено на концы лучей: {moved}")

    for t in mine:
        board.RemoveNative(t)

    g = build(board, pads, vias, keepouts, wires, tips)

    # Порядок — от коротких цепей к длинным: у короткой связи путь чаще всего
    # единственный разумный, и уступать его длинной незачем.
    tasks = []
    for (code, name), pts in by_net.items():
        if len(pts) < 2:
            continue
        if wanted and name not in wanted:
            continue
        span = max(math.dist(a, b) for a in pts for b in pts)
        # Порядок — строго по длине связи, без предпочтения питанию. Пробовали
        # вести рельсы первыми: питанию стало лучше (29 несошедшихся связей
        # против 43), но сигналам заметно хуже, и в сумме разведённых стало
        # меньше — 104 против 119. Длинная разветвлённая рельса, проложенная
        # первой, режет плату надвое и отбирает коридоры у всех остальных.
        # Перемерено после починки модели зазоров (`PCB_POWER_FIRST=1`): 137
        # связей против 138. Вывод тот же, разрыв только стал меньше.
        tasks.append((span, code, name, pts))
    tasks.sort()

    # Проходы «неудачники идут первыми». Настоящий rip-up выдирает мешающие
    # дорожки и кладёт их иначе; здесь беднее, но по духу то же — цепь, которой
    # не хватило коридора, в следующем проходе выбирает первой.
    #
    # Считаем неудачи НАКОПИТЕЛЬНО, а не «кто провалился в прошлый раз». Флажок
    # «в прошлом проходе не сошлась» заменялся целиком, и проходы входили в
    # цикл длиной два: 169, 171, 176, 169, 176, 169, 176, 169 — с третьего
    # прохода одно и то же по кругу, восемь проходов стоят как три и дают
    # ровно то же. Счётчик так не зацикливается: цепь, проваливающаяся из
    # прохода в проход, поднимается в очереди всё выше.
    #
    # На числе связей это, впрочем, НЕ СКАЗАЛОСЬ: `PCB_LASTFAIL=1` (прежнее
    # поведение) и накопительный счёт дают одинаково 191. Оставлено потому, что
    # цикл сам по себе врёт про пользу проходов, а не потому, что помогло.
    hist = collections.Counter()
    best_state = None
    for attempt in range(PASSES):
        g = build(board, pads, vias, keepouts, wires, tips)
        laid = []
        done = fail = nvias = 0
        failed = []
        spots = []
        why = collections.Counter()
        # Три яруса: критичные, ленты, все остальные. Внутри ленты порядок —
        # по обходу, внутри остальных — по длине связи. Ярус «не хватило
        # коридора в прошлом проходе» вклинивается перед общей толпой, но
        # ленту не разрывает: пучок, положенный вразбивку, дороже любой
        # отдельной цепи, которой не повезло.
        def key(tk):
            name, span = tk[2], tk[0]
            if name in CRITICAL:
                return (0, 0, 0.0)
            if name in RANK:
                b, i = RANK[name]
                return (1, b, -i)
            if POWER_FIRST and name in POWER:
                return (2, 0, span)
            return (3, -hist[name], span)

        ordered = sorted(tasks, key=key)
        for span, code, name, pts in ordered:
            net = netobj[name]
            width = POWER_TRACK if name in POWER else TRACK
            toll = tuple(to_cell(a, b) + to_cell(c, d)
                         for a, b, c, d, who in RESERVED
                         if not name.startswith(who))
            cells = [to_cell(*q) for q in pts]
            g.copper.setdefault(code, set())
            # Соединённое ведём отдельно от «меди вообще». В меди у цепи лежат
            # все её площадки сразу, и если стартовать от неё, цель оказывается
            # достигнутой в ноль шагов: путь пустой, счётчик растёт, на плату
            # не ложится ничего. Разводка «удавалась» полностью и не давала
            # ни одной дорожки.
            # Стартуем от куска, в котором лежит первая площадка, а не от
            # всей меди цепи.
            #
            # Клетки помним ВМЕСТЕ СО СЛОЕМ. Прежде слой отбрасывался — «всё
            # равно дорожка приходит на площадку по лицу», — и это давало
            # дорожки из ниоткуда: ветка цепи прошла через клетку по изнанке,
            # клетка попала в «соединённое», и следующая ветка стартовала из
            # неё ПО ЛИЦУ, где меди нет. Отрезок ложился на плату, ни к чему
            # не присоединённый, а стартовую клетку никто не проверяет на
            # занятость — она же своя. Так `+1V8` начался в 0.2 мм от `RESET`
            # и замкнул его: два замыкания в DRC и восемь висящих концов.
            of_cell, of_root = components(edges.get(code, ()))
            def piece(cell):
                r = of_cell.get(cell + (0,)) or of_cell.get(cell + (1,))
                return set(of_root[r]) if r else {cell + (0,)}
            #
            # Растим не «от первой площадки», а лес: каждая площадка со своим
            # куском меди — отдельная группа, и мы сшиваем ближайшую пару
            # групп, пока пар не останется.
            #
            # Прежде стартовали от куска, в котором лежит площадка номер ноль,
            # и росли только оттуда. Если эта площадка окажется запертой,
            # рушится ВСЯ цепь: `own` не растёт ни на клетку, и каждая
            # следующая связь честно получает «нет пути». Так `+1V8` терял все
            # пятнадцать связей из пятнадцати — при том что один на плате он
            # разводится целиком, 15 из 15. Проверено на паре: критичные цепи
            # плюс `+1V8` — те же 15 из 15 в минус, `AVCC`+`AGND` плюс `+1V8` —
            # 27 связей и ни одной неудачи. Дело было не в тесноте.
            #
            # Заодно у сшивки пары целей не одна, а все площадки группы: путь
            # ищется до ЛЮБОЙ из них, а не до заранее назначенной.
            groups, gid = {}, 0
            for idx in range(len(pts)):
                p = piece(cells[idx])
                hit = None
                for k, (gc, _) in groups.items():
                    if (gc & p) or any(cells[idx] + (L,) in gc for L in (0, 1)):
                        hit = k
                        break
                if hit is None:
                    groups[gid] = (set(p), {idx})
                    gid += 1
                else:
                    groups[hit][0].update(p)
                    groups[hit][1].add(idx)

            need = len(pts) - 1
            joined, bad = 0, set()
            while len(groups) > 1:
                pair, dist = None, None
                keys = sorted(groups)
                for ia, a in enumerate(keys):
                    for b in keys[ia + 1:]:
                        if frozenset((a, b)) in bad:
                            continue
                        d = min(math.dist(pts[i], pts[j])
                                for i in groups[a][1] for j in groups[b][1])
                        if dist is None or d < dist:
                            pair, dist = (a, b), d
                if pair is None:
                    break
                a, b = pair
                own = groups[a][0]
                goals = [cells[i] for i in groups[b][1]]
                path = route(g, sorted(own), goals, code, margin=MARGIN,
                             toll=toll)
                if path:
                    nvias += lay_rec(laid, path, width, code)
                    prev_L = None
                    for i, j, L in path:
                        x, y = to_mm(i, j)
                        # Тем же способом, что чужая медь с платы, и это не
                        # придирка: пока свежая дорожка занимала место по числу
                        # клеток, а прочитанная с платы — по миллиметрам, одна
                        # и та же пара дорожек была законной внутри прохода и
                        # незаконной на следующем.
                        g.fill_near(x, y, code, L,
                                    width / 2 + CLEAR + TRACK / 2)
                        g.add_copper(i, j, L, code)
                        own.add((i, j, L))
                        if prev_L is not None and L != prev_L:
                            # Переходная занимает место на ОБОИХ слоях, и
                            # занимать его надо явно: пока отмечались только
                            # клетки пути, соседняя дорожка ложилась к ней
                            # вплотную — пять нарушений зазора на плату.
                            keep = 0.35 + 0.2
                            g.fill_box(x - keep, y - keep,
                                       x + keep, y + keep, code)
                            g.add_hole(x, y)
                        prev_L = L
                    own |= groups[b][0]
                    groups[a] = (own, groups[a][1] | groups[b][1])
                    del groups[b]
                    joined += 1
                else:
                    bad.add(frozenset((a, b)))
                    why[route.why] += 1
                    # Куда именно не дошли. Одного имени цепи мало: у `+3V3`
                    # тридцать восемь площадок, и «не удалось 13» не говорит
                    # ни где смотреть, ни что двигать.
                    spots.append((name, pts[min(groups[b][1])], route.why))
            # Считаем как раньше: связей у цепи `len(pts) - 1`, сшитых
            # `joined`, остальное — неудачи. Иначе числа перестанут сравниваться
            # с прежними замерами, а сравнивать их всё равно будут.
            done += joined
            fail += need - joined
            failed.extend([name] * (need - joined))
        print(f"  проход {attempt + 1}: проложено {done}, не удалось {fail} "
              f"({', '.join(f'{k} {v}' for k, v in why.most_common())}), "
              f"переходных {nvias}")
        if best_state is None or done > best_state[0]:
            best_state = (done, fail, nvias, laid, list(failed), list(spots))
        if os.environ.get("PCB_LASTFAIL"):
            hist.clear()        # прежнее поведение, для сравнения одной командой
        for n in failed:
            hist[n] += 1
        if fail == 0:
            break

    done, fail, nvias, laid, failed, spots = best_state
    # Одна и та же переходная может попасть в список дважды: две ветви цепи
    # проходят через одну клетку и каждая честно записывает переход. На плате
    # это два отверстия в одной точке — сверлить их будут дважды.
    # В том числе те, что уже стоят на плате: заходов у нас несколько подряд,
    # и каждый следующий не знает, что предыдущий уже поставил тут переходную.
    seen_via = {((round(vx, 2), round(vy, 2)), code) for code, vx, vy in vias}
    # Отбрасываем ТОЛЬКО совпадение точка в точку. Стояла ещё и проверка «или
    # ближе миллиметра» — мол, две ветви одной цепи ставят два отверстия там,
    # где хватает одного. Убрано по рассуждению, а не по замеру: путь, у
    # которого отняли переходную, не срастается с соседней — медь до неё не
    # доходит, — и обе половины остаются висеть в воздухе. Лишнее отверстие в
    # 0.4 мм от соседнего — неудобство при сверловке, оборванная связь — брак.
    #
    # Замер после правки: связей 152 -> 155, переходных столько же, и три
    # заклёпки встали ближе миллиметра друг к другу (две пары дали
    # `hole_to_hole` в DRC). Размен приемлемый, но эффект маленький — правило
    # срабатывало редко.
    #
    # Чего эта правка НЕ починила, вопреки первому предположению: 91 висящий
    # конец дорожки как был, так и остался. Проверено поимённо — 83 из них
    # лучи веера у цепей, которые не разошлись вовсе. Это не оборванные пути,
    # это выходы, к которым никто не пришёл, и лечатся они разводкой, а не
    # уборкой переходных. Оставшиеся восемь — разбирать отдельно.
    # Счётчик «ближе миллиметра» здесь стоял вместо правила и врал в обе
    # стороны: миллиметр он взял наугад, а настоящее ограничение — 0.65 между
    # центрами (сверло 0.4 плюс 0.2495 между кромками). Пары в 0.8 он объявлял
    # подозрительными, будучи законными, а пару в 0.6 — тоже «одной штукой»,
    # хотя это готовое `hole_to_hole` в DRC. Правило теперь соблюдает поиск
    # (`Grid.nohole`), и счётчик-заместитель убран: он показывал число, по
    # которому нельзя было принять ни одного решения.
    for kind, a, b, width, layer, code in laid:
        if kind == "via":
            key = ((round(a[0], 2), round(a[1], 2)), code)
            if key in seen_via:
                continue
            seen_via.add(key)
        net = codeobj[code]
        if kind == "via":
            v = pcbnew.PCB_VIA(board)
            v.SetPosition(pcbnew.VECTOR2I(mm(OX + a[0]), mm(OY + a[1])))
            v.SetWidth(mm(0.7))
            v.SetDrill(mm(0.4))
            v.SetNet(net)
            v.SetLayerPair(pcbnew.F_Cu, pcbnew.B_Cu)
            v.SetLocked(True)
            board.Add(v)
        else:
            tr = pcbnew.PCB_TRACK(board)
            tr.SetStart(pcbnew.VECTOR2I(mm(OX + a[0]), mm(OY + a[1])))
            tr.SetEnd(pcbnew.VECTOR2I(mm(OX + b[0]), mm(OY + b[1])))
            tr.SetWidth(mm(width))
            tr.SetLayer(pcbnew.F_Cu if layer == 0 else pcbnew.B_Cu)
            tr.SetNet(net)
            tr.SetLocked(True)     # наше — задание отдаёт это неприкосновенным
            board.Add(tr)

    filler = pcbnew.ZONE_FILLER(board)
    filler.Fill(board.Zones())
    board.Save(str(BOARD))
    print(f"проложено связей: {done}, не удалось: {fail}, переходных {nvias}; "
          f"отрезков на плату: {sum(1 for k, *_ in laid if k == 'seg')}")
    if failed:
        top = collections.Counter(failed).most_common(10)
        print("  не разошлись:", ", ".join(f"{k}×{v}" for k, v in top))
        # Попыток больше, чем недостающих связей, и это не противоречие: у
        # цепи из G кусков пар до G(G-1)/2, и каждая неудачная пара — своя
        # запись. Печатаем оба числа, иначе список выглядит несходящимся с
        # «не удалось».
        print(f"  мест, где не прошло: {len(spots)} попыток на {fail} связей")
        # Куда не дошли — по местам, а не только по именам. Печатаем немного:
        # лог, в котором тонет главное, равен отсутствию лога.
        n = int(os.environ.get("PCB_SPOTS", 8))
        for name, (px, py), w in spots[:n]:
            print(f"    {name:16} до ({px + OX:6.1f}, {py + OY:6.1f}) — {w}")
        if len(spots) > n:
            print(f"    …и ещё {len(spots) - n}")


