#!/usr/bin/env python3
"""Рисует блок 6 «ДИСПЛЕЙ» в hw/console/console.kicad_sch.

Запуск:  python3 hw/console/tools/block06_display.py

Скрипт идемпотентный: перед вставкой выкидывает из схемы всё, что лежит внутри
рамки блока 6, а рамку и заголовок не трогает.

Все номиналы — из hw/console/blocks/06-display.md, ссылка на раздел лежит в
поле `Источник` каждого компонента.

Раскладка. Шлейф на 40 контактов — это 99 мм столбца с шагом 2.54, и любая
деталь, поставленная прямо у контакта, упирается в соседний ряд: подпись
резистора занимает по 2.5 мм вверх и вниз, а между рядами всего 2.54. Поэтому
у разъёма стоят **только метки**, а все тринадцать деталей вынесены влево, в
свободное поле, и соединяются с разъёмом теми же глобальными метками. Это то же
решение, к которому пришёл блок 8 у выводов F133, и по той же причине.

Метки у ног самого F133 ставит блок 8 (правило из 07-clock-reset.md §6.4).

Общая машинерия — в tools/kicadsch.py.
"""

import sys

from kicadsch import Sheet, root_uuid, write

# Рамка блока 6 из tools/scaffold.py — по ней чистится старое содержимое.
FRAME = (378.0, 234.0, 574.0, 344.0)

DOC = "06-display.md"

# Разъём. Вывод n сидит в (JX - 5.08, JY - 48.26 + (n-1)*2.54), монтажная
# лапка MP — в (JX, JY + 55.88). Отсюда и выбраны JX/JY: столбец выводов
# 237.49..336.55, лапка 341.63 — всё внутри рамки 234..344 вместе с меткой
# земли на лапке, которая иначе вылезала за нижнюю границу.
JX, JY = 546.1, 285.75
PIN_X = JX - 5.08
PIN_Y0 = JY - 48.26


def py(n):
    """Ордината вывода разъёма."""
    return PIN_Y0 + (n - 1) * 2.54


# Что висит на каждом контакте шлейфа: имя цепи или None для «не подключён».
# Порядок и функции — 06-display.md §2.3, назначение цепей — §6.1.
FFC = {
    1: None, 2: None, 3: None, 4: None,        # тачскрин, §2.5 п. 4
    5: "GND",
    6: "+3V3", 7: "+3V3",                      # VCC и IOVCC, §6.2
    8: None,                                   # FMARK, §7.3
    9: "LCD-CS",
    # ВЫВОДЫ 10 И 11 — МЕСТО, ГДЕ ДОКУМЕНТ ВРАЛ. В четырёхпроводном SPI:
    #   вывод 10 — `D/C`, выбор команда/данные;
    #   вывод 11 — `SCL`, тактовый.
    # `06-display.md §2.2` утверждал обратное, и схема это унаследовала: такт
    # приходил на `D/C`, плата бы не заработала. Разобрано по схеме САМОГО
    # МОДУЛЯ от продавца (`docs/display/ili9488/3.5寸40P ，9488原理图.pdf`), где
    # против выводов стоят их функции: `DCX/RS(SPI-4)` против 10 и
    # `WRX/SPI SCL` против 11. Колонки там разъезжаются при извлечении текста,
    # поэтому сверено по проверяемым соседям: 8 `FMARK`, 12 `RDX`, 13 `SDA`,
    # 14 `SDO`, 15 `RESX`, 16 `GND`, 17 `DB0` — вся цепочка совпала со спекой.
    # Третий свидетель — рабочая пайка проводами, AGENTS.md: `SCL` на 11.
    #
    # Имена цепей взяты по ФУНКЦИИ, а не по шелкографии модуля (`LCD_RS` /
    # `LCD_WR`): имя «WR» у тактового сигнала и есть та ловушка, в которую
    # схема уже один раз попала.
    10: "LCD-DC",
    11: "LCD-SCL",
    12: "LCD-RD",
    13: "LCD-SDA",
    # `SDO` НЕ подключаем, хотя код умеет читать `read_id`. Так говорит спека
    # («If not used, open this pin», §2.3) и так говорит инструкция продавца
    # («14PIN_SDO — в воздухе»).
    #
    # Я это решение один раз переопределил — ради удобной проверки при первом
    # запуске — и оно стоило дорого: `SPI0-MISO` стала ВТОРОЙ по длине цепью
    # платы, 266 мм. Причём вся эта длина — отвод на шине, которую делит
    # ЗАГРУЗОЧНАЯ флешка. Если `SDO` дисплея не уходит в высокий импеданс при
    # снятом `CS` (у контроллеров ILI это известная болезнь, и спека молчит),
    # флешка не прочитается и плата не загрузится вовсе. Менять «читается ли
    # дисплей» на «загружается ли плата» нельзя.
    14: None,
    15: "LCD-RST",
    16: "GND",
    33: "LCD-LEDA",
    34: "LCD-LEDK", 35: "LCD-LEDK", 36: "LCD-LEDK",
    37: "GND",
    38: "LCD-IM", 39: "+3V3", 40: "LCD-IM",    # IM0 / IM1 / IM2, §2.4
    "MP": "GND",                               # монтажная лапка, §6.10
}
# Шина данных `DB0`…`DB15` — НА ЗЕМЛЮ, все шестнадцать. Панель это прямо
# требует: «Fix to GND level when not in use» (§2.3), и схема модуля от
# продавца повторяет — «25-32PIN_DB8-15接GND».
#
# Почему сняли параллельный интерфейс. Он нужен ради скорости, но кадр равен
# `max(эмуляция, передача)`, а замер на железе (AGENTS.md) даёт эмуляцию 29 мс
# против ожидания передачи 2 мс. Убрать передачу совсем — 38 кадров в секунду
# вместо нынешних 33. То есть шина 8080 стоила бы самой тяжёлой задачи на
# плате (23 линии через просвет 9 × 11 мм, из 36 связей проходило 23…25 даже
# на пустой плате) ради пяти кадров, которых сегодня всё равно не получить.
#
# Платим за это тем, что на ЭТОЙ ревизии параллельный режим закрыт насовсем:
# `DB` сидят на земле, обратно только резать дорожки. Разбор порядка бит для
# параллельной шины (он был нетривиален — порядок обхода, а не длина) остаётся
# в `06-display.md §2.8` на случай, если к ней вернутся.
#
# На плате это не дорожки: площадки разъёма лежат на лице, где залита земля,
# и соединяются с ней заливкой.
FFC.update({pin: "GND" for pin in range(17, 33)})                # §2.3, §7.9.3


def connector(s):
    """Разъём с метками на каждом контакте.

    Корпус свой, не штатный. Геометрия побайтово из
    `Connector_FFC-FPC:Hirose_FH12-40S-0.5SH_1x40-1MP_P0.50mm_Horizontal`,
    переставлены только номера площадок: площадка N — это контакт 41−N
    настоящего Hirose. Так сделано потому, что хвост панели заворачивается на
    180° ей на изнанку и приходит к разъёму в обратном порядке; разбор и
    расчёт поворотов — §7.2. Благодаря этому на схеме вывод N разъёма
    остаётся выводом N панели, и схему можно читать рядом с её спекой.
    """
    s.sym("Connector_Generic_MountingPin:Conn_01x40_MountingPin", "J601",
          "FFC-40 0.5mm", JX, JY, 0, src=f"{DOC} §6.1, §7.2", lcsc="C202114",
          fp="console:FH12-40S-0.5SH_ContactsReversed",
          # подписи справа от корпуса разъёма и ниже рамки: при -52 «J601»
          # вылезала на пунктир верхней границы блока
          rdx=3.81, rdy=-49.53, vdx=3.81, vdy=-46.99)

    for n in range(1, 41):
        net = FFC[n]
        if net is None:
            s.no_connect((PIN_X, py(n)))
        else:
            s.glabel(net, (PIN_X, py(n)), 180)

    # Монтажная лапка: провод влево и метка, вправо и вниз места уже нет.
    mp = (JX, JY + 55.88)
    s.wire(mp, (mp[0] - 12.7, mp[1]))
    s.glabel(FFC["MP"], (mp[0] - 12.7, mp[1]), 180)


def series(s):
    """Последовательные резисторы: метка — резистор — метка (§6.4).

    Слева цепь со стороны F133, справа — со стороны шлейфа.

    Раньше эти три резистора были перемычками выбора режима: ими решалось,
    придёт на вывод 10 такт (SPI) или `LCD0-DE` (параллельный). Режим теперь
    один, и резисторы делают то, ради чего их обычно и ставят, — гасят звон на
    трёх БЫСТРЫХ линиях, уходящих в шлейф. `D/C` через резистор не ведём: он
    переключается раз на команду, звенеть там нечему.

    Дисплей сидит на SPI1, а не на SPI0. Причину видно только на плате:
    разъём шлейфа слева от чипа, и SPI1 (`PD11`/`PD12`) выходит именно на эту
    сторону корпуса, тогда как SPI0 (`PC2`/`PC4`) — на противоположную. Через
    SPI0 те же два сигнала обходили чип кругом и тащили за собой переходные;
    через SPI1 идут прямо. Разбор и замеры — `block08_decoupling.py`, у `PD`.

    Заодно шину больше не делим: раньше `SDA`/`SCL` были общие с флешкой и
    шлейф висел на них отводом, а резистор гасил отражение от конца отвода.
    Теперь у шлейфа своя шина, и резистор просто гасит звон на своей линии.
    """
    # Шаг рядов 12.7, а не 10.16: подпись резистора отходит на 2.54 вверх и
    # вниз, и при меньшем шаге номинал одного ряда прижимался к ссылке соседнего
    rows = [
        (243.84, "SPI1-CLK", "R603", "LCD-SCL", "§6.4"),
        (256.54, "SPI1-MOSI", "R604", "LCD-SDA", "§6.4"),
        # Третьего резистора нет: он стоял на `SDO`, а `SDO` не подключён.
        # Оставлять его «на всякий случай» не стали — деталь без цепи это
        # лишняя строка в спецификации и лишняя пайка.
    ]
    # координаты кратны 1.27: иначе ERC ловит вывод резистора «не на сетке»
    x_lab_l, x_r, x_lab_r = 401.32, 424.18, 447.04
    for y, left, ref, right, sec in rows:
        s.wire((x_lab_l, y), (x_r - 3.81, y))
        s.sym("Device:R", ref, "33", x_r, y, 90, src=f"{DOC} {sec}",
              rdx=0.0, rdy=-2.54, vdx=0.0, vdy=2.54, just=None)
        s.wire((x_r + 3.81, y), (x_lab_r, y))
        s.glabel(left, (x_lab_l, y), 180)
        s.glabel(right, (x_lab_r, y), 0)


def pulls(s):
    """Резисторы, задающие уровень (§6.5).

    Пять одинаковых столбиков: рельса сверху, резистор, метка снизу. Шаг 25.4
    выбран по длине метки: текст идёт от метки влево примерно на 16 мм, и при
    меньшем шаге подписи соседних столбиков наезжали бы друг на друга.
    """
    cols = [
        (396.24, "power:+3V3", "R606", "LCD-RD"),
        (421.64, "power:+3V3", "R607", "LCD-CS"),
        (447.04, "power:GND", "R608", "LCD-RST"),
        (472.44, "power:+3V3", "R609", "LCD-IM"),
        (497.84, "power:+3V3", "R602", "LCD-BL"),
    ]
    y_top, y_r, y_bot = 287.02, 294.64, 302.26
    for x, rail, ref, net in cols:
        # У подтяжки вниз столбик перевёрнут: символ земли рисуется остриём
        # вниз, и сверху колонки он читается как ошибка.
        down = rail.endswith("GND")
        y_rail, y_lab = (y_bot, y_top) if down else (y_top, y_bot)
        s.power(rail, (x, y_rail))
        s.wire((x, y_top), (x, y_r - 3.81))
        s.sym("Device:R", ref, "10k", x, y_r, 0, src=f"{DOC} §6.5",
              rdx=-2.54, vdx=-2.54, just="right")
        s.wire((x, y_r + 3.81), (x, y_bot))
        # Метка горизонтальная: вертикальная у KiCad растёт вверх, в резистор.
        # Текст уходит влево максимум на 16 мм, шаг столбиков 25.4 — не сходятся.
        s.glabel(net, (x, y_lab), 180)


def backlight(s):
    """Подсветка: балласт в анод, MOSFET в катоды (§6.6)."""
    # балласт: +3V3 — R601 — LCD-LEDA
    x, y = 401.32, 322.58
    s.power("power:+3V3", (x - 12.7, y))
    s.wire((x - 12.7, y), (x - 3.81, y))
    s.sym("Device:R", "R601", "0", x, y, 90, src=f"{DOC} §6.6",
          rdx=0.0, rdy=-3.81, vdx=0.0, vdy=3.81, just=None)
    s.wire((x + 3.81, y), (x + 12.7, y))
    s.glabel("LCD-LEDA", (x + 12.7, y), 0)

    # ключ: сток — катоды, затвор — LCD-BL, исток — земля
    qx, qy = 462.28, 322.58
    # AO3400A: логический уровень, 30 В, 5.7 А — на наши 75 мА и затвор от
    # 3.3 В запас чудовищный, зато деталь везде есть. Распиновка SOT-23 у неё
    # G-S-D, ровно как у символа `Q_NMOS_GSD`.
    q = s.sym("Transistor_FET:Q_NMOS_GSD", "Q601", "AO3400A", qx, qy, 0,
              src=f"{DOC} §6.6, §7.1", fp="Package_TO_SOT_SMD:SOT-23",
              rdx=6.35, rdy=-2.54, vdx=6.35, vdy=0.0)
    s.wire(q.pin("3"), (qx + 2.54, qy - 12.7))
    s.glabel("LCD-LEDK", (qx + 2.54, qy - 12.7), 0)
    s.wire(q.pin("1"), (qx - 12.7, qy))
    s.glabel("LCD-BL", (qx - 12.7, qy), 180)
    s.wire(q.pin("2"), (qx + 2.54, qy + 10.16))
    s.power("power:GND", (qx + 2.54, qy + 10.16))


def caps(s):
    """Развязка питания панели у разъёма (§6.2).

    Стоят правее ключа и ниже столбиков подтяжек: у тех метка вертикальная и
    текст уходит вниз примерно на 13 мм, так что 302 + 13 = 315 — это занято.
    """
    for ref, val, x in (("C601", "0.1u", 500.38), ("C602", "10u", 513.08)):
        y = 330.2
        s.power("power:+3V3", (x, y - 7.62))
        s.wire((x, y - 7.62), (x, y - 3.81))
        s.sym("Device:C", ref, val, x, y, 0, src=f"{DOC} §6.2",
              rdx=-2.54, vdx=-2.54, just="right")
        s.wire((x, y + 3.81), (x, y + 7.62))
        s.power("power:GND", (x, y + 7.62))


def notes(s):
    s.note("контакты 1..4 — тачскрин, 8 FMARK, 14 SDO: спека велит "
           "оставить в воздухе", (382.0, 240.0))
    s.note("детали вынесены из столбца разъёма: шаг контактов 2.54, "
           "подписи не помещаются", (382.0, 279.4))


def main():
    s = Sheet(root_uuid(), 6, FRAME)
    connector(s)
    series(s)
    pulls(s)
    backlight(s)
    caps(s)
    notes(s)
    write(s)
    return 0


if __name__ == "__main__":
    sys.exit(main())
