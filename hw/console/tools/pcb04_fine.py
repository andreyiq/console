#!/usr/bin/env python3
"""Точное размещение там, где документы блоков требуют конкретного соседства.

`pcb03_blocks.py` раскладывает блок ровными рядами в зоне — этого достаточно,
чтобы разобрать кучу, но недостаточно там, где место детали задано физикой:
конденсатор развязки принадлежит **конкретному выводу**, `CIN` обязан стоять
между `IN` и `GND` своего бака, делитель `FB` — подальше от `LX`.

Что делает этот скрипт:

| | откуда требование |
|---|---|
| 27 конденсаторов развязки кольцом вокруг F133, каждый у своего вывода | 08-decoupling.md §6.2, §6.3, §6.4 |
| три бака: `CIN` у `IN`, дроссель у `LX`, `COUT` за дросселем, делитель на стороне `FB` | даташит SY8089 §2.4 Layout Design пп. 1–4, через 02-power.md §6.1 |
| кварцы вплотную к своим выводам, нагрузочные конденсаторы у кварца | 07-clock-reset.md §6.1 |
| `CC`-резисторы и `USBLC6` у самой розетки | 03-usb.md §6.2 |

Скрипт двигает только перечисленное поимённо и блокирует поставленное, чтобы
`pcb03` его больше не трогал. Запускать после `pcb03_blocks.py`.
"""
import itertools
import math
import os
from pathlib import Path

import pcbnew

ROOT = Path(__file__).resolve().parent.parent
BOARD = ROOT / "console.kicad_pcb"

OX, OY = 50.0, 40.0
BOARD_W, BOARD_H = 156.0, 74.0   # размер платы, от (OX, OY)
GAP = 0.6                      # просвет между courtyard соседей
# Сколько рядов допускаем в кольце развязки. Прежде стояло 2, и третий ряд был
# запрещён из соображения «дальше от вывода — хуже развязка». Соображение
# верное, но запрет решал не ту задачу: при двух рядах деталь, которой не
# хватило места, уезжала ВДОЛЬ бока на те же десять миллиметров — то есть
# дальше от вывода, чем третий ряд. Выбор теперь делает расстояние (см. ниже),
# и лишний ряд стал не поблажкой, а просто ещё одним местом на выбор.
MAX_ROWS = int(os.environ.get("PCB_ROWS", 4))

# Ставить ли кольцо развязки на ИЗНАНКУ, как делает Xassette.
#
# Гипотеза была сильная и взята не с потолка: Xassette — тот же F133, тот же
# корпус LQFP-128 шаг 0.4, та же двуслойная плата, — и у него 10 конденсаторов
# из 26 стоят на `B.Cu`, ближайшие в 5.5…6.4 мм от центра корпуса, то есть
# прямо под чипом. У нас все 27 на лице, до вывода в среднем 8.4 мм.
#
# ПРОВЕРЕНО НА КОПИИ, и отвергнуто дважды:
#
# | что пробовали | связей | разрывов по DRC | нарушений |
# |---|---|---|---|
# | как есть, лицо | 191 | 63 | 0 |
# | изнанка, кольцо там же | 191 | **81** | 0 |
# | изнанка + под корпус (отступ −3.5) | **189** | **87** | **7, из них 2 замыкания** |
#
# Первое: земляные выводы конденсаторов перестают касаться ЛИЦЕВОЙ заливки у
# выводов чипа, и рвётся земля аналога (`AGND×5`). Второе: под корпусом уже
# стоят термопад и его сшивка, конденсаторы на них налезают — наложения
# корпусов, перемычки маски и настоящие замыкания.
#
# Развязке при этом становится лучше (средняя до вывода 8.4 -> 6.0 мм), так
# что гипотеза не глупая — она просто стоит дороже, чем даёт.
BACK = bool(os.environ.get("PCB_DECOUP_BACK"))

# Отступ кольца развязки от края площадок корпуса. Вынесен в окружение, чтобы
# цену этого миллиметра можно было померить одной константой, а не спорить о
# ней:  PCB_ROWS=4 PCB_RING=0.7 python3 pcb04_fine.py
#
# Перемерено после починки роста цепи в трассировщике. Каждая строка — полный
# прогон размещения и разводки, ряды и отступ разведены по одному:
#
# | рядов | отступ | средняя | худшая | дальше 7 мм | связей |
# |---|---|---|---|---|---|
# | 3 | 1.1 | 6.8 | 12.0 | 11 | 191 |
# | 4 | 1.1 | 7.1 | 14.8 | 11 | 193 |
# | 5 | 1.1 | 7.5 | 18.9 | 12 | 188 |
# | 3 | 0.7 | 6.3 | 11.8 |  9 | 189 |
# | 4 | 0.7 | 6.5 | 14.4 |  9 | 192 |
# | 4 | 0.5 | 6.4 | 14.2 |  9 | 187 |
#
# Ручки отвечают за разное: ОТСТУП правит развязку (ёмкостей дальше семи
# миллиметров 11 -> 9), а ЛИШНИЙ РЯД добавляет связей. Пятый ряд вредит обоим —
# место в нём дальше, чем вдоль бока.
#
# ВСЯ ЭТА ТАБЛИЦА СНЯТА В УСЛОВИЯХ, КОТОРЫХ БОЛЬШЕ НЕТ, и потому едет вместе с
# условием: тем ёмкостям, которым места не нашлось, разрешалось лечь ВНАХЛЁСТ.
# Числа верные, а плата по ним нерабочая: `C823` с `C816` садились на `J601`,
# два `courtyards_overlap`. Наложение убрано (см. ветку `force` ниже), и цена
# развязки сразу выросла — она и раньше была такой, просто половину её платил
# несобираемый вариант.
#
# После починки, тот же прогон целиком:
#
# | рядов | отступ | средняя | худшая | дальше 7 мм | связей | наложений |
# |---|---|---|---|---|---|---|
# | 3 | 1.1 | 9.1 | 25.1 | 13 |  —  | 0 |
# | 4 | 0.7 | 8.4 | 20.8 | 11 | 194 | 0 |  <- взято
#
# Средняя и худшая стали хуже, чем в таблице выше, и это осознанный размен.
# Считать надо ЧИСЛО ёмкостей, которые в самом деле развязывают: их 27 − 11 =
# 16, столько же, сколько было. Среднюю и худшую испортили те, кто и раньше
# работал индуктивностью, а не ёмкостью, — они просто уехали дальше. Взамен
# плата стала собираемой и связей стало на три больше.
RING = float(os.environ.get("PCB_RING", 0.7))

# Просвет МЕЖДУ РЯДАМИ кольца — отдельно от `GAP` между соседями в ряду.
#
# ГИПОТЕЗА БЫЛА НЕВЕРНА, и проверка это сказала однозначно. Рассуждение
# выглядело так: между рядами 0.6 мм, в них влезает ровно одна дорожка (0.2
# плюс два зазора 0.2), а рельс три — вот почему все разрывы питания стоят
# внутри кольца. Померено: просвет 0.6, 1.0 и 1.4 дают ОДИНАКОВО 147 связей,
# а развязка при этом портится (ёмкостей дальше 7 мм 11, 16 и 16). То есть
# полоса между рядами не была узким местом вовсе; рельсам мешает что-то другое.
#
# Ручку оставляю: она дешёвая и один раз уже сэкономила спор.
ROW_GAP = float(os.environ.get("PCB_ROW_GAP", 0.6))

# ------------------------------------------------------- развязка по выводам
#
# Соответствие «конденсатор — вывод F133» восстановлено из block08_decoupling.py:
