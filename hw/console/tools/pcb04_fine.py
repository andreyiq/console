#!/usr/bin/env python3
"""Точное размещение там, где документы блоков требуют конкретного соседства.

`pcb03_blocks.py` раскладывает блок ровными рядами в зоне — этого достаточно,
чтобы разобрать кучу, но недостаточно там, где место детали задано физикой:
конденсатор развязки принадлежит **конкретному выводу**, `CIN` обязан стоять
между `IN` и `GND` своего бака, делитель `FB` — подальше от `LX`.

Что делает этот скрипт:

| | откуда требование |
|---|---|
| 27 конденсаторов развязки кольцом вокруг F133, каждый у своего вывода | 08-decoupling.md §6.2, §6.3, §6.4 |
| три бака: `CIN` у `IN`, дроссель у `LX`, `COUT` за дросселем, делитель на стороне `FB` | даташит SY8089 §2.4 Layout Design пп. 1–4, через 02-power.md §6.1 |
| кварцы вплотную к своим выводам, нагрузочные конденсаторы у кварца | 07-clock-reset.md §6.1 |
| `CC`-резисторы и `USBLC6` у самой розетки | 03-usb.md §6.2 |

Скрипт двигает только перечисленное поимённо и блокирует поставленное, чтобы
`pcb03` его больше не трогал. Запускать после `pcb03_blocks.py`.
"""
import itertools
import math
import os
from pathlib import Path

import pcbnew

ROOT = Path(__file__).resolve().parent.parent
BOARD = ROOT / "console.kicad_pcb"

OX, OY = 50.0, 40.0
GAP = 0.6                      # просвет между courtyard соседей
# Сколько рядов допускаем в кольце развязки. Прежде стояло 2, и третий ряд был
# запрещён из соображения «дальше от вывода — хуже развязка». Соображение
# верное, но запрет решал не ту задачу: при двух рядах деталь, которой не
# хватило места, уезжала ВДОЛЬ бока на те же десять миллиметров — то есть
# дальше от вывода, чем третий ряд. Выбор теперь делает расстояние (см. ниже),
# и лишний ряд стал не поблажкой, а просто ещё одним местом на выбор.
MAX_ROWS = int(os.environ.get("PCB_ROWS", 3))

# Отступ кольца развязки от края площадок корпуса. Вынесен в окружение, чтобы
# цену этого миллиметра можно было померить одной командой, а не спорить о ней:
#     PCB_RING=2.5 python3 pcb04_fine.py
RING = float(os.environ.get("PCB_RING", 1.1))

# Просвет МЕЖДУ РЯДАМИ кольца — отдельно от `GAP` между соседями в ряду.
#
# ГИПОТЕЗА БЫЛА НЕВЕРНА, и проверка это сказала однозначно. Рассуждение
# выглядело так: между рядами 0.6 мм, в них влезает ровно одна дорожка (0.2
# плюс два зазора 0.2), а рельс три — вот почему все разрывы питания стоят
# внутри кольца. Померено: просвет 0.6, 1.0 и 1.4 дают ОДИНАКОВО 147 связей,
# а развязка при этом портится (ёмкостей дальше 7 мм 11, 16 и 16). То есть
# полоса между рядами не была узким местом вовсе; рельсам мешает что-то другое.
#
# Ручку оставляю: она дешёвая и один раз уже сэкономила спор.
ROW_GAP = float(os.environ.get("PCB_ROW_GAP", 0.6))

# ------------------------------------------------------- развязка по выводам
#
# Соответствие «конденсатор — вывод F133» восстановлено из block08_decoupling.py:
# там `rails()` идёт по таблице RAILS и нумерует C801… подряд, по одному
# 0.1 мкФ на вывод плюс объёмный на рельсу.
DECOUP = {
    # +3V3: объём и по выводам 34, 66, 83, 128
    "C801": "83", "C802": "34", "C803": "66", "C804": "83", "C805": "128",
    # +1V8: объём и выводы 20, 26, 48, 49, 50, 65
    "C806": "50", "C807": "20", "C808": "26", "C809": "48", "C810": "49",
    "C811": "50", "C812": "65",
    # +0V9: объём и выводы 46, 51, 81, 116, 117
    "C813": "116", "C814": "46", "C815": "51", "C816": "81", "C817": "116",
    "C818": "117",
    "C819": "29",                    # 2.2 мкФ на входе внутренних LDO
    "C820": "77",                    # VCC-TVOUT
    "C821": "28", "C822": "30",      # выходы LDOA / LDOB
    "C823": "89",                    # объём аналога
    "C824": "89", "C825": "97",      # AVCC / HPVCC
    "C826": "92", "C827": "90",      # опоры VRA1 / VRA2
}
# Объёмные ставим во внешний ряд: они не про высокочастотную развязку, а про
# запас заряда, и место у самого вывода дороже отдать керамике 0.1 мкФ.
BULK = {"C801", "C806", "C813", "C823"}

# ------------------------------------------------------------------- баки
#
# Смещения от центра SY8089, в миллиметрах. `IN` и `FB` у SOT-23-5 на одной
# стороне корпуса, `LX` и `GND` на другой — отсюда и раскладка: вход справа,
# силовой выход влево, обратная связь вниз-вправо, подальше от `LX`.
BUCKS = [
    # U,    L,    CIN,  COUT, C0.1, Rверх, Rниз, перемычка, TP,   C22p
    ("U2", "L1", "C1", "C4", "C7", "R1", "R2", "R16", "TP1", None),
    ("U3", "L2", "C2", "C5", "C8", "R3", "R4", "R17", "TP2", None),
    ("U4", "L3", "C3", "C6", "C9", "R5", "R6", "R18", "TP3", "C10"),
]
# Три канала над корпусом: на лице банк питания и USB (101…117) выходит у F133
# вверх, и рельсы приходят к нему сверху, никого не огибая.
#
# Порядок слева направо — 3.3 / 1.8 / 0.9 В, и он не случаен. Выход бака стоит
# в кластере слева (за дросселем), поэтому чем правее сам бак, тем короче путь
# его рельсы до корпуса. Ближе всех ставим 0.9 В: у него самый большой ток
# (0.6 А, 02-power.md §7.1) и самый тесный допуск — просадка 20 мВ на трёх
# вольтах это ничто, а на девяти десятых уже заметно.
BUCK_AT = [(34.0, 58.0), (61.0, 58.0), (88.0, 58.0)]
# Смещения от центра SY8089. У SOT-23-5 `EN`, `GND` и `LX` на одной стороне
# корпуса, `IN` и `FB` на другой — отсюда раскладка: вход и обратная связь
# справа, силовой выход влево. Делитель уходит вниз-вправо, то есть в сторону
# `FB` и подальше от `LX`, как требует даташит §2.4 п. 4.
BUCK_OFF = {
    "CIN":  (4.5, 0.0, 90),      # вплотную к IN
    "L":    (-4.5, 0.0, 0),      # у LX
    "COUT": (-9.0, 0.0, 90),
    "C01":  (-9.0, 4.4, 90),
    "RT":   (4.5, 4.4, 90),      # делитель — на стороне FB
    "RB":   (9.0, 4.4, 90),      # рядом, а не под ним: полоса всего 9 мм
    "JMP":  (13.5, 0.0, 90),     # 0 Ω перемычка на выходе рельсы
    "TP":   (-4.5, 4.4, 0),
    "C22":  (13.5, 4.4, 90),
}


def mm(v):
    return pcbnew.FromMM(v)


def xy(fp):
    p = fp.GetPosition()
    return pcbnew.ToMM(p.x) - OX, pcbnew.ToMM(p.y) - OY


def size(fp):
    """Габарит courtyard **при нулевом повороте**.

    Мерить как есть нельзя: скрипт сам поворачивает детали, и на втором прогоне
    у повёрнутого конденсатора ширина с высотой меняются местами. Кольцо от
    этого разъезжается и детали налезают друг на друга — так и было, пока не
    стали снимать габарит на нуле и возвращать поворот обратно.
    """
    # Кэш courtyard пересчитываем явно: после `SetPosition` KiCad помечает
    # его недействительным, но не строит заново, и `GetCourtyard()` отдаёт
    # пустой полигон. Проверка тогда молча пропускает деталь и рапортует
    # ноль — ровно так подсунутая внахлёст пара конденсаторов не нашлась.
    fp.BuildCourtyardCaches()
    was = fp.GetOrientation()
    fp.SetOrientationDegrees(0)
    lay = pcbnew.B_CrtYd if fp.IsFlipped() else pcbnew.F_CrtYd
    cy = fp.GetCourtyard(lay)
    bb = cy.BBox() if cy.OutlineCount() else fp.GetBoundingBox(False, False)
    w, h = pcbnew.ToMM(bb.GetWidth()), pcbnew.ToMM(bb.GetHeight())
    fp.SetOrientation(was)
    return w, h


def put(board, ref, x, y, rot, lock=True):
    fp = board.FindFootprintByReference(ref)
    if fp is None:
        return None
    if fp.IsFlipped():
        fp.Flip(fp.GetPosition(), False)
    fp.SetOrientationDegrees(rot)
    fp.SetPosition(pcbnew.VECTOR2I(mm(OX + x), mm(OY + y)))
    fp.SetLocked(lock)
    return fp


# ------------------------------------------------------------------ кольцо

def ring(board):
    """Конденсаторы развязки — каждый напротив своего вывода.

    Выводов на стороне много, а конденсатор шире шага выводов, поэтому кольцо
    получается в несколько рядов: деталь садится в первый ряд, где её интервал
    вдоль стороны свободен, иначе уходит дальше от корпуса. Так конденсатор
    остаётся против своего вывода, а не уезжает к середине стороны.
    """
    u1 = board.FindFootprintByReference("U1")
    cx, cy = xy(u1)
    pads = {p.GetNumber(): (pcbnew.ToMM(p.GetPosition().x) - OX,
                            pcbnew.ToMM(p.GetPosition().y) - OY)
            for p in u1.Pads()}

    # Коридор к разъёму шлейфа кольцу уступает. Шина дисплея — 23 линии, и
    # ради того, чтобы она легла без крюка, разъём стоит вплотную к левому
    # верхнему углу корпуса (`pcb02_place.py`). Конденсатор, которому выпало
    # это место, уходит рядом дальше; развязке лишний миллиметр стоит меньше,
    # чем шине десять переходных.
    j601 = board.FindFootprintByReference("J601")
    j601.BuildCourtyardCaches()
    jb = j601.GetCourtyard(pcbnew.F_CrtYd).BBox()
    keeps = [(pcbnew.ToMM(jb.GetLeft()) - OX - 0.4,
              pcbnew.ToMM(jb.GetTop()) - OY - 0.4,
              pcbnew.ToMM(jb.GetRight()) - OX + 0.4,
              pcbnew.ToMM(jb.GetBottom()) - OY + 0.4)]

    # Коридор для шины дисплея. 23 линии выходят у чипа лентой вдоль верхней
    # четверти левого бока, и им надо пройти к разъёму — а кольцо развязки
    # стоит там сплошной стеной в два столбца. Оставляем в нём горизонтальную
    # щель ровно в полосе этих выводов: конденсаторы, которым выпало это
    # место, сдвигаются вдоль бока вверх или вниз, на два-три миллиметра, а не
    # уезжают за угол. Без щели шина не проходит вовсе: разрывы стоят ровно
    # между лучом у разъёма и лучом у чипа.
    lcd = [(pcbnew.ToMM(p.GetPosition().x) - OX,
            pcbnew.ToMM(p.GetPosition().y) - OY) for p in u1.Pads()
           if p.GetNetname().startswith("LCD")
           and pcbnew.ToMM(p.GetPosition().x) - OX < cx]
    if lcd:
        # Полоса нужна не одна, а с надставкой вверх, и вот почему. Выводы
        # шины лежат на ДВУХ сторонах корпуса: часть на левой (уходят прямо к
        # разъёму), часть на верхней (уходят вверх и только потом поворачивают
        # налево). Первым нужна полоса против выводов, вторым — этаж НАД
        # корпусом, и попасть на этот этаж они могут только через тот же
        # коридор.
        #
        # Пока щель считалась по одной полосе выводов, этаж оставался занят:
        # `C803` и `C812` вставали на 63 мм, то есть ровно в проход, и от
        # коридора наверх оставалась дверь шириной 0.7 мм. Восемь линий верхней
        # стороны через неё не идут. Обе эти ёмкости при этом и своё дело
        # делали плохо — до выводов 65 и 66 у них было 5.7 и 9.4 мм.
        #
        # Ширина — по числу линий, а не по полосе выводов: полоса даёт 5.8 мм,
        # а 23 линии при шаге 0.4 требуют 9.2.
        # Коридор соединяет ДВЕ группы площадок, и полосу надо брать по обеим.
        # Считалась она только по выводам чипа, и это работало случайно: при
        # прежнем месте разъёма его площадки попадали в ту же полосу целиком.
        # Разъём сдвинули на ось хвоста панели — и половина его площадок
        # оказалась ниже полосы, ровно напротив нижнего столбца развязки. Шина
        # прошла одной линией из шестнадцати.
        jl = [pcbnew.ToMM(p.GetPosition().y) - OY for p in j601.Pads()
              if p.GetNetname().startswith(("LCD", "SPI0"))]
        ys = [y for _, y in lcd] + jl
        top = min(ys)
        ntop = sum(1 for _, y in lcd if y < min(y for _, y in lcd) + 0.2)
        need = 0.4 * len(lcd) + 1.6
        mid = (min(ys) + max(ys)) / 2
        keeps.append((pcbnew.ToMM(jb.GetRight()) - OX,
                      min(mid - need / 2, top - 0.4 * ntop - 1.6),
                      cx - 8.0, max(mid + need / 2, max(ys) + 0.8)))

    # сторона вывода и оси: n — наружу, t — вдоль стороны
    def side(pin):
        px, py = pads[pin]
        if px < cx - 7:
            return "L"
        if px > cx + 7:
            return "R"
        return "T" if py < cy else "B"

    AXIS = {"L": (-1, 0), "R": (1, 0), "T": (0, -1), "B": (0, 1)}
    groups = {"L": [], "R": [], "T": [], "B": []}
    for ref, pin in DECOUP.items():
        if pin not in pads:
            continue
        s = side(pin)
        groups[s].append((ref, pin))

    # Чужие корпуса — тоже препятствие. Кольцо смотрело только на запреты
    # (разъём шлейфа и коридор шины), а на остальную плату нет: соседей по
    # кольцу разводил счётчик занятого вдоль ряда, и этого хватало, пока
    # выбор места был жадным и до чужих деталей просто не доходил. Как только
    # место стало выбираться по расстоянию, `C802` село на контрольную точку
    # `TP801`. Своих по кольцу здесь нет — их держит `rows`.
    mine = set(DECOUP) | {"U1"}
    for f in board.GetFootprints():
        if f.GetReference() in mine:
            continue
        f.BuildCourtyardCaches()
        c = f.GetCourtyard(pcbnew.F_CrtYd)
        if not c.OutlineCount():
            continue
        bb = c.BBox()
        keeps.append((pcbnew.ToMM(bb.GetLeft()) - OX - GAP / 2,
                      pcbnew.ToMM(bb.GetTop()) - OY - GAP / 2,
                      pcbnew.ToMM(bb.GetRight()) - OX + GAP / 2,
                      pcbnew.ToMM(bb.GetBottom()) - OY + GAP / 2))

    # Край площадок корпуса плюс зазор. Зазор не «на всякий случай»: в него
    # должен уместиться луч, которым сигнал выходит из-под корпуса
    # (`pcb07_fanout.py`) — 0.4 мм самого короткого луча и по 0.2 зазора с
    # каждой стороны. При прежних 0.4 кольцо запирало выход: лучей выходило 66
    # из 128 вместо 108. Ставим 1.1.
    half = 8.25 + RING
    placed = 0
    stuck = []
    # Занятое вдоль рядов — по каждой стороне свой счётчик, и он живёт дольше
    # прохода по стороне: тем, кому места на своей стороне не нашлось, мы даём
    # второй проход по ВСЕМ сторонам. Левый бок у нас занят разъёмом шлейфа и
    # коридором шины, и шесть ёмкостей звука там не помещались вовсе —
    # садились внахлёст. Уйти за угол на соседнюю сторону дальше от вывода,
    # чем встать на своей, но ближе, чем лечь на чужой корпус.
    rows_of = {s: [] for s in groups}

    def try_place(ref, pin, s, force):
        """Поставить `ref` у стороны `s`. Возвращает, нашлось ли место.

        `force` — ставить даже если свободного места нет: тогда деталь ляжет
        внахлёст, и об этом будет сказано в отчёте.
        """
        nx, ny = AXIS[s]
        vertical = s in ("L", "R")            # вдоль стороны идёт Y
        rows = rows_of[s]
        fp = board.FindFootprintByReference(ref)
        if fp is None:
            return True                       # нечего ставить, и это не наша беда
        w, h = size(fp)
        # длинной стороной наружу: так деталь занимает вдоль стороны
        # минимум и влезает больше штук в один ряд
        rot = 90 if not vertical else 0
        along, radial = h, w
        t = pads[pin][1] if vertical else pads[pin][0]
        lo0 = t - along / 2
        # Габарит ПОСЛЕ поворота, а не до. Деталь ставится длинной стороной
        # наружу, то есть у верхней и нижней сторон корпуса она повёрнута на
        # 90°, — а проверка занятости меряла её неповёрнутой: ширину по X,
        # высоту по Y. У боков это совпадало случайно, у верха и низа врало, и
        # конденсатор садился на чужой корпус (`J601~C823`). `along` и `radial`
        # уже посчитаны в осях стороны, ими и меряем.
        bx = radial if vertical else along
        by = along if vertical else radial

        def spot(k, lo):
            """Место в ряду k при начале интервала lo — и занято ли оно."""
            tc = lo + along / 2
            rc = half + radial / 2 + k * (radial + ROW_GAP)
            qx, qy = (cx + nx * rc, tc) if vertical else (tc, cy + ny * rc)
            bad = any(b[0] < qx + bx / 2 and qx - bx / 2 < b[2]
                      and b[1] < qy + by / 2 and qy - by / 2 < b[3]
                      for b in keeps)
            return tc, qx, qy, bad

        # Из всех свободных мест берём БЛИЖАЙШЕЕ К СВОЕМУ ВЫВОДУ, и это
        # единственная честная мера: смысл развязки — короткая петля тока, а
        # короткая она по прямой, а не «вдоль» или «наружу».
        #
        # Прежде выбор делало правило: сперва ближний ряд при любом сдвиге
        # вдоль бока, до десяти миллиметров, и только потом ряд дальше.
        # Правило звучало разумно («сдвиг вдоль дешевле сдвига наружу») и на
        # малых сдвигах верно, но на больших врёт вдвое: третий ряд уводит от
        # вывода на 2.5 мм, а сдвиг вдоль — на все десять. Ровно так `C801`
        # уехал за нижний угол корпуса и оказался в 16.6 мм от вывода 83, при
        # том что место в третьем ряду напротив вывода было свободно.
        pinx, piny = pads[pin]
        cands = []
        for shift in [0.0] + [q * d for q in
                              (0.5, 1.0, 1.5, 2.0, 2.5, 3.0, 4.0, 5.0,
                               6.0, 7.0, 8.0, 9.0, 10.0)
                              for d in (1, -1)]:
            want = lo0 + shift
            for k in range(MAX_ROWS):
                if k == len(rows):
                    rows.append(-1e9)
                if rows[k] + GAP > want:
                    continue
                tc, qx, qy, bad = spot(k, want)
                if bad:
                    continue
                cands.append((math.hypot(qx - pinx, qy - piny), k, want))
        ok = bool(cands)
        if cands:
            _, k, lo = min(cands)
        elif not force:
            return False
        else:
            # Свободного места нет вовсе. Ставим в наименее занятый ряд — и
            # ГОВОРИМ об этом. Прежде эта ветка молчала и занятость не
            # проверяла: деталь садилась на чужой корпус, и узнать об этом
            # можно было только по DRC, среди сотни разрывов.
            k = min(range(len(rows)), key=lambda i: rows[i])
            lo = max(rows[k] + GAP, lo0)
        t, px, py, _ = spot(k, lo)
        rows[k] = lo + along
        put(board, ref, px, py, rot)
        return ok

    for s, items in groups.items():
        vertical = s in ("L", "R")
        # объёмные — в конец очереди, они уедут в дальний ряд
        items.sort(key=lambda it: (it[0] in BULK,
                                   pads[it[1]][1] if vertical else pads[it[1]][0]))
        for ref, pin in items:
            # Уход на СОСЕДНЮЮ сторону пробовали и отказались. Мысль
            # напрашивается: левый бок занят разъёмом шлейфа и коридором шины,
            # шести ёмкостям там места нет — пусть уйдут за угол. Померено:
            # средняя длина до вывода 6.8 -> 8.3 мм, худшая 12.0 -> 19.1.
            # За углом свободно как раз то, что дальше всего от вывода, и
            # «нашлось место» получается за счёт того, ради чего это место
            # искали. Внахлёст на своей стороне хотя бы видно в отчёте.
            if not try_place(ref, pin, s, force=True):
                stuck.append(f"{ref}(вывод {pin})")
            placed += 1

    if stuck:
        print(f"    места в кольце не нашлось, поставлено внахлёст: "
              f"{len(stuck)} — {' '.join(stuck)}")
    return placed


# -------------------------------------------------------------------- баки

def bucks(board):
    """Три канала: CIN у IN, дроссель у LX, делитель на стороне FB."""
    n = 0
    for (u, l, cin, cout, c01, rt, rb, jmp, tp, c22), (bx, by) in zip(BUCKS, BUCK_AT):
        put(board, u, bx, by, 0)
        for ref, key in ((cin, "CIN"), (l, "L"), (cout, "COUT"), (c01, "C01"),
                         (rt, "RT"), (rb, "RB"), (jmp, "JMP"), (tp, "TP"),
                         (c22, "C22")):
            if ref is None:
                continue
            dx, dy, rot = BUCK_OFF[key]
            if put(board, ref, bx + dx, by + dy, rot):
                n += 1
        n += 1
    return n


# ------------------------------------------------------- кварцы и USB

def crystals(board):
    """Кварцы и флешка — вплотную к своим выводам на левом торце корпуса.

    После переворота корпуса левая сторона несёт всё, что должно стоять рядом:
    выводы 7…19 (`PF`/`PC`, шина флешки) на `y = 36.0…40.8`, выводы 21…25
    (кварцы) на `y = 33.6…35.2`. Кольцо развязки занимает там `y = 32…36`
    в двух рядах, поэтому:

    * **флешка** садится в свободный карман `y = 37…43` прямо у корпуса —
      от её выводов до выводов F133 около миллиметра;
    * **кварцы** уходят на ряд дальше, за развязку, но остаются напротив
      своих выводов. Приоритет у развязки: петля тока по питанию важнее
      длины кварцевой дорожки, а 24 МГц спокойно терпит десяток миллиметров.

    До этой правки и флешка, и кварцы стояли у самого края платы, в 20…40 мм
    от своих выводов — свободное место у корпуса просто никто не занял.
    """
    # Координаты — от середины корпуса, а не от угла платы: чип двигается ради
    # шины дисплея, и всё, что стоит «вплотную к его выводам», обязано ехать
    # за ним. Иначе кварцы и флешка молча остаются на месте в двадцати
    # миллиметрах от своих выводов — так и случилось при первом же сдвиге.
    u1 = board.FindFootprintByReference("U1")
    cx, cy = xy(u1)
    n = 0
    for ref, dx, dy, rot in (("U401", 22.0,  1.5, 0),    # SPI NOR у выводов 14…19
                             ("Y1",   20.0, -5.0, 0),    # 24 МГц, выводы 22/23
                             ("Y2",   20.0, -10.0, 0),   # 32.768 кГц, выводы 24/25
                             ("C15",  25.5, -6.0, 0),    # нагрузочные 24 МГц
                             ("C16",  25.5, -3.0, 0),
                             ("C17",  25.5, -11.0, 0),   # нагрузочные 32 кГц
                             ("C18",  25.5, -8.5, 0)):
        if put(board, ref, cx + dx, cy + dy, rot):
            n += 1
    return n


def usb(board):
    """CC-резисторы и защита — вплотную к розетке (03-usb.md §6.2)."""
    n = 0
    # `USBLC6` обязан стоять В РАЗРЫВЕ пары `D+`/`D−`, у самой розетки: он для
    # того и нужен, чтобы разряд ушёл в него, а не в чип. Стоял правее розетки
    # — пара шла бы от неё вправо к защите и потом обратно влево к F133, крюк
    # в три сантиметра на паре USB.
    for ref, x, y, rot in (("D301", 107.0, 60.0, 0),
                           ("R301", 113.0, 57.0, 0), ("R302", 113.0, 60.0, 0)):
        if put(board, ref, x, y, rot):
            n += 1
    return n


def leds(board):
    """Светодиоды заряда — на нижний торец, где их видно.

    `D1` и `D2` показывают `CHRG` и `STDBY` у TP4056: это индикация для
    человека, а не служебный узел. Раскладчик по зонам ставил их в середину
    блока зарядника — то есть на лице под правой ладонью, где их не видно
    вовсе. Ставим у нижнего торца рядом с розеткой: там же, где втыкают
    кабель, туда же и смотрят.
    """
    n = 0
    for ref, x, y in (("D1", 121.0, 69.0), ("D2", 125.0, 69.0)):
        if put(board, ref, x, y, 0):
            n += 1
    return n


def overlaps(board):
    for f in board.GetFootprints():
        f.BuildCourtyardCaches()
    boxes = []
    for f in board.GetFootprints():
        for lay in (pcbnew.F_CrtYd, pcbnew.B_CrtYd):
            c = f.GetCourtyard(lay)
            if c.OutlineCount():
                boxes.append((f.GetReference(), lay, c.BBox()))
    return [f"{a}~{b}" for (a, l1, x), (b, l2, y) in itertools.combinations(boxes, 2)
            if l1 == l2 and x.Intersects(y)]


def ring_cost(board):
    """Во что обошёлся отступ кольца: как далеко ёмкости от своих выводов.

    Печатает тот, кто их ставит. Отступ кольца — размен: наружу двинешь, шине
    станет легче, а развязке хуже, и без этого числа выбирают по одной
    половине размена. Порог 7 мм не наш, он из практики развязки; сколько
    именно вышло — здесь.
    """
    u1 = board.FindFootprintByReference("U1")
    if u1 is None:
        return "U1 не найден"
    P = {p.GetNumber(): p.GetPosition() for p in u1.Pads()}
    ds = []
    for ref, pin in DECOUP.items():
        f = board.FindFootprintByReference(ref)
        if f is None or pin not in P:
            continue
        ds.append(min(math.hypot(pcbnew.ToMM(q.GetPosition().x - P[pin].x),
                                 pcbnew.ToMM(q.GetPosition().y - P[pin].y))
                      for q in f.Pads()))
    if not ds:
        return "ни одной ёмкости развязки не найдено"
    return (f"{len(ds)} шт, до вывода в среднем {sum(ds) / len(ds):.1f} мм, "
            f"худшая {max(ds):.1f}, дальше 7 мм — {sum(1 for d in ds if d > 7):d}")


def main():
    board = pcbnew.LoadBoard(str(BOARD))
    print(f"  развязка кольцом вокруг F133: {ring(board)}")
    print(f"  отступ кольца {RING} мм ценой:  {ring_cost(board)}")
    print(f"  баки с обвязкой:              {bucks(board)}")
    print(f"  кварцы и их конденсаторы:     {crystals(board)}")
    print(f"  обвязка USB у розетки:        {usb(board)}")
    print(f"  светодиоды заряда у торца:    {leds(board)}")
    board.Save(str(BOARD))
    bad = overlaps(board)
    print("пересечений courtyard:", len(bad), " ".join(bad[:14]))


if __name__ == "__main__":
    main()
