def mm(v):
    return pcbnew.FromMM(v)


def xy(fp):
    p = fp.GetPosition()
    return pcbnew.ToMM(p.x) - OX, pcbnew.ToMM(p.y) - OY


def size(fp):
    """Габарит courtyard **при нулевом повороте**.

    Мерить как есть нельзя: скрипт сам поворачивает детали, и на втором прогоне
    у повёрнутого конденсатора ширина с высотой меняются местами. Кольцо от
    этого разъезжается и детали налезают друг на друга — так и было, пока не
    стали снимать габарит на нуле и возвращать поворот обратно.
    """
    # Кэш courtyard пересчитываем явно: после `SetPosition` KiCad помечает
    # его недействительным, но не строит заново, и `GetCourtyard()` отдаёт
    # пустой полигон. Проверка тогда молча пропускает деталь и рапортует
    # ноль — ровно так подсунутая внахлёст пара конденсаторов не нашлась.
    fp.BuildCourtyardCaches()
    was = fp.GetOrientation()
    fp.SetOrientationDegrees(0)
    lay = pcbnew.B_CrtYd if fp.IsFlipped() else pcbnew.F_CrtYd
    cy = fp.GetCourtyard(lay)
    bb = cy.BBox() if cy.OutlineCount() else fp.GetBoundingBox(False, False)
    w, h = pcbnew.ToMM(bb.GetWidth()), pcbnew.ToMM(bb.GetHeight())
    fp.SetOrientation(was)
    return w, h


def put(board, ref, x, y, rot, lock=True, back=False):
    fp = board.FindFootprintByReference(ref)
    if fp is None:
        return None
    if fp.IsFlipped() != back:
        fp.Flip(fp.GetPosition(), False)
    fp.SetOrientationDegrees(rot)
    fp.SetPosition(pcbnew.VECTOR2I(mm(OX + x), mm(OY + y)))
    fp.SetLocked(lock)
    return fp


# ------------------------------------------------------------------ кольцо

# Ставить развязку «в ближайшее свободное место от своего вывода» вместо
# «вдоль своей стороны рядами».
#
# Рядами получалось так: сторона выбирается по выводу, а место — по свободному
# интервалу ВДОЛЬ неё, то есть конденсатор едет вдоль бока, а не от него. Пока
# бока были пусты, это совпадало с «близко». Сейчас левый бок занят разъёмом
# шлейфа, коридором шины и обвязкой дисплея, и совпадать перестало: девять
# ёмкостей уехали на 15…33 мм, а это уже не развязка.
NEAREST = os.environ.get("PCB_NEAREST", "1") != "0"


def place_nearest(board, pads, keeps, cx, cy, half):
    """Каждому конденсатору — ближайшее к его выводу свободное место.

    Перебор идёт кольцами по 0.2 мм от вывода наружу, и первое место, куда
    деталь встаёт без пересечений, и есть ответ. Проверяются: запреты
    (`keeps`), площадки самого корпуса, уже поставленные соседи и край платы.
    Обе ориентации — по длинной стороне вдоль и поперёк.
    """
    taken = []
    for f in board.GetFootprints():
        if f.GetReference() in DECOUP or f.GetReference() == "U1":
            continue
        f.BuildCourtyardCaches()
        c = f.GetCourtyard(pcbnew.F_CrtYd)
        if c.OutlineCount():
            bb = c.BBox()
            taken.append((pcbnew.ToMM(bb.GetLeft()) - OX - GAP / 2,
                          pcbnew.ToMM(bb.GetTop()) - OY - GAP / 2,
                          pcbnew.ToMM(bb.GetRight()) - OX + GAP / 2,
                          pcbnew.ToMM(bb.GetBottom()) - OY + GAP / 2))

    def free(x0, y0, x1, y1):
        if not (1.0 < x0 and x1 < BOARD_W - 1.0
                and 1.0 < y0 and y1 < BOARD_H - 1.0):
            return False
        if x1 > cx - half and x0 < cx + half \
                and y1 > cy - half and y0 < cy + half:
            return False                       # площадки и лучи самого F133
        for bx0, by0, bx1, by1 in keeps:
            if x1 > bx0 and bx1 > x0 and y1 > by0 and by1 > y0:
                return False
        for bx0, by0, bx1, by1 in taken:
            if x1 > bx0 and bx1 > x0 and y1 > by0 and by1 > y0:
                return False
        return True

    placed, far = 0, []
    order = sorted(DECOUP.items(), key=lambda it: (it[0] in BULK, it[1]))
    for ref, pin in order:
        fp = board.FindFootprintByReference(ref)
        if fp is None or pin not in pads:
            continue
        px, py = pads[pin]
        w, h = size(fp)
        best = None
        for step in range(1, 120):             # до 24 мм от вывода
            r = step * 0.2
            for k in range(max(8, int(2 * math.pi * r / 0.4))):
                a = 2 * math.pi * k / max(8, int(2 * math.pi * r / 0.4))
                x, y = px + r * math.cos(a), py + r * math.sin(a)
                for rot, (bw, bh) in ((0, (w, h)), (90, (h, w))):
                    if free(x - bw / 2, y - bh / 2, x + bw / 2, y + bh / 2):
                        best = (x, y, rot, bw, bh)
                        break
                if best:
                    break
            if best:
                break
        if best is None:
            far.append(ref)
            continue
        x, y, rot, bw, bh = best
        taken.append((x - bw / 2 - GAP / 2, y - bh / 2 - GAP / 2,
                      x + bw / 2 + GAP / 2, y + bh / 2 + GAP / 2))
        put(board, ref, x, y, rot, back=BACK)
        placed += 1
    if far:
        print(f"    места не нашлось вовсе: {len(far)} — {' '.join(far)}")
    return placed


