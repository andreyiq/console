def ring(board):
    """Конденсаторы развязки — каждый напротив своего вывода.

    Выводов на стороне много, а конденсатор шире шага выводов, поэтому кольцо
    получается в несколько рядов: деталь садится в первый ряд, где её интервал
    вдоль стороны свободен, иначе уходит дальше от корпуса. Так конденсатор
    остаётся против своего вывода, а не уезжает к середине стороны.
    """
    u1 = board.FindFootprintByReference("U1")
    cx, cy = xy(u1)
    pads = {p.GetNumber(): (pcbnew.ToMM(p.GetPosition().x) - OX,
                            pcbnew.ToMM(p.GetPosition().y) - OY)
            for p in u1.Pads()}

    # Коридор к разъёму шлейфа кольцу уступает. Шина дисплея — 23 линии, и
    # ради того, чтобы она легла без крюка, разъём стоит вплотную к левому
    # верхнему углу корпуса (`pcb02_place.py`). Конденсатор, которому выпало
    # это место, уходит рядом дальше; развязке лишний миллиметр стоит меньше,
    # чем шине десять переходных.
    j601 = board.FindFootprintByReference("J601")
    j601.BuildCourtyardCaches()
    jb = j601.GetCourtyard(pcbnew.F_CrtYd).BBox()
    keeps = [(pcbnew.ToMM(jb.GetLeft()) - OX - 0.4,
              pcbnew.ToMM(jb.GetTop()) - OY - 0.4,
              pcbnew.ToMM(jb.GetRight()) - OX + 0.4,
              pcbnew.ToMM(jb.GetBottom()) - OY + 0.4)]

    # Коридор для шины дисплея. 23 линии выходят у чипа лентой вдоль верхней
    # четверти левого бока, и им надо пройти к разъёму — а кольцо развязки
    # стоит там сплошной стеной в два столбца. Оставляем в нём горизонтальную
    # щель ровно в полосе этих выводов: конденсаторы, которым выпало это
    # место, сдвигаются вдоль бока вверх или вниз, на два-три миллиметра, а не
    # уезжают за угол. Без щели шина не проходит вовсе: разрывы стоят ровно
    # между лучом у разъёма и лучом у чипа.
    lcd = [(pcbnew.ToMM(p.GetPosition().x) - OX,
            pcbnew.ToMM(p.GetPosition().y) - OY) for p in u1.Pads()
           if p.GetNetname().startswith("LCD")
           and pcbnew.ToMM(p.GetPosition().x) - OX < cx]
    if lcd:
        # Полоса нужна не одна, а с надставкой вверх, и вот почему. Выводы
        # шины лежат на ДВУХ сторонах корпуса: часть на левой (уходят прямо к
        # разъёму), часть на верхней (уходят вверх и только потом поворачивают
        # налево). Первым нужна полоса против выводов, вторым — этаж НАД
        # корпусом, и попасть на этот этаж они могут только через тот же
        # коридор.
        #
        # Пока щель считалась по одной полосе выводов, этаж оставался занят:
        # `C803` и `C812` вставали на 63 мм, то есть ровно в проход, и от
        # коридора наверх оставалась дверь шириной 0.7 мм. Восемь линий верхней
        # стороны через неё не идут. Обе эти ёмкости при этом и своё дело
        # делали плохо — до выводов 65 и 66 у них было 5.7 и 9.4 мм.
        #
        # Ширина — по числу линий, а не по полосе выводов: полоса даёт 5.8 мм,
        # а 23 линии при шаге 0.4 требуют 9.2.
        # Коридор соединяет ДВЕ группы площадок, и полосу надо брать по обеим.
        # Считалась она только по выводам чипа, и это работало случайно: при
        # прежнем месте разъёма его площадки попадали в ту же полосу целиком.
        # Разъём сдвинули на ось хвоста панели — и половина его площадок
        # оказалась ниже полосы, ровно напротив нижнего столбца развязки. Шина
        # прошла одной линией из шестнадцати.
        jl = [pcbnew.ToMM(p.GetPosition().y) - OY for p in j601.Pads()
              if p.GetNetname().startswith(("LCD", "SPI0"))]
        ys = [y for _, y in lcd] + jl
        top = min(ys)
        ntop = sum(1 for _, y in lcd if y < min(y for _, y in lcd) + 0.2)
        need = 0.4 * len(lcd) + 1.6
        mid = (min(ys) + max(ys)) / 2
        keeps.append((pcbnew.ToMM(jb.GetRight()) - OX,
                      min(mid - need / 2, top - 0.4 * ntop - 1.6),
                      cx - 8.0, max(mid + need / 2, max(ys) + 0.8)))

    # сторона вывода и оси: n — наружу, t — вдоль стороны
    def side(pin):
        px, py = pads[pin]
        if px < cx - 7:
            return "L"
        if px > cx + 7:
            return "R"
        return "T" if py < cy else "B"

    AXIS = {"L": (-1, 0), "R": (1, 0), "T": (0, -1), "B": (0, 1)}
    groups = {"L": [], "R": [], "T": [], "B": []}
    for ref, pin in DECOUP.items():
        if pin not in pads:
            continue
        s = side(pin)
        groups[s].append((ref, pin))

    # Чужие корпуса — тоже препятствие. Кольцо смотрело только на запреты
    # (разъём шлейфа и коридор шины), а на остальную плату нет: соседей по
    # кольцу разводил счётчик занятого вдоль ряда, и этого хватало, пока
    # выбор места был жадным и до чужих деталей просто не доходил. Как только
    # место стало выбираться по расстоянию, `C802` село на контрольную точку
    # `TP801`. Своих по кольцу здесь нет — их держит `rows`.
    mine = set(DECOUP) | {"U1"}
    for f in board.GetFootprints():
        if f.GetReference() in mine:
            continue
        # Развязка на изнанке лицевых соседей не видит — они на другой стороне
        # платы. Пока они считались препятствиями, кольцо обходило пустоту.
        if BACK and not f.IsFlipped():
            continue
        f.BuildCourtyardCaches()
        c = f.GetCourtyard(pcbnew.F_CrtYd)
        if not c.OutlineCount():
            continue
        bb = c.BBox()
        keeps.append((pcbnew.ToMM(bb.GetLeft()) - OX - GAP / 2,
                      pcbnew.ToMM(bb.GetTop()) - OY - GAP / 2,
                      pcbnew.ToMM(bb.GetRight()) - OX + GAP / 2,
                      pcbnew.ToMM(bb.GetBottom()) - OY + GAP / 2))

    # Ниже забора развязке делать нечего. Полосы крестовины идут поперёк платы
    # на y 91…95, и всё, что оказалось под ними, соединяется с чипом только
    # через две заклёпки — а у заклёпки есть индуктивность, и развязка через
    # неё перестаёт быть развязкой. Померено: четыре ёмкости опор кодека
    # (`AVCC`, `AGND`, `VRA1`, `VRA2`) уехали вниз и притащили с собой четыре
    # цепи через забор.
    keeps.append((50.0 - OX, 90.5 - OY, 206.0 - OX, 114.0 - OY))

    # Коридор кварцев. Четыре сигнала — `X32KIN`, `X32KOUT`, `DXIN`, `DXOUT` —
    # выходят из окна высотой 1.2 мм (выводы 25…22, y 71.6…72.8) и должны
    # разойтись: пара 32 кГц вверх к `Y2`, пара 24 МГц вниз к `Y1`. Кольцу это
    # место кажется свободным, и оно ставит туда развязку: `C819` встал на
    # x 161.1…164.5, и от него до соседнего `C822` осталось 0.7 мм — щель на
    # одну дорожку из двух. Запрещаем полосу целиком; развязке выводов 20, 26,
    # 28…30 придётся отъехать на ряд, и это дешевле.
    keeps.append((156.5 - OX, 68.5 - OY, 165.5 - OX, 73.5 - OY))

    # Колонка сброса. `RESET` (вывод 27, y 70.8) зажат: сверху `LDOA-OUT` и
    # `+3V3`, снизу пара 32 кГц, справа кварц `Y2`. Прямо ему идти некуда,
    # значит надо вверх — и только вплотную к боку, пока соседи ещё не
    # разошлись по своим лучам. Эту колонку кольцу тоже не отдаём.
    keeps.append((157.6 - OX, 61.0 - OY, 160.6 - OX, 68.5 - OY))

    # Полосы ручной разводки — тоже препятствие, и это не мелочь. Порядок
    # работы теперь блочный: часть платы разведена руками ДО того, как встало
    # кольцо (10-mech.md §8.3.0). Кольцо про эти линии не знало и село прямо
    # на них — семь ёмкостей поверх линий кнопок. Видно это было только
    # глазами: DRC молчал бы до первой попытки развести саму развязку.
    #
    # Смотрим не на медь платы, а на ПЛАН — таблицу `pcb_hand.ROUTES`.
    # Смотреть на медь нельзя: `pcb07_fanout.py` первым делом снимает с платы
    # всё, и к моменту расстановки её там нет. План же лежит числами и не
    # зависит от того, на каком шаге круга мы находимся.
    for poly in (p for polys in hand_routes().values() for p in polys):
        for (ax, ay), (bx, by) in zip(poly, poly[1:]):
            x1, y1, x2, y2 = ax - OX, ay - OY, bx - OX, by - OY
            r = 0.1 + GAP / 2
            if abs(x1 - x2) < 0.01 or abs(y1 - y2) < 0.01:
                keeps.append((min(x1, x2) - r, min(y1, y2) - r,
                              max(x1, x2) + r, max(y1, y2) + r))
                continue
            # Наклонную нельзя брать габаритом: у диагонали в сорок
            # миллиметров габарит закроет четверть платы. Идём по ней шагами.
            n = int(math.dist((x1, y1), (x2, y2)) / 0.4) + 1
            for i in range(n + 1):
                k = i / n
                px, py = x1 + (x2 - x1) * k, y1 + (y2 - y1) * k
                keeps.append((px - r, py - r, px + r, py + r))

    # Край площадок корпуса плюс зазор. Зазор не «на всякий случай»: в него
    # должен уместиться луч, которым сигнал выходит из-под корпуса
    # (`pcb07_fanout.py`) — 0.4 мм самого короткого луча и по 0.2 зазора с
    # каждой стороны. При прежних 0.4 кольцо запирало выход: лучей выходило 66
    # из 128 вместо 108. Ставим 1.1.
    half = 8.25 + RING
    placed = 0
    stuck = []
    later = []
    moved = []
    # Занятое вдоль рядов — по каждой стороне свой счётчик, и он живёт дольше
    # прохода по стороне: тем, кому места на своей стороне не нашлось, мы даём
    # второй проход по ВСЕМ сторонам. Левый бок у нас занят разъёмом шлейфа и
    # коридором шины, и шесть ёмкостей звука там не помещались вовсе —
    # садились внахлёст. Уйти за угол на соседнюю сторону дальше от вывода,
    # чем встать на своей, но ближе, чем лечь на чужой корпус.
    rows_of = {s: [] for s in groups}

    def try_place(ref, pin, s, force):
        """Поставить `ref` у стороны `s`. Возвращает, нашлось ли место.

        `force` — ставить даже если свободного места нет: тогда деталь ляжет
        внахлёст, и об этом будет сказано в отчёте.
        """
        nx, ny = AXIS[s]
        vertical = s in ("L", "R")            # вдоль стороны идёт Y
        rows = rows_of[s]
        fp = board.FindFootprintByReference(ref)
        if fp is None:
            return True                       # нечего ставить, и это не наша беда
        w, h = size(fp)
        # длинной стороной наружу: так деталь занимает вдоль стороны
        # минимум и влезает больше штук в один ряд
        rot = 90 if not vertical else 0
        along, radial = h, w
        t = pads[pin][1] if vertical else pads[pin][0]
        lo0 = t - along / 2
        # Габарит ПОСЛЕ поворота, а не до. Деталь ставится длинной стороной
        # наружу, то есть у верхней и нижней сторон корпуса она повёрнута на
        # 90°, — а проверка занятости меряла её неповёрнутой: ширину по X,
        # высоту по Y. У боков это совпадало случайно, у верха и низа врало, и
        # конденсатор садился на чужой корпус (`J601~C823`). `along` и `radial`
        # уже посчитаны в осях стороны, ими и меряем.
        bx = radial if vertical else along
        by = along if vertical else radial

        def spot(k, lo):
            """Место в ряду k при начале интервала lo — и занято ли оно."""
            tc = lo + along / 2
            rc = half + radial / 2 + k * (radial + ROW_GAP)
            qx, qy = (cx + nx * rc, tc) if vertical else (tc, cy + ny * rc)
            bad = any(b[0] < qx + bx / 2 and qx - bx / 2 < b[2]
                      and b[1] < qy + by / 2 and qy - by / 2 < b[3]
                      for b in keeps)
            return tc, qx, qy, bad

        # Из всех свободных мест берём БЛИЖАЙШЕЕ К СВОЕМУ ВЫВОДУ, и это
        # единственная честная мера: смысл развязки — короткая петля тока, а
        # короткая она по прямой, а не «вдоль» или «наружу».
        #
        # Прежде выбор делало правило: сперва ближний ряд при любом сдвиге
        # вдоль бока, до десяти миллиметров, и только потом ряд дальше.
        # Правило звучало разумно («сдвиг вдоль дешевле сдвига наружу») и на
        # малых сдвигах верно, но на больших врёт вдвое: третий ряд уводит от
        # вывода на 2.5 мм, а сдвиг вдоль — на все десять. Ровно так `C801`
        # уехал за нижний угол корпуса и оказался в 16.6 мм от вывода 83, при
        # том что место в третьем ряду напротив вывода было свободно.
        pinx, piny = pads[pin]
        cands = []
        for shift in [0.0] + [q * d for q in
                              (0.5, 1.0, 1.5, 2.0, 2.5, 3.0, 4.0, 5.0,
                               6.0, 7.0, 8.0, 9.0, 10.0)
                              for d in (1, -1)]:
            want = lo0 + shift
            for k in range(MAX_ROWS):
                if k == len(rows):
                    rows.append(-1e9)
                if rows[k] + GAP > want:
                    continue
                tc, qx, qy, bad = spot(k, want)
                if bad:
                    continue
                cands.append((math.hypot(qx - pinx, qy - piny), k, want))
        ok = bool(cands)
        if cands:
            _, k, lo = min(cands)
        elif not force:
            return False
        else:
            # Свободного места в разрешённых рядах нет. Прежде здесь деталь
            # ложилась в наименее занятый ряд ВНАХЛЁСТ, и об этом говорилось в
            # отчёте — а на плате это два `courtyards_overlap`: `C823` и `C816`
            # садились прямо на `J601`. Сказать про наложение не то же, что его
            # не сделать: деталь, налезшая на разъём, не паяется вовсе.
            #
            # Поэтому уходим наружу дальше разрешённого — ряд за рядом, пока не
            # найдём свободное место. Развязке там плохо (и это видно по
            # средней длине в отчёте), но плохая развязка лечится, а
            # столкновение корпусов — нет.
            # Мера та же, что в основном поиске: БЛИЖАЙШЕЕ к своему выводу.
            #
            # Направление важнее меры, и здесь легко ошибиться дважды. Уходить
            # ПРЯМО НАРУЖУ, ряд за рядом, нельзя: ближайшее свободное место
            # оказывается в чистом поле в двадцати пяти миллиметрах, средняя
            # длина 6.5 -> 10.3 мм, худшая 14.4 -> 30.8. Правильное направление
            # — ВДОЛЬ стороны, в тех же рядах: там тесно, но близко.
            #
            # Прежняя ветка это направление угадывала верно (сдвиг вдоль до
            # наименее занятого ряда), но занятость не проверяла — и с четырьмя
            # рядами `C823` с `C816` сели на `J601`. Проверяем и уходим дальше,
            # пока не найдём свободное.
            far = []
            for k2 in range(MAX_ROWS):
                while k2 >= len(rows):
                    rows.append(-1e9)
                for shift in [q * d for q in
                              (11, 13, 15, 18, 21, 25, 30, 35, 40)
                              for d in (1, -1)]:
                    want = max(rows[k2] + GAP, lo0 + shift)
                    tc, qx, qy, bad = spot(k2, want)
                    if bad:
                        continue
                    far.append((math.hypot(qx - pinx, qy - piny), k2, want))
            k = lo = None
            if far:
                _, k, lo = min(far)
            if k is None:
                # Не нашлось и снаружи: не ставим никуда и говорим об этом.
                # Молчаливое «поставил куда попало» хуже, чем «не поставил».
                return False
        t, px, py, _ = spot(k, lo)
        rows[k] = lo + along
        put(board, ref, px, py, rot, back=BACK)
        return ok

    if NEAREST:
        return place_nearest(board, pads, keeps, cx, cy, half)

    for s, items in groups.items():
        vertical = s in ("L", "R")
        # объёмные — в конец очереди, они уедут в дальний ряд
        items.sort(key=lambda it: (it[0] in BULK,
                                   pads[it[1]][1] if vertical else pads[it[1]][0]))
        for ref, pin in items:
            if not try_place(ref, pin, s, force=False):
                later.append((ref, pin, s))
            placed += 1

    # Второй проход: кому на своей стороне места не нашлось, пробует соседние.
    #
    # Уход за угол однажды уже пробовали и отказались: померено было, что
    # средняя длина до вывода растёт 6.8 -> 8.3 мм, худшая 12.0 -> 19.1, — и
    # вывод «за углом свободно как раз то, что дальше всего» был верен ТОГДА.
    # Сейчас условие другое: левый бок закрыт разъёмом шлейфа, коридором шины
    # и обвязкой дисплея, а угол под корпусом свободен. Без второго прохода
    # девять ёмкостей ложатся внахлёст (DRC краснеет) либо уезжают в восьмой
    # ряд — худшая выходит 32.7 мм, и это уже не развязка, а украшение.
    #
    # Стороны перебираются по близости к выводу, а не по алфавиту: берём ту,
    # до чьей оси от вывода ближе. Внахлёст остаётся последним средством и
    # по-прежнему виден в отчёте.
    for ref, pin, own in later:
        px, py = pads[pin]
        order = sorted((s for s in groups if s != own),
                       key=lambda s: abs(px - cx) if s in ("T", "B")
                       else abs(py - cy))
        for s2 in order:
            if try_place(ref, pin, s2, force=False):
                moved.append(f"{ref}->{s2}")
                break
        else:
            try_place(ref, pin, own, force=True)
            stuck.append(f"{ref}(вывод {pin})")

    if moved:
        print(f"    ушло на соседнюю сторону: {len(moved)} — {' '.join(moved)}")

    if stuck:
        print(f"    места в кольце не нашлось, унесено за кольцо: "
              f"{len(stuck)} — {' '.join(stuck)}")
    return placed


# -------------------------------------------------------------------- баки

def bucks(board):
    """Три канала: CIN у IN, дроссель у LX, делитель на стороне FB."""
    n = 0
    for (u, l, cin, cout, c01, rt, rb, jmp, tp, c22), (bx, by) in zip(BUCKS, BUCK_AT):
        put(board, u, bx, by, 0)
        for ref, key in ((cin, "CIN"), (l, "L"), (cout, "COUT"), (c01, "C01"),
                         (rt, "RT"), (rb, "RB"), (jmp, "JMP"), (tp, "TP"),
                         (c22, "C22")):
            if ref is None:
                continue
            dx, dy, rot = BUCK_OFF[key]
            if put(board, ref, bx + dx, by + dy, rot):
                n += 1
        n += 1
    return n


# ------------------------------------------------------- кварцы и USB

def crystals(board):
    """Кварцы и флешка — вплотную к своим выводам на левом торце корпуса.

    После переворота корпуса левая сторона несёт всё, что должно стоять рядом:
    выводы 7…19 (`PF`/`PC`, шина флешки) на `y = 36.0…40.8`, выводы 21…25
    (кварцы) на `y = 33.6…35.2`. Кольцо развязки занимает там `y = 32…36`
    в двух рядах, поэтому:

    * **флешка** садится в свободный карман `y = 37…43` прямо у корпуса —
      от её выводов до выводов F133 около миллиметра;
    * **кварцы** уходят на ряд дальше, за развязку, но остаются напротив
      своих выводов. Приоритет у развязки: петля тока по питанию важнее
      длины кварцевой дорожки, а 24 МГц спокойно терпит десяток миллиметров.

    До этой правки и флешка, и кварцы стояли у самого края платы, в 20…40 мм
    от своих выводов — свободное место у корпуса просто никто не занял.
    """
    # Координаты — от середины корпуса, а не от угла платы: чип двигается ради
    # шины дисплея, и всё, что стоит «вплотную к его выводам», обязано ехать
    # за ним. Иначе кварцы и флешка молча остаются на месте в двадцати
    # миллиметрах от своих выводов — так и случилось при первом же сдвиге.
    u1 = board.FindFootprintByReference("U1")
    cx, cy = xy(u1)
    n = 0
    for ref, dx, dy, rot in (("U401", 22.0,  1.5, 0),    # SPI NOR у выводов 14…19
                             ("Y1",   20.0, -5.0, 0),    # 24 МГц, выводы 22/23
                             ("Y2",   20.0, -10.0, 0),   # 32.768 кГц, выводы 24/25
                             ("C15",  25.5, -6.0, 0),    # нагрузочные 24 МГц
                             ("C16",  25.5, -3.0, 0),
                             ("C17",  25.5, -11.0, 0),   # нагрузочные 32 кГц
                             ("C18",  25.5, -8.5, 0)):
        if put(board, ref, cx + dx, cy + dy, rot):
            n += 1
    n += flash_parts(board)
