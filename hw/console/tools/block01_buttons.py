#!/usr/bin/env python3
"""Рисует блок 1 «Кнопки» в hw/console/console.kicad_sch.

Запуск:  python3 hw/console/tools/block01_buttons.py

Скрипт идемпотентный: перед вставкой выкидывает из схемы всё, что лежит внутри
рамки блока 1, а рамку и заголовок не трогает.

Все решения — из hw/console/blocks/01-buttons.md, ссылка на раздел лежит в поле
`Источник` каждой детали.

Самый простой блок листа: десять одинаковых ячеек «метка — кнопка — земля», ни
одного пассивного элемента. Подтяжка вверх у чипа внутренняя, включается
программно (§6.3), поэтому у кнопки ровно два конца.

Ряд на чертеже — это сторона корпуса, а не группа под пальцами: верхний ряд
уходит на левый край F133 (выводы 1…6), нижний — на верхний край (124…127).
Раскладка кнопок в руках к схеме отношения не имеет (§6.6).

Метки у ног самого F133 ставит блок 8 (правило из 07-clock-reset.md §6.4).

Общая машинерия — в tools/kicadsch.py.
"""

import sys

from kicadsch import Sheet, root_uuid, write

# Рамка блока 1 из tools/scaffold.py — по ней чистится старое содержимое.
FRAME = (20.0, 20.0, 218.0, 130.0)

DOC = "01-buttons.md"

# Кнопка PTS645 — та же, что на RESET (блок 7) и на FEL (блок 3).
FP = "Button_Switch_SMD:SW_SPST_PTS645Sx43SMTR92"

# Все координаты кратны 1.27: иначе ERC ловит вывод детали «не на сетке».
X0, PITCH = 27.94, 31.75      # левая колонка и шаг между кнопками
ROWS = (45.72, 91.44)         # верх ячейки: левый край корпуса, верхний край

# (цепь, подпись на схеме, ряд). Порядок в ряду — порядок выводов PG6…PG15,
# то есть слева направо идут выводы 1…6 и 124…127 (§6.1).
KEYS = [
    ("KEY-UP", "UP", 0),
    ("KEY-DOWN", "DOWN", 0),
    ("KEY-LEFT", "LEFT", 0),
    ("KEY-RIGHT", "RIGHT", 0),
    ("KEY-SELECT", "SELECT", 0),
    ("KEY-START", "START", 0),
    ("KEY-A", "A", 1),
    ("KEY-B", "B", 1),
    ("KEY-C", "C", 1),
    ("KEY-D", "D", 1),
]


def cell(s, x, y, net, name, ref):
    """Одна кнопка: метка сверху, кнопка, земля снизу.

    Метка вертикальная (поворот 90°, текст растёт вверх): горизонтальная при
    шаге колонок 31.75 мм упиралась бы в соседнюю ячейку, а вверх свободно —
    над рядом ничего нет. Самое длинное имя, `KEY-SELECT`, занимает около
    16 мм, и у верхнего ряда от метки до рамки остаётся ещё десяток.

    Кнопка повёрнута на 90°, поэтому её выводы стоят вертикально: вывод 2
    сверху (на 5.08 мм выше центра), вывод 1 снизу.
    """
    s.glabel(net, (x, y), 90)
    s.wire((x, y), (x, y + 2.54))
    sw = s.sym("Switch:SW_Push", ref, name, x, y + 7.62, 90,
               src=f"{DOC} §6.2", fp=FP)
    s.wire(sw.pin("1"), (x, y + 15.24))
    s.power("power:GND", (x, y + 15.24))


def buttons(s):
    for i, (net, name, row) in enumerate(KEYS):
        col = i if row == 0 else i - 6
        cell(s, X0 + col * PITCH, ROWS[row], net, name, f"SW1{i + 1:02d}")


def notes(s):
    """Подписи — справа от нижнего ряда, там пусто.

    Ширина у шрифта 1.6 около 1.4 мм на знак, от начала подписи до правой
    рамки 71 мм: строка длиннее полусотни знаков вылезет наружу.
    """
    x = 142.24
    s.note("верхний ряд: PG6..PG11, выводы 1..6", (x, 91.44))
    s.note("нижний ряд: PG12..PG15, выводы 124..127", (x, 99.06))
    s.note("подтяжка вверх внутренняя, 100k, ставит софт", (x, 106.68))
    s.note("нажато = 0; дребезг гасится софтом", (x, 114.3))
    s.note("PG0..PG5 (118..123) оставлены свободными", (x, 121.92))


def main():
    s = Sheet(root_uuid(), 1, FRAME)
    buttons(s)
    notes(s)
    write(s)
    return 0


if __name__ == "__main__":
    sys.exit(main())
