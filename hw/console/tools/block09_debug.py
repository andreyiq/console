#!/usr/bin/env python3
"""Рисует блок 9 «UART, JTAG, светодиод» в hw/console/console.kicad_sch.

Запуск:  python3 hw/console/tools/block09_debug.py

Скрипт идемпотентный: перед вставкой выкидывает из схемы всё, что лежит внутри
рамки блока 9, а рамку и заголовок не трогает.

Все решения — из hw/console/blocks/09-debug.md, ссылка на раздел лежит в поле
`Источник` каждой детали.

Блок из трёх независимых кусков, стоящих в ряд: гребёнка UART слева, пять
площадок JTAG в середине, светодиод питания справа. Проводов между ними нет —
их и не должно быть.

Метки у ног самого F133 ставит блок 8 (правило из 07-clock-reset.md §6.4).

Общая машинерия — в tools/kicadsch.py.
"""

import sys

from kicadsch import Sheet, root_uuid, write

# Рамка блока 9 из tools/scaffold.py — по ней чистится старое содержимое.
FRAME = (20.0, 352.0, 368.0, 400.0)

DOC = "09-debug.md"

# Все координаты кратны 1.27: иначе ERC ловит вывод детали «не на сетке».
HDR = (76.2, 365.76)         # гребёнка UART
PADS = 127.0                 # левая площадка JTAG
PITCH = 12.7                 # шаг площадок
LED = 304.8                  # столбик светодиода


def uart(s):
    """Гребёнка 4 контакта: GND, TX, RX, +3V3 — порядок из ТЗ (§6.2).

    Символ зеркалим по Y, чтобы контакт 1 оказался сверху, а провода приходили
    слева: так столбик читается сверху вниз в том же порядке, в каком контакты
    пронумерованы на плате.
    """
    j = s.sym("Connector:Conn_01x04_Pin", "J901", "UART", *HDR, 0,
              mirror="y", src=f"{DOC} §6.2", rdx=0.0, rdy=-8.89,
              vdx=0.0, vdy=-6.35, just="left")

    # 1 — земля, 4 — рельса: оба уходят символами питания, вверх и вниз
    s.wire(j.pin("1"), (63.5, j.pin("1")[1]), (63.5, 358.14))
    s.power("power:GND", (63.5, 358.14), 180)
    s.wire(j.pin("4"), (63.5, j.pin("4")[1]), (63.5, 375.92))
    s.power("power:+3V3", (63.5, 375.92), 180)

    # 2 и 3 — сигналы. Имена со стороны платы: TX — то, что плата передаёт
    for num, net in (("2", "TXD0"), ("3", "RXD0")):
        x, y = j.pin(num)
        s.wire((x, y), (55.88, y))
        s.glabel(net, (55.88, y), 180)


def jtag(s):
    """Четыре площадки JTAG и пятая на землю (§6.3).

    Пятая не для красоты: ближайшая земляная точка стоит у корпуса чипа, в
    другом конце платы, а щупу отладчика опора нужна рядом.
    """
    for i, net in enumerate(("TMS", "TDI", "TDO", "TCK")):
        x = PADS + i * PITCH
        s.glabel(net, (x, 365.76), 0)
        s.wire((x, 365.76), (x, 370.84))
        s.sym("Connector:TestPoint", f"TP90{i + 1}", net, x, 370.84, 180,
              src=f"{DOC} §6.3", show_value=False,
              rdx=0.0, rdy=5.08, just=None)

    x = PADS + 4 * PITCH
    s.power("power:GND", (x, 365.76), 180)
    s.wire((x, 365.76), (x, 370.84))
    s.sym("Connector:TestPoint", "TP905", "GND", x, 370.84, 180,
          src=f"{DOC} §6.3", show_value=False, rdx=0.0, rdy=5.08, just=None)


def led(s):
    """Светодиод «питание есть»: от рельсы 3.3 В, а не от GPIO (§6.4).

    Цвет в номинале: по чему ещё узнать, какой паять. Жёлтый выбран, чтобы не
    путался с красным и зелёным светодиодами заряда в блоке 2, и потому что у
    него Vf около 2 В — синий с этим резистором просто не зажжётся (§7.6).
    """
    s.power("power:+3V3", (LED, 358.14), 0)
    r = s.sym("Device:R", "R901", "1k", LED, 364.49, 0, src=f"{DOC} §6.4",
              rdx=2.03, vdx=2.03)
    s.wire((LED, 358.14), r.pin("1"))
    d = s.sym("Device:LED", "D901", "жёлтый", LED, 374.65, 90,
              # 3.81, а не обычные 2.54: у повёрнутого светодиода стрелки
              # излучения торчат вправо и лезут прямо в подпись
              src=f"{DOC} §6.4", rdx=3.81, rdy=-1.27, vdx=3.81, vdy=1.905)
    s.wire(r.pin("2"), d.pin("2"))
    s.wire(d.pin("1"), (LED, 381.0))
    s.power("power:GND", (LED, 381.0))


def notes(s):
    """Подписи — под каждым куском, там же, где он стоит.

    Ширина у шрифта 1.6 около 1.4 мм на знак; правая рамка на 368, поэтому
    последняя подпись не длиннее сорока знаков.
    """
    s.note("к переходнику только GND, TX, RX: 3.3 В с", (40.64, 386.08))
    s.note("контакта 4 столкнётся с рельсой платы", (40.64, 391.16))
    s.note("JTAG включается софтом, функция 7 у PE4..PE7", (127.0, 386.08))
    s.note("на мёртвом чипе его нет — там FEL", (127.0, 391.16))
    s.note("горит, когда поднялись рельсы", (243.84, 386.08))
    s.note("заряд показывают светодиоды блока 2", (243.84, 391.16))


def main():
    s = Sheet(root_uuid(), 9, FRAME)
    uart(s)
    jtag(s)
    led(s)
    notes(s)
    write(s)
    return 0


if __name__ == "__main__":
    sys.exit(main())
