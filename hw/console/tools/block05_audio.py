#!/usr/bin/env python3
"""Рисует блок 5 «Звук» в hw/console/console.kicad_sch.

Запуск:  python3 hw/console/tools/block05_audio.py

Скрипт идемпотентный: перед вставкой выкидывает из схемы всё, что лежит внутри
рамки блока 5, а рамку и заголовок не трогает.

Все решения и номиналы — из hw/console/blocks/05-audio.md, ссылка на раздел
лежит в поле `Источник` каждой детали.

Тракт читается слева направо: метки выхода кодека — разделительные
конденсатор — 24k — усилитель — разъём динамика. Питание усилителя приходит
сверху, `SD` посажен на `PWR_EN` снизу.

Метки у ног самого F133 ставит блок 8 (правило из 07-clock-reset.md §6.4).

Общая машинерия — в tools/kicadsch.py.
"""

import sys

from kicadsch import Sheet, root_uuid, write

# Рамка блока 5 из tools/scaffold.py — по ней чистится старое содержимое.
FRAME = (378.0, 140.0, 574.0, 226.0)

DOC = "05-audio.md"

# Все координаты кратны 1.27: иначе ERC ловит вывод детали «не на сетке».
IN_L, IN_R = 165.1, 172.72   # строки левого и правого канала
LBL = 393.7                  # где стоят входные метки
CX, RX = 403.86, 416.56      # разделительный конденсатор и резистор сумматора
TIE = 425.45                 # где сходятся оба плеча
AMP = (447.04, 167.64)       # центр усилителя
BUS = 157.48                 # шина питания усилителя
SDX = 431.8                  # столбик управления SD


def inputs(s):
    """Одно плечо: метка — 10 мкФ — 24k — вход усилителя (третья ревизия).

    Звук NES монофонический, прошивка кладёт одинаковый сэмпл в оба канала
    кодека, и сумматор из двух плеч давал ровно то же, что одно плечо с
    вдвое меньшим резистором: два 47k параллельно — 23.5k. Берём ближайший из
    ряда E24, 24k: 0.54 В · 160 / (10 + 24) = 2.54 В на 8 Ом против
    расчётных 2.58 (05-audio.md §6.3). Правый канал `HPOUTR` не подключён.

    Цена сумматора была не в двух деталях, а в разводке: от кодека к
    усилителю одна линия вместо двух, и она проходит там же, где уже идёт
    `GPADC0`, — под разъёмом шлейфа, второй полосой.
    """
    net, y = "HPOUTL", IN_L
    s.glabel(net, (LBL, y), 180)
    c = s.sym("Device:C", "C501", "10u", CX, y, 90, src=f"{DOC} §6.3",
              rdy=-6.35, vdy=-3.81)
    r = s.sym("Device:R", "R501", "24k", RX, y, 90, src=f"{DOC} §6.3",
              rdy=-6.35, vdy=-3.81)
    s.wire((LBL, y), c.pin("1"))
    s.wire(c.pin("2"), r.pin("1"))
    s.wire((RX + 3.81, IN_L), (AMP[0] - 10.16, IN_L))


def amp(s):
    """PAM8301 и его питание (§6.2, §6.4).

    Вывод 3 `IN` попадает ровно на строку левого канала, поэтому сумматор
    входит в усилитель без единого излома.
    """
    u = s.sym("Amplifier_Audio:PAM8301", "U501", "PAM8301", *AMP, 0,
              src=f"{DOC} §6.2", lcsc="C3001605",
              # ссылка и тип уходят вправо: слева сверху приходит шина
              # питания, слева снизу — столбик SD, и обе подписи ложились
              # прямо на провод
              rdx=5.08, rdy=-11.43, vdx=5.08, vdy=12.7, just="left")

    # питание: VSYS через 0 Ω (место под бусину) и два конденсатора развязки
    x = 408.94   # 322 x 1.27: сетка
    s.power("parts:VSYS", (x, 147.32))
    rb = s.sym("Device:R", "R503", "0", x, 153.67, 0, src=f"{DOC} §6.4",
               rdx=-2.03, vdx=-2.03, just="right")
    s.wire((x, 147.32), rb.pin("1"))
    s.wire(rb.pin("2"), (421.64, BUS), (434.34, BUS), (440.69, BUS),
           (AMP[0], BUS))
    s.wire((AMP[0], BUS), u.pin("5"))

    # Через резистор признак «выход питания» не проходит, и ERC считает вывод
    # 5 незапитанным. Флаг говорит ему, что цепь запитана; в плату не идёт.
    s.wire((440.69, BUS), (440.69, 152.4))
    s.power("power:PWR_FLAG", (440.69, 152.4), 0, ref="#FLG501")
    s.junction((440.69, BUS))
    for cx, ref, val in ((421.64, "C504", "1u"), (434.34, "C505", "10u")):
        c = s.sym("Device:C", ref, val, cx, 153.67, 0, src=f"{DOC} §6.4",
                  rdx=2.03, vdx=2.03)
        s.wire(c.pin("1"), (cx, 147.32))
        s.power("power:GND", (cx, 147.32), 180)
        s.junction((cx, BUS))

    s.wire(u.pin("2"), (AMP[0], 180.34))
    s.power("power:GND", (AMP[0], 180.34))
    return u


def shutdown(s, u):
    """`SD` — на `PWR_EN`, выход выключателя питания (третья ревизия).

    Было: GPIO `PB2` плюс подтяжка вниз `R504`. Задача подтяжки — чтобы при
    выключенной консоли усилитель молчал и не брал 4 мА с банки (`VSYS` живёт
    всегда). `PWR_EN` решает ту же задачу без деталей: во включённом
    положении движок `SW1` даёт на него `VSYS` — тот же уровень, что на `VDD`
    усилителя, — а в выключенном его тянет к земле `R9` (02-power.md). Ток
    `SD` — единицы микроампер, делителям `EN` баков он не мешает.

    Зачем менять: `AMP-SD` шёл от вывода 86 на левом боку корпуса, и путь от
    него к усилителю перегораживала линия подсветки `LCD-BL` — ещё одна цепь
    через тесный угол. `PWR_EN` идёт по плате прямо над полем усилителя.
    """
    y = 185.42
    s.wire(u.pin("4"), (SDX, u.pin("4")[1]), (SDX, y))
    s.label("PWR_EN", (SDX, y), 0)


def speaker(s, u):
    """Динамик мостом: обе клеммы на выходах, землю сажать нельзя (§6.7)."""
    j = s.sym("Connector:Conn_01x02_Pin", "J501", "SPK 8R", 490.22, 170.18,
              180, src=f"{DOC} §6.7", rdx=0.0, rdy=-8.89, vdx=0.0, vdy=-6.35,
              just="left")
    s.wire(u.pin("1"), j.pin("1"))
    s.wire(u.pin("6"), (480.06, IN_L), (480.06, 167.64), j.pin("2"))


def feedback(s):
    """`HPOUTFB` — 0.1 мкФ на общую `GND`, как у Xassette (§4.1).

    MangoPi возвращает его на `AGND` (§3.4). Третья ревизия выбирает `GND`
    по разводке: вывод 100 стоит между `HPOUTL` (99) и `GPADC0` (101), обе
    линии уходят влево, и до `AGND` конденсатору пришлось бы пересечь
    `HPOUTL`. Общая земля там — сплошная заливка. Наушников на плате нет,
    вывод просто зашунтирован; обе референсные платы делают с ним это.
    """
    y = 200.66
    s.glabel("HPOUTFB", (LBL, y), 180)
    c = s.sym("Device:C", "C503", "0.1u", CX, y, 90, src=f"{DOC} §4.1",
              rdy=-6.35, vdy=-3.81)
    s.wire((LBL, y), c.pin("1"))
    s.wire(c.pin("2"), (RX, y))
    s.glabel("GND", (RX, y), 0)


def notes(s):
    """Подписи — в свободном правом нижнем углу блока.

    От начала подписи до правой рамки 94 мм, шрифт 1.6 даёт около 1.4 мм на
    знак: строка до шестидесяти знаков помещается.
    """
    x = 480.06
    s.note("одно плечо 24k: звук NES моно, HPOUTR не нужен", (x, 185.42))
    s.note("полная шкала кодека -> 2.5 В на 8 Ом, это 0.8 Вт", (x, 193.04))
    s.note("SD на PWR_EN: выключатель гасит и усилитель", (x, 200.66))
    s.note("выход мостовой: ни одну клемму динамика на землю", (x, 208.28))
    s.note("PB3..PB7 свободны — это I2S2 под MAX98357A", (x, 215.9))


# Ставим ли усилитель и динамик в ПЕРВОЙ ревизии.
#
# Причина отказа — не схема, а разводка, и она считается. Полосы крестовины
# идут поперёк платы на y 91…95 и работают забором: всё, что приходит с
# нижнего края, обязано его пересечь, а у нас нет металлизации отверстий, и
# каждое пересечение — заклёпка, которую паяют вручную с двух сторон.
#
# Замерено на плате: через забор идут 11 цепей, то есть 22 заклёпки. Семь из
# одиннадцати — звук (`HPOUTL`, `HPOUTR`, `HPOUTFB`, `AVCC`, `AGND`, `VRA2`,
# `AMP-SD`): усилитель стоит под забором, а кодек над ним. Без звука остаются
# три (`USB0-DP`, `USB0-DM`, `VBUS`) — шесть заклёпок.
#
# Что НЕ уходит вместе с блоком: сам кодек сидит внутри F133, и его питание
# `AVCC`/`HPVCC` с развязкой остаётся — это выводы чипа, а не наша обвязка.
# Значит вернуть звук во второй ревизии стоит одиннадцати деталей и разводки
# низа, а не переделки питания.
#
# Третья ревизия: блок ВЕРНУЛСЯ, но не под забор. Усилитель стоит в пустом поле
# под дисплеем, у зарядника (VSYS рядом), а от кодека к нему идёт одна линия
# `HPOUTL` — под разъёмом шлейфа, рядом с `GPADC0`. Через забор — ноль цепей.
FITTED = True


def main():
    s = Sheet(root_uuid(), 5, FRAME)
    if not FITTED:
        s.note("В ПЕРВОЙ РЕВИЗИИ БЛОКА НЕТ — см. FITTED в block05_audio.py",
               (393.7, 165.1))
        s.note("причина в разводке: усилитель под забором из полос", (393.7, 172.72))
        s.note("крестовины, кодек над ним — семь цепей поперёк и", (393.7, 180.34))
        s.note("четырнадцать заклёпок вручную из двадцати двух", (393.7, 187.96))
        s.note("кодек внутри F133 остаётся, питание и развязка тоже", (393.7, 195.58))
        write(s)
        return 0
    inputs(s)
    u = amp(s)
    shutdown(s, u)
    speaker(s, u)
    feedback(s)
    notes(s)
    write(s)
    return 0


if __name__ == "__main__":
    sys.exit(main())
