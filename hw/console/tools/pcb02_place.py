#!/usr/bin/env python3
"""Посадка механики: то, у чего нет свободы размещения.

Скрипт только двигает уже импортированные из схемы корпуса — ничего не создаёт
и не удаляет, поэтому повторный прогон безопасен и идемпотентен. Каждый
поставленный корпус блокируется (`locked`), чтобы не уехал при ручной правке.

Координаты — от левого верхнего угла платы, там же вспомогательный ноль.
Обоснование чисел — blocks/10-mech.md §6.

Порядок работы:
    1. python3 hw/console/tools/pcb01_outline.py     # контур и крепёж
    2. в KiCad: Update PCB from Schematic (F8)       # CLI для этого нет
    3. python3 hw/console/tools/pcb01_outline.py     # F8 сносит крепёж `H*`
    4. python3 hw/console/tools/pcb00_sync.py        # корпуса под схему
    5. python3 hw/console/tools/pcb02_place.py       # эта посадка
    6. python3 hw/console/tools/pcb03_blocks.py      # черновая раскладка блоков
"""
import re
from pathlib import Path

import pcbnew

ROOT = Path(__file__).resolve().parent.parent
BOARD = ROOT / "console.kicad_pcb"

OX, OY = 50.0, 40.0            # то же начало, что в pcb01_outline.py
ARM = 7.5                      # шаг в кресте, снят с платы v1

LEFT = (17.5, 37.0)
RIGHT = (138.5, 37.0)

# ref, x, y, поворот, сторона ("F" — лицо платы)
#
# Крест слева — как на v1. Справа A и B поставлены В РЯД по горизонтали, как на
# оригинальном контроллере NES: играем в основном ими, и держать их на одной
# линии удобнее, чем по диагонали. C и D — сверху и снизу.
PLACES = [
    ("SW101", LEFT[0],        LEFT[1] - ARM,  0, "F"),   # UP
    ("SW102", LEFT[0],        LEFT[1] + ARM,  0, "F"),   # DOWN
    ("SW103", LEFT[0] - ARM,  LEFT[1],        0, "F"),   # LEFT
    ("SW104", LEFT[0] + ARM,  LEFT[1],        0, "F"),   # RIGHT

    ("SW110", RIGHT[0],       RIGHT[1] - ARM, 0, "F"),   # D — верх
    ("SW109", RIGHT[0],       RIGHT[1] + ARM, 0, "F"),   # C — низ
    ("SW108", RIGHT[0] - ARM, RIGHT[1],       0, "F"),   # B — слева
    ("SW107", RIGHT[0] + ARM, RIGHT[1],       0, "F"),   # A — справа

    # SELECT и START под панелью. y = 69, а не 66: кнопка 6 x 6 на 66 заняла бы
    # 63..69, а панель доходит до 64.28 — толкатель упёрся бы в стекло.
    ("SW105", 66.0, 69.0, 0, "F"),                       # SELECT
    ("SW106", 90.0, 69.0, 0, "F"),                       # START

    # Разъём шлейфа — на ЛИЦЕ, под панелью, окном влево (поворот 90°).
    # Хвост выходит из левого торца панели (x = 35.97), заворачивается на её
    # изнанку и идёт вправо; вылет по изнанке 43.72 ± 0.5, то есть кончик
    # достаёт до x ≈ 79.7. Рот разъёма при центре 75.0 приходится на x ≈ 72,
    # шлейф входит на ~4.5 мм — остаётся около 3 мм слабины, чтобы хвост не
    # работал внатяг. По вертикали — на оси панели: её центр y = 37.0, ось
    # хвоста смещена от неё всего на 0.77 (спека, стр. 4), это в пределах
    # податливости шлейфа. Разбор поворотов и обратной нумерации — §7.2.1.
    ("J601", 75.0, 37.0, 90, "F"),
]

# ------------------------------------------------------------- торцы
#
# Распределение торцов — 10-mech.md §5. Коротко, почему так:
#
#   верх   — USB-C и слот microSD. Наверху же по схеме сидят блоки питания и
#            хранения (выводы 101…117 и 7…19 выходят из F133 вверх и влево),
#            и главное — руки держат плату за левый и правый края, сверху и
#            снизу пальцев нет, торчащему кабелю и карте они не мешают;
#   верх-лево — движок питания, под указательным пальцем левой руки;
#   низ    — служебное: UART, динамик, разъём банки, RESET и FEL.
#
# `edge` — каким краем деталь прижимается к контуру: "T" верх, "B" низ.
# Координату вдоль этого края задаём, поперёк её считает сам скрипт по
# courtyard, чтобы корпус встал вровень с резом.
# Последнее число — отступ от реза внутрь платы.
EDGES = [
    # Всё торчащее и всё высокое обязано стоять ВНЕ габарита панели: под ней
    # просвет 2.0 мм, туда влезает только мелочь. Верхняя и нижняя полосы и
    # боковые поля — единственные места, где это возможно.
    ("J401",  26.0, "T", 180, "F", 0.0),   # microSD, карта входит сверху
    ("SW1",   13.0, "T", 180, "F", 0.4),   # движок, рычаг наружу
    # USB-C прямо над выводами 112…115: на лице банк питания и USB (101…117)
    # выходит у F133 **вверх**, на y = 29.4. Пара `D+`/`D−` идёт напрямую.
    # Розетка на нижнем торце, прямо под выводами 112…115: у развёрнутого
    # корпуса банк питания и USB выходит вниз, на y = 45.6. x = 104 — просвет
    # между площадкой START (86…94) и правым краем.
    ("J301", 104.0, "B",   0, "F", 0.0),
    ("J901",  20.0, "B",   0, "F", 0.0),   # UART
    ("J501",  36.0, "B",   0, "F", 0.0),   # динамик
    ("J1",   130.0, "B",   0, "F", 0.0),   # банка — рядом с зарядником
]

# Служебные площадки и F133. FEL и RESET — «где удобно разводке», поставлены
# в нижнюю полосу, подальше от SELECT/START на лице.
FIXED = [
    # F133 на ЛИЦЕ, как и всё остальное. Ради этого просвет под панелью поднят
    # с 1.4 до 2.0 мм: корпус 1.55, самая рослая деталь под стеклом — TP4056,
    # 1.75. Взамен шина дисплея идёт к `J601` по одному слою, без единой
    # переходной; раньше их требовалось 36 (10-mech.md §4.1).
    # Поворот 180° и вправо от `J601`. На лице шина дисплея `PD` выходит у
    # F133 вниз и вправо; развёрнутый корпус смотрит ею вверх и ВЛЕВО — то
    # есть прямо на разъём. Заодно питание и USB уходят вниз, к нижнему торцу,
    # а хранение и такт — вправо, в поле за панелью.
    ("U1",    98.0, 35.0, 180, "F"),
    # UART наружу не смотрит, торец ему не нужен — ставим внутрь платы, слева
    # от корпуса, рядом с выводами `PE` отладки. На нижнем торце он налезал на
    # крепёжное отверстие H4.
        ("JP1",    6.0, 12.0,   0, "F"),   # RESET — пара площадок
    ("JP301",  6.0, 16.0,   0, "F"),   # FEL — пара площадок
]


def mm(v):
    return pcbnew.FromMM(v)


BOARD_H = 74.0


def put(board, ref, x, y, rot, side):
    fp = board.FindFootprintByReference(ref)
    if fp is None:
        return None
    if fp.IsFlipped() != (side == "B"):
        fp.Flip(fp.GetPosition(), False)
    fp.SetPosition(pcbnew.VECTOR2I(mm(OX + x), mm(OY + y)))
    fp.SetOrientationDegrees(rot)
    fp.SetLocked(True)
    return fp


def flush(board, ref, x, edge, rot, side, inset=0.0):
    """Прижать корпус к торцу платы по courtyard.

    Ставим предварительно, смотрим, где оказался courtyard, и сдвигаем на
    разницу. Так не приходится держать в голове, где у каждого разъёма начало
    координат — у microSD оно, например, смещено от габарита на 2.5 мм.
    """
    fp = put(board, ref, x, BOARD_H / 2, rot, side)
    if fp is None:
        return None
    cy = fp.GetCourtyard(pcbnew.B_CrtYd if side == "B" else pcbnew.F_CrtYd)
    bb = cy.BBox()
    top = pcbnew.ToMM(bb.GetTop()) - OY
    bot = pcbnew.ToMM(bb.GetBottom()) - OY
    y = BOARD_H / 2 + (inset - top if edge == "T" else BOARD_H - inset - bot)
    fp.SetPosition(pcbnew.VECTOR2I(mm(OX + x), mm(OY + y)))
    return fp


def main():
    board = pcbnew.LoadBoard(str(BOARD))
    done, miss = 0, []
    for ref, x, y, rot, side in PLACES + FIXED:
        if put(board, ref, x, y, rot, side) is None:
            miss.append(ref)
        else:
            done += 1
    for ref, x, edge, rot, side, inset in EDGES:
        if flush(board, ref, x, edge, rot, side, inset) is None:
            miss.append(ref)
        else:
            done += 1
    board.Save(str(BOARD))
    print(f"поставлено и заблокировано: {done}")
    if miss:
        print("НЕ НАЙДЕНЫ на плате:", ", ".join(miss))


if __name__ == "__main__":
    main()
