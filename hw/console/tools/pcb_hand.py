def main():
    board = pcbnew.LoadBoard(str(BOARD))
    ni = board.GetNetInfo()

    # Снимаем прежде проложенное по этим цепям, кроме лучей выхода из
    # гребёнок: луч короткий и начинается на самой площадке.
    gone = 0
    for t in list(board.GetTracks()):
        if t.GetNetname() not in ROUTES:
            continue
        if isinstance(t, pcbnew.PCB_VIA):
            board.RemoveNative(t)
            gone += 1
            continue
        s, e = t.GetStart(), t.GetEnd()
        ln = max(abs(s.x - e.x), abs(s.y - e.y))
        if ln > pcbnew.FromMM(3.0):
            board.RemoveNative(t)
            gone += 1

    if "--clean" in sys.argv:
        board.Save(str(BOARD))
        print(f"снято отрезков: {gone}; лучи оставлены")
        return

    laid = 0
    for name, polys in ROUTES.items():
        net = ni.GetNetItem(name)
        if net is None:
            print(f"  ЦЕПИ НЕТ НА ПЛАТЕ: {name}")
            continue
        for poly in polys:
            for (x1, y1), (x2, y2) in zip(poly, poly[1:]):
                t = pcbnew.PCB_TRACK(board)
                t.SetStart(pcbnew.VECTOR2I(pcbnew.FromMM(x1),
                                           pcbnew.FromMM(y1)))
                t.SetEnd(pcbnew.VECTOR2I(pcbnew.FromMM(x2),
                                         pcbnew.FromMM(y2)))
                t.SetWidth(pcbnew.FromMM(WIDTH))
                t.SetLayer(pcbnew.F_Cu)
                t.SetNet(net)
                board.Add(t)
                laid += 1

    board.Save(str(BOARD))
    print(f"снято прежних отрезков: {gone}, положено своих: {laid}, "
          f"цепей: {len(ROUTES)}")
    print("переходных не ставили ни одного — всё по лицу")


if __name__ == "__main__":
    main()
