def main():
    board = pcbnew.LoadBoard(str(BOARD))
    ni = board.GetNetInfo()

    # Снимаем прежде проложенное по этим цепям, кроме лучей выхода из
    # гребёнок: луч короткий и начинается на самой площадке.
    gone = 0
    for g in list(board.Groups()):
        if g.GetName() == HAND_GROUP:
            board.RemoveNative(g)
    ours = {net_of(k) for k in ROUTES} | set(BACK) | set(VIAS)
    for t in list(board.GetTracks()):
        if t.GetNetname() not in ours:
            continue
        if isinstance(t, pcbnew.PCB_VIA):
            board.RemoveNative(t)
            gone += 1
            continue
        s, e = t.GetStart(), t.GetEnd()
        ln = max(abs(s.x - e.x), abs(s.y - e.y))
        if ln > pcbnew.FromMM(3.0):
            board.RemoveNative(t)
            gone += 1

    if "--clean" in sys.argv:
        board.Save(str(BOARD))
        print(f"снято отрезков: {gone}; лучи оставлены")
        return

    # Ручные отрезки лежат в группе `hand`: по ней трассировщик узнаёт их и не
    # снимает. Без метки он снимал всю незапертую медь цепи, которую
    # доразводит, — и `VBUS`, недоведённый только у розетки, терял весь
    # периметр. Запереть (`locked`) нельзя: запертый отрезок трассировщик
    # считает лучом веера и ставит перед его концом коридор выхода.
    group = pcbnew.PCB_GROUP(board)
    group.SetName(HAND_GROUP)
    board.Add(group)

    def netitem(name):
        net = ni.GetNetItem(name)
        if net is None:
            print(f"  ЦЕПИ НЕТ НА ПЛАТЕ: {name}")
        return net

    laid = 0
    layers = [(ROUTES, pcbnew.F_Cu), (BACK, pcbnew.B_Cu)]
    for table, layer in layers:
        for key, polys in table.items():
            net = netitem(net_of(key))
            if net is None:
                continue
            for poly in polys:
                for (x1, y1), (x2, y2) in zip(poly, poly[1:]):
                    t = pcbnew.PCB_TRACK(board)
                    t.SetStart(pcbnew.VECTOR2I(pcbnew.FromMM(x1),
                                               pcbnew.FromMM(y1)))
                    t.SetEnd(pcbnew.VECTOR2I(pcbnew.FromMM(x2),
                                             pcbnew.FromMM(y2)))
                    t.SetWidth(pcbnew.FromMM(WIDE.get(key, WIDTH)))
                    t.SetLayer(layer)
                    t.SetNet(net)
                    board.Add(t)
                    group.AddItem(t)
                    laid += 1

    n_via = 0
    for name, pts in VIAS.items():
        net = netitem(name)
        if net is None:
            continue
        for x, y in pts:
            v = pcbnew.PCB_VIA(board)
            v.SetPosition(pcbnew.VECTOR2I(pcbnew.FromMM(x), pcbnew.FromMM(y)))
            v.SetWidth(pcbnew.FromMM(0.7))          # как у трассировщика
            v.SetDrill(pcbnew.FromMM(0.4))
            v.SetLayerPair(pcbnew.F_Cu, pcbnew.B_Cu)
            v.SetNet(net)
            board.Add(v)
            group.AddItem(v)
            n_via += 1

    board.Save(str(BOARD))
    print(f"снято прежних отрезков: {gone}, положено своих: {laid}, "
          f"цепей: {len(ours)}")
    print(f"переходных своих: {n_via}"
          + ("" if n_via else " — всё по лицу"))


if __name__ == "__main__":
    main()
