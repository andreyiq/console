#!/usr/bin/env python3
"""Дорожки, проложенные руками, — таблицей, а не мышью.

Зачем. Трассировщик ищет путь для каждой связи по отдельности и о полосах не
знает: он честно находит дорогу, но первая же цепь ложится посреди чужой
полосы, и следующая упирается. На блоке дисплея это видно как «нет пути» там,
где места полно, — сосед запечатал.

Человек делает иначе: назначает каждому сигналу свою полосу, ведёт их
параллельно и сводит веером у гребёнки. Здесь то же самое, только полосы
записаны числами, а не нарисованы мышью, — тогда их можно перечитать,
поправить одну и прогнать заново.

Правила, по которым выбраны числа:

* дорожка 0.2, зазор 0.2 — значит между осями соседних дорожек 0.4;
* от оси дорожки до края площадки 0.3 (0.1 своей половины + 0.2 зазора);
* повороты только 45°, иначе кислотная ванна подтравливает острый угол;
* две параллельные диагонали 45° расходятся по `x+y` не меньше чем на 0.57
  (это 0.4 по нормали), поэтому смещения соседних диагоналей берутся 0.7–1.0;
* к гребёнке чипа подходим на y своей площадки: лучи соседей идут параллельно
  в 0.4, а поперёк их резать нельзя — они кончаются на 137.65 либо 138.45,
  поэтому всё, что идёт поперёк, держим левее 137.35.

Запуск:  python3 hw/console/tools/pcb_hand.py         — проложить
         python3 hw/console/tools/pcb_hand.py --clean — снять только свои
"""
import sys
from pathlib import Path

import pcbnew

ROOT = Path(__file__).resolve().parent.parent
BOARD = ROOT / "console.kicad_pcb"

WIDTH = 0.2

# Каждая цепь — список ломаных. Точки в миллиметрах, слой лицевой.
# Первая точка каждой ломаной должна попадать в уже существующую медь
# (площадку или конец луча), иначе кусок повиснет.
ROUTES = {
    # --- верхняя шестёрка: разъём -> чип -------------------------------
    # CS идёт выше всех: он верхний и на шлейфе, и на чипе (вывод 64 в углу,
    # луч которого смотрит вверх). Поэтому уходит на y=65 и идёт над корпусом.
    "LCD-CS": [
        [(120.10, 71.25), (121.50, 71.25), (127.75, 65.00), (141.80, 65.00),
         (141.80, 65.45)],
        [(129.00, 65.00), (129.00, 63.50)],          # отвод к подтяжке R607
    ],
    # DC — вторая сверху; ныряет под CS параллельной диагональю (расход 1.0
    # по x+y) и идёт полосой 68.6 до самой гребёнки.
    "LCD-DC": [
        [(120.90, 71.75), (122.00, 71.75), (125.15, 68.60), (136.00, 68.60),
         (137.00, 69.60), (137.65, 69.60)],
    ],
    # SCL кончается в последовательном резисторе R603, дальше цепь другая.
    "LCD-SCL": [
        [(120.10, 72.25), (122.50, 72.25), (123.75, 71.00), (131.00, 71.00)],
    ],
    "SPI1-CLK": [
        [(133.00, 71.00), (136.00, 71.00), (137.00, 70.00), (138.45, 70.00)],
    ],
    # RD дальше резистора не идёт: в четырёхпроводном SPI он не используется,
    # R606 просто держит его в единице. Поэтому полоса короткая.
    "LCD-RD": [
        [(120.90, 72.75), (121.10, 72.75), (121.35, 72.80), (126.00, 72.80)],
    ],
    "LCD-SDA": [
        [(120.10, 73.25), (122.00, 73.25), (123.25, 74.50), (131.00, 74.50)],
    ],
    "SPI1-MOSI": [
        [(133.00, 74.50), (133.80, 74.50), (137.50, 70.80), (137.65, 70.80)],
    ],
    # RST ныряет сразу: если он пойдёт прямо, его пересечёт спуск SDA.
    "LCD-RST": [
        [(120.90, 74.25), (121.00, 74.25), (123.15, 76.40), (133.20, 76.40),
         (138.20, 71.40), (138.20, 71.20), (138.45, 71.20)],
        [(128.00, 76.40), (128.00, 77.50), (127.00, 78.50)],   # отвод к R608
    ],
    # --- низ: подсветка и страп ---------------------------------------
    "LCD-LEDA": [
        [(120.10, 83.25), (120.35, 83.25), (120.60, 83.00), (129.00, 83.00)],
    ],
    "LCD-LEDK": [
        [(120.90, 83.75), (121.50, 83.75), (121.50, 84.75)],
        [(120.10, 84.25), (121.50, 84.25)],
        [(120.90, 84.75), (121.50, 84.75)],
        [(121.50, 84.75), (122.75, 86.00), (127.06, 86.00)],
    ],
    # Два места, мимо которых надо пройти, и оба невидны на общем плане:
    # луч питания вывода 39 тянется вправо до x=120.9 на y=86.25, а крепёжная
    # площадка разъёма (земля) занимает прямоугольник 120.5…122.3 / 87.55…89.75.
    # Первый заход шёл по x=120.6 и пересёк луч, а диагональю задел площадку.
    "LCD-IM": [
        [(120.10, 85.75), (121.50, 85.75), (121.50, 86.75)],
        [(120.10, 86.75), (121.50, 86.75)],
        [(121.50, 86.75), (123.00, 86.75), (125.75, 89.50), (129.00, 89.50)],
    ],
    # Подсветка: затвор у чипа внизу (PB3), ключ внизу платы — дорожка идёт
    # вверх ЛЕВЕЕ гребёнки (x=137.0), потому что лучи соседних выводов
    # кончаются на 137.65 и поперёк них не пройти.
    "LCD-BL": [
        [(128.94, 86.95), (129.89, 86.00), (137.00, 86.00), (137.00, 76.80),
         (138.45, 76.80)],
        [(137.00, 86.00), (137.00, 87.50), (136.00, 88.50)],   # отвод к R602
    ],
}


def main():
    board = pcbnew.LoadBoard(str(BOARD))
    ni = board.GetNetInfo()

    # Снимаем прежде проложенное по этим цепям, кроме лучей выхода из
    # гребёнок: луч короткий и начинается на самой площадке.
    gone = 0
    for t in list(board.GetTracks()):
        if t.GetNetname() not in ROUTES:
            continue
        if isinstance(t, pcbnew.PCB_VIA):
            board.RemoveNative(t)
            gone += 1
            continue
        s, e = t.GetStart(), t.GetEnd()
        ln = max(abs(s.x - e.x), abs(s.y - e.y))
        if ln > pcbnew.FromMM(3.0):
            board.RemoveNative(t)
            gone += 1

    if "--clean" in sys.argv:
        board.Save(str(BOARD))
        print(f"снято отрезков: {gone}; лучи оставлены")
        return

    laid = 0
    for name, polys in ROUTES.items():
        net = ni.GetNetItem(name)
        if net is None:
            print(f"  ЦЕПИ НЕТ НА ПЛАТЕ: {name}")
            continue
        for poly in polys:
            for (x1, y1), (x2, y2) in zip(poly, poly[1:]):
                t = pcbnew.PCB_TRACK(board)
                t.SetStart(pcbnew.VECTOR2I(pcbnew.FromMM(x1),
                                           pcbnew.FromMM(y1)))
                t.SetEnd(pcbnew.VECTOR2I(pcbnew.FromMM(x2),
                                         pcbnew.FromMM(y2)))
                t.SetWidth(pcbnew.FromMM(WIDTH))
                t.SetLayer(pcbnew.F_Cu)
                t.SetNet(net)
                board.Add(t)
                laid += 1

    board.Save(str(BOARD))
    print(f"снято прежних отрезков: {gone}, положено своих: {laid}, "
          f"цепей: {len(ROUTES)}")
    print("переходных не ставили ни одного — всё по лицу")


if __name__ == "__main__":
    main()
