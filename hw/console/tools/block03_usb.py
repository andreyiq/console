#!/usr/bin/env python3
"""Рисует блок 3 «USB и FEL» в hw/console/console.kicad_sch.

Запуск:  python3 hw/console/tools/block03_usb.py

Скрипт идемпотентный: перед вставкой выкидывает из схемы всё, что лежит внутри
рамки блока 3, а рамку и заголовок не трогает.

Все решения — из hw/console/blocks/03-usb.md, ссылка на раздел лежит в поле
`Источник` каждого компонента.

Блок маленький — пять деталей, — поэтому здесь, в отличие от блоков 4 и 6,
разъём соединяется с защитной сборкой проводом, а не через метку: провод
короткий и видно, что защита стоит именно между разъёмом и чипом. Метками
уходят только две цепи, которым дальше через весь лист: `USB0-DM`/`USB0-DP`.

Метки у ног самого F133 ставит блок 8 (правило из 07-clock-reset.md §6.4).

Общая машинерия — в tools/kicadsch.py.
"""

import sys

from kicadsch import Sheet, root_uuid, write

# Рамка блока 3 из tools/scaffold.py — по ней чистится старое содержимое.
FRAME = (456.0, 20.0, 574.0, 130.0)

DOC = "03-usb.md"

# Все координаты кратны 1.27: иначе ERC ловит вывод детали «не на сетке».
JX, JY = 474.98, 57.15      # разъём
DX, DY = 524.51, 57.15      # защитная сборка
TIE = 497.84                # где сходятся половинки D+ и D−
OUT = 541.02                # метки USB0-DM / USB0-DP


def connector(s):
    """Розетка USB-C: питание, земля, обе половинки D+/D−, CC и SBU (§6.2)."""
    j = s.sym("Connector:USB_C_Receptacle_USB2.0_16P", "J301", "USB-C 16P",
              JX, JY, 0, src=f"{DOC} §6.2", lcsc="C165948",
              fp="Connector_USB:USB_C_Receptacle_HRO_TYPE-C-31-M-12",
              rdx=0.0, rdy=-21.59, vdx=0.0, vdy=-19.05)

    # VBUS уходит в блок 2 на вход TP4056 — символом питания, не проводом
    vb = (JX + 15.24, JY - 22.86)
    s.wire(j.pin("A4"), vb)
    s.power("power:VBUS", vb)

    # Выводы разъёма для ERC — passive, источником питания он их не считает,
    # поэтому цепь `VBUS` остаётся «не запитанной», хотя питание приходит
    # именно отсюда. Флаг стоит у разъёма — там, где физически источник.
    # В плату не идёт (ссылка `#FLG`), см. 02-power.md §6.7.
    s.wire(vb, (vb[0] - 7.62, vb[1]))
    s.power("power:PWR_FLAG", (vb[0] - 7.62, vb[1]), 180, ref="#FLG301")
    s.junction(vb)

    # Земля корпуса и земля сигнальная сводятся под разъёмом в один узел:
    # так же у обеих референсных плат (§3.1, §4.1)
    s.wire(j.pin("A1"), (JX, JY + 31.75))
    s.wire(j.pin("S1"), (JX - 7.62, JY + 31.75), (JX, JY + 31.75))
    s.junction((JX, JY + 31.75))
    s.wire((JX, JY + 31.75), (JX, JY + 34.29))
    s.power("power:GND", (JX, JY + 34.29))

    # Кабель переворачивается, поэтому DP1+DP2 и DN1+DN2 — одна линия (§2.4).
    # Верхняя половинка заводится углом на нижнюю, точка обязательна.
    for a, b, to in (("A7", "B7", DX - 5.08), ("B6", "A6", DX - 5.08)):
        (ax, ay), (bx, by) = j.pin(a), j.pin(b)
        s.wire((ax, ay), (TIE, ay), (TIE, by))
        s.wire((bx, by), (TIE, by))
        s.junction((TIE, by))
        s.wire((TIE, by), (to, by))

    # SBU в USB 2.0 не используется — ни у MangoPi, ни у Xassette (§6.6)
    for num in ("A8", "B8"):
        s.no_connect(j.pin(num))

    return j


def cc(s, j):
    """Rd 5.1k с каждого контакта CC на землю — порт потребитель (§6.3).

    Столбики уходят **вверх**: справа от разъёма всё занято линиями данных, а
    сверху свободно. Ближний столбик берёт верхний контакт (`CC1`): его
    вертикальный отвод кончается выше, чем идёт горизонталь дальнего, и
    провода нигде не пересекаются.
    """
    for pin, x, ref in (("A5", 500.38, "R301"), ("B5", 513.08, "R302")):
        px, py = j.pin(pin)
        s.wire((px, py), (x, py), (x, 39.37))
        s.sym("Device:R", ref, "5.1k", x, 35.56, 0, src=f"{DOC} §6.3",
              rdx=-2.54, vdx=-2.54, just="right")
        s.wire((x, 31.75), (x, 29.21))
        s.power("power:GND", (x, 29.21), 180)


def esd(s):
    """USBLC6-2SC6 в разрыв обеих линий, как можно ближе к разъёму (§6.4).

    Выводы 1 и 6 — один канал, 3 и 4 — второй, поэтому деталь стоит именно в
    разрыве, а не отводом. Вывод 5 обязан сидеть на VBUS: без него верхним
    диодам некуда сбрасывать разряд (§2.5).
    """
    d = s.sym("Power_Protection:USBLC6-2SC6", "D301", "USBLC6-2SC6",
              DX, DY, 0, src=f"{DOC} §6.4", lcsc="C2687116",
              rdx=6.35, rdy=6.35, vdx=6.35, vdy=8.89)

    s.wire(d.pin("5"), (DX, DY - 12.7))
    s.power("power:VBUS", (DX, DY - 12.7))
    s.wire(d.pin("2"), (DX, DY + 11.43))
    s.power("power:GND", (DX, DY + 11.43))

    for num, net in (("6", "USB0-DM"), ("4", "USB0-DP")):
        x, y = d.pin(num)
        s.wire((x, y), (OUT, y))
        s.glabel(net, (OUT, y), 0)


def fel(s):
    """Кнопка FEL: SPI0-MOSI на землю, без резистора (§6.5).

    Резистора в цепи быть не может — он образовал бы с выходным каскадом
    делитель, и уровень не дошёл бы до VIL = 0.99 В.
    """
    x, y = 486.41, 102.87
    s.glabel("SPI0-MOSI", (JX, y), 180)
    s.wire((JX, y), (x, y))

    sw = s.sym("Switch:SW_Push", "SW301", "FEL", x, y + 5.08, 90,
               src=f"{DOC} §6.5",
               fp="Button_Switch_SMD:SW_SPST_PTS645Sx43SMTR92",
               rdx=2.54, rdy=-1.27, vdx=2.54, vdy=1.905)
    s.wire(sw.pin("1"), (x, y + 12.7))
    s.power("power:GND", (x, y + 12.7))


def notes(s):
    """Подписи — в свободном правом нижнем углу блока.

    Ширина у шрифта 1.6 выходит около 1.4 мм на знак, а от начала подписи до
    правой рамки 74 мм: длиннее полусотни знаков строка вылезает наружу.
    """
    s.note("CC1 и CC2 по 5.1k вниз — порт потребитель", (497.84, 88.9))
    s.note("USB1 (112, 113) не используется", (497.84, 96.52))
    s.note("кнопка FEL прижимает SPI0-MOSI к земле", (497.84, 104.14))


def main():
    s = Sheet(root_uuid(), 3, FRAME)
    j = connector(s)
    cc(s, j)
    esd(s)
    fel(s)
    notes(s)
    write(s)
    return 0


if __name__ == "__main__":
    sys.exit(main())
