#!/usr/bin/env python3
"""Рисует блок 8 «Развязка и контрольные точки» в hw/console/console.kicad_sch.

    python3 hw/console/tools/block08_decoupling.py

Решения и номиналы — blocks/08-decoupling.md, поле `Источник` каждой детали
указывает раздел. Машинерия — tools/kicadsch.py.

Блок состоит из двух частей, и лежат они в разных местах листа.

1. **Внутри рамки** — конденсаторы, резисторы и контрольные точки: три ряда по
   рельсам плюс два островка справа (неиспользуемые узлы и аналог кодека).
2. **Вокруг корпуса F133** — символ питания или метка у каждого вывода,
   который блок закрывает. Рамка блока далеко, поэтому на каждый такой вывод
   заводится своя узкая зона (`Sheet.zone`): при перезапуске блок вычищает
   ровно свои ноги и не трогает соседние, которые достанутся другим блокам.

Развязка соединяется с выводами не проводом, а по имени цепи — иначе к
128-выводному корпусу пришлось бы тянуть двадцать проводов через весь лист
(README, «Как соединяется»).

Про раскладку. Глобальная метка рисуется стрелкой длиной под текст: `AVCC` —
это 7 мм, `VCC-TVOUT` — 12. Вертикальная метка поэтому съедает весь просвет
между рядами и налезает на соседний ряд. Отсюда правило блока: **у рельсовых
рядов концы — символы питания (они короткие), а там, где нужна метка, колонки
ставятся с шагом 12.7 мм и метка кладётся горизонтально.**
"""

import sys

from kicadsch import Sheet, root_uuid, write, lib_pins

DOC = "08-decoupling.md"
FRAME = (226.0, 278.0, 372.0, 348.0)

U1 = (297.18, 203.2)          # положение F133 на листе, tools/scaffold.py

X0, PITCH = 236.22, 10.16     # сетка рельсовых колонок
ROWS = (284.48, 307.34, 331.47)  # верх колонки: +3V3, +1V8, +0V9

AX, AP, AY = 302.26, 12.7, 284.48    # островок «неиспользуемые узлы»
BX, BY = 307.34, 306.07              # островок «аналог кодека»

# Направление отвода от вывода и угол метки по сторонам корпуса. Длина отвода
# у каждой стороны своя, и обе поправки против интуиции.
#
# Метка рисуется **от точки привязки по направлению своего поворота**, и
# длина её заметная: «+1V8» это 7 мм, «LCD-DB11» — почти 14. Отсюда две
# поправки к длине отвода, обе против интуиции.
#
# Справа текст уходит от корпуса вправо, и отвод 5 мм выносил хвост метки за
# левую границу рамки блока 6 (x = 378) — поэтому 2.54.
#
# Внизу поворот 270°, то есть текст растёт вверх, назад к выводу. Отвод обязан
# быть длиннее самой метки, иначе её рамка накрывает номер вывода и заходит в
# корпус: рельсовым меткам хватает 8.89, шине дисплея нужно 13.97 (см. PINS).
# Длиннее — уже нельзя: заголовок блока стоит на 276.73.
DIR = {"L": (-1.0, 0.0), "R": (1.0, 0.0), "T": (0.0, -1.0), "B": (0.0, 1.0)}
ROT_LBL = {"L": 180, "R": 0, "T": 90, "B": 270}
STEP = {"L": 5.08, "R": 2.54, "T": 5.08, "B": 8.89}

# Выводы F133, которые закрывает блок: номер, сторона, имя цепи, раздел
# документа (§6.1 рельсы, §6.3 аналог, §6.4 неиспользуемые узлы,
# §6.5 контрольная точка, §6.6 чужие цепи) и, если он отличается от
# принятого для стороны, отвод в миллиметрах.
PINS = [
    # левая сторона: PLL, DCXO, RTC, LDO
    ("20", "L", "+1V8", "§6.1"),
    ("21", "L", "REFCLK", "§6.5"),
    ("22", "L", "DXOUT", "§6.6"),
    ("23", "L", "DXIN", "§6.6"),
    ("24", "L", "X32KOUT", "§6.6"),
    ("25", "L", "X32KIN", "§6.6"),
    ("26", "L", "+1V8", "§6.1"),
    ("27", "L", "RESET", "§6.6"),
    ("28", "L", "LDOA-OUT", "§6.4"),
    ("29", "L", "+3V3", "§6.1"),
    ("30", "L", "LDOB-OUT", "§6.4"),
    # низ: PE, SYS, DRAM
    ("34", "B", "+3V3", "§6.1"),
    ("46", "B", "+0V9", "§6.1"),
    ("47", "B", "DZQ", "§6.4"),
    ("48", "B", "+1V8", "§6.1"),
    ("49", "B", "+1V8", "§6.1"),
    ("50", "B", "+1V8", "§6.1"),
    ("51", "B", "+0V9", "§6.1"),
    # правая сторона: PD, TVOUT, PB, аудиокодек
    ("65", "R", "+1V8", "§6.1"),
    ("66", "R", "+3V3", "§6.1"),
    ("77", "R", "VCC-TVOUT", "§6.4"),
    ("81", "R", "+0V9", "§6.1"),
    ("83", "R", "+3V3", "§6.1"),
    ("89", "R", "AVCC", "§6.3"),
    ("90", "R", "VRA2", "§6.3"),
    ("91", "R", "AGND", "§6.3"),
    ("92", "R", "VRA1", "§6.3"),
    # верх: наушники, CORE, PG, термопад
    ("97", "T", "AVCC", "§6.3"),
    ("116", "T", "+0V9", "§6.1"),
    ("117", "T", "+0V9", "§6.1"),
    ("128", "T", "+3V3", "§6.1"),
    ("EPAD", "T", "GND", "§6.1"),
]

# Весь банк PD — шина дисплея (06-display.md §6.1 и §2.8). Цепи принадлежат
# блоку 6, но метка у ноги корпуса — обвязка F133, то есть этот блок (§6.6).
# Банк расходуется целиком, все 23 вывода: свободных в нём не остаётся.
PD = {
    52: "LCD-BL", 53: "LCD-CS", 54: "LCD-RD", 55: "LCD-IM", 64: "LCD-RST",
    69: "LCD-DB11", 70: "LCD-DB10",      # PD12/PD13 переставлены в корпусе
    75: "LCD0-CLK", 76: "LCD0-DE",       # WR и RS идут через R603/R604
}
PD.update({56 + i: f"LCD-DB{i}" for i in range(8)})       # PD1..PD8
PD.update({67 + i: f"LCD-DB{8 + i}" for i in range(2)})   # PD10, PD11
PD.update({71 + i: f"LCD-DB{12 + i}" for i in range(4)})  # PD14..PD17

# Снизу отвод втрое длиннее принятого: имена шины по восемь знаков, и метка,
# растущая вверх, иначе накрыла бы номера выводов 52…64. Заголовок блока эти
# тринадцать меток не задевают — он кончается левее вывода 52.
PINS += [(str(n), "B", net, "§6.6 → 06-display.md §6.1", 13.97)
         if n <= 64 else (str(n), "R", net, "§6.6 → 06-display.md §6.1")
         for n, net in sorted(PD.items())]

# Развязка: рельс → (ряд, объёмный номинал, выводы под 0.1 мкФ)
RAILS = [
    ("power:+3V3", 0, ("34", "66", "83", "128")),
    ("power:+1V8", 1, ("20", "26", "48", "49", "50", "65")),
    ("parts:+0V9", 2, ("46", "51", "81", "116", "117")),
]


def pin_xy(num):
    px, py = lib_pins("console:F133-A")[num]
    return (round(U1[0] + px, 4), round(U1[1] - py, 4))


def pwr(s, lib_id, x, y, rot, sect, vdx=0.0, vdy=-5.08, just=None, show=True):
    n = len([i for i in s.items if "#PWR" in i])
    return s.sym(lib_id, f"#PWR8{n:02d}", lib_id.split(":")[1], x, y, rot,
                 src=f"{DOC} {sect}", show_value=show,
                 vdx=vdx, vdy=vdy, rdx=vdx, rdy=vdy, just=just)


# -------------------------------------------------------------- вокруг F133

def at_pins(s):
    """Метка цепи на каждом выводе F133, который берёт блок.

    Именно метка, а не символ питания: выводы корпуса стоят через 2.54 мм, а
    подпись символа питания рисуется поперёк — четыре соседние ноги дают кашу
    из наложенных «+1V8». У метки текст идёт вдоль провода и занимает по
    ширине полтора миллиметра. По той же причине так сделано и у MangoPi.
    """
    for num, side, what, sect, *rest in PINS:
        x, y = pin_xy(num)
        dx, dy = DIR[side]
        step = rest[0] if rest else STEP[side]
        end = (round(x + dx * step, 4), round(y + dy * step, 4))
        s.wire((x, y), end)
        s.glabel(what, end, ROT_LBL[side])
        # Зона чистки — только вокруг этой ноги, уже шага выводов (2.54 мм),
        # чтобы не задеть соседнюю: её будет рисовать другой блок. Вдоль отвода
        # зона всегда не короче 15 мм, даже когда сам отвод куце́е: иначе после
        # правки STEP старые метки остались бы лежать рядом с новыми. Дальше
        # растягивать нельзя — снизу в 21 мм от выводов уже стоят колонки
        # развязки (ROWS[0] = 284.48).
        reach = 15.24
        if side in ("L", "R"):
            s.zone(min(x, x + dx * reach) - 1.0, y - 1.2,
                   max(x, x + dx * reach) + 1.0, y + 1.2)
        else:
            s.zone(x - 1.2, min(y, y + dy * reach) - 1.0,
                   x + 1.2, max(y, y + dy * reach) + 1.0)


# ------------------------------------------------------- три ряда развязки

def part(s, x, y, kind, ref, value, sect):
    """Деталь в колонке: выводы попадают на y-3.81 и y+3.81."""
    return s.sym(kind, ref, value, x, y, 0, src=f"{DOC} {sect}",
                 rdx=2.03, rdy=-1.27, vdx=2.03, vdy=1.905)


def column(s, x, top, source, ref, value, sect,
           kind="Device:C", bottom="power:GND"):
    """Колонка «верхний конец — деталь — нижний конец», высота 12.7 мм."""
    _end(s, x, top, "up", source)
    s.wire((x, top), (x, top + 2.54))
    part(s, x, top + 6.35, kind, ref, value, sect)
    s.wire((x, top + 10.16), (x, top + 12.7))
    _end(s, x, top + 12.7, "down", bottom)


def _end(s, x, y, where, what):
    """Конец колонки: символ питания или горизонтальная глобальная метка."""
    if not what.startswith(("power:", "parts:")):
        s.glabel(what, (x, y), 0)
        return
    gnd = what.endswith("GND")
    rot = (180 if where == "up" else 0) if gnd else (0 if where == "up" else 180)
    pwr(s, what, x, y, rot, "§6.2", show=not gnd,
        vdy=-5.08 if where == "up" else 5.08)


def rails(s):
    """Три ряда: объёмный конденсатор рельсы плюс по 0.1 мкФ на вывод (§6.2)."""
    n = 800
    for lib_id, row, pins in RAILS:
        y = ROWS[row]
        n += 1
        column(s, X0, y, lib_id, f"C{n}", "10u", "§6.2 объём рельсы")
        for i, pin in enumerate(pins):
            n += 1
            column(s, X0 + (i + 1) * PITCH, y, lib_id, f"C{n}", "0.1u",
                   f"§6.2 вывод {pin}")
    # 2.2 мкФ на входе внутренних LDO — вывод 29 сидит на той же +3V3
    column(s, X0 + 5 * PITCH, ROWS[0], "power:+3V3", "C819", "2.2u",
           "§6.2 вывод 29")


# --------------------------------------------- островок неиспользуемых узлов

def island_a(s):
    """Вывод 77, внутренние LDO, вывод 47 и контрольная точка кварца.

    Колонки с шагом 12.7 мм — под горизонтальную метку сверху; у самой длинной
    (`VCC-TVOUT`) текст 12 мм, поэтому шаг меньше делать нельзя.
    """
    x = AX
    # 77: +3V3 через 0 Ω, чтобы узел можно было обесточить (§6.4)
    pwr(s, "power:+3V3", x, AY, 0, "§6.4")
    s.wire((x, AY), (x, AY + 2.54))
    part(s, x, AY + 6.35, "Device:R", "R801", "0", "§6.4")
    s.wire((x, AY + 10.16), (x, AY + 12.7))
    s.glabel("VCC-TVOUT", (x, AY + 12.7), 0)
    s.wire((x, AY + 12.7), (x, AY + 15.24))
    pwr(s, "power:PWR_FLAG", x, AY + 15.24, 180, "§6.4", show=False)

    column(s, AX + AP, AY, "VCC-TVOUT", "C820", "0.1u", "§6.2 вывод 77")
    column(s, AX + 2 * AP, AY, "LDOA-OUT", "C821", "2.2u", "§6.4 вывод 28")
    column(s, AX + 3 * AP, AY, "LDOB-OUT", "C822", "2.2u", "§6.4 вывод 30")

    # контрольная точка на выводе 21 — требование 07-clock-reset.md §6.4
    x = AX + 4 * AP
    s.glabel("REFCLK", (x, AY), 0)
    s.wire((x, AY), (x, AY + 5.08))
    s.sym("Connector:TestPoint", "TP801", "REFCLK", x, AY + 5.08, 180,
          src=f"{DOC} §6.5", show_value=False, rdx=0.0, rdy=5.08, just=None)

    column(s, AX + 5 * AP, AY, "DZQ", "R802", "240", "§6.4 вывод 47",
           kind="Device:R")


def bus(s, y, taps, junctions):
    """Горизонтальная шина: провод разрезан у каждого отвода.

    Провод, не разрезанный в точке ответвления, KiCad молча считает
    несоединённым — на печати это неотличимо от исправной схемы
    (README, «Проверка»). Точка ставится там, где сходится больше двух концов.
    """
    pts = sorted(set(taps))
    for a, b in zip(pts, pts[1:]):
        s.wire((a, y), (b, y))
    for x in junctions:
        s.junction((x, y))


# ------------------------------------------------- островок аналога кодека

def island_b(s):
    """`AVCC` и `AGND` на шинах: пять конденсаторов между ними (§6.3)."""
    av, ag = BY + 12.7, BY + 25.4           # шина AVCC и шина AGND
    xs = [BX + i * 12.7 for i in range(5)]
    # флаги ставим между конденсаторами, а не рядом с резистором:
    # подпись R803/R804 уходит вправо на 5 мм и накрывает символ
    flag_av, flag_ag = BX + 19.05, BX + 31.75

    # +1V8 -> 0 Ω -> AVCC. Резистор 0805: сюда встанет бусина, если
    # понадобится (§6.3)
    pwr(s, "power:+1V8", BX, BY, 0, "§6.3")
    s.wire((BX, BY), (BX, BY + 2.54))
    part(s, BX, BY + 6.35, "Device:R", "R803", "0", "§6.3")
    s.wire((BX, BY + 10.16), (BX, av))

    bus(s, av, [xs[0], flag_av, xs[1], xs[2]], [xs[0], flag_av, xs[1]])
    s.glabel("AVCC", (xs[2], av), 0)
    s.wire((flag_av, av), (flag_av, av - 5.08))
    pwr(s, "power:PWR_FLAG", flag_av, av - 5.08, 0, "§6.3", show=False)

    # опора VRA1/VRA2 — свои метки, но возврат на ту же AGND
    s.glabel("VRA1", (xs[3], av), 0)
    s.glabel("VRA2", (xs[4], av), 0)

    for x, ref, val, sect in ((xs[0], "C823", "2.2u", "§6.3 объём аналога"),
                              (xs[1], "C824", "0.1u", "§6.3 вывод 89"),
                              (xs[2], "C825", "0.1u", "§6.3 вывод 97"),
                              (xs[3], "C826", "0.47u", "§6.3 вывод 92"),
                              (xs[4], "C827", "0.47u", "§6.3 вывод 90")):
        s.wire((x, av), (x, av + 2.54))
        part(s, x, av + 6.35, "Device:C", ref, val, sect)
        s.wire((x, av + 10.16), (x, ag))

    bus(s, ag, xs + [flag_ag], xs[1:4] + [flag_ag])
    s.glabel("AGND", (xs[4], ag), 0)
    s.wire((flag_ag, ag), (flag_ag, ag + 5.08))
    pwr(s, "power:PWR_FLAG", flag_ag, ag + 5.08, 180, "§6.3", show=False)

    # аналоговая земля пришита к общей одной точкой (§6.3)
    s.wire((xs[1], ag), (xs[1], ag + 2.54))
    part(s, xs[1], ag + 6.35, "Device:R", "R804", "0", "§6.3")
    s.wire((xs[1], ag + 10.16), (xs[1], ag + 12.7))
    pwr(s, "power:GND", xs[1], ag + 12.7, 0, "§6.3", show=False, vdy=5.08)


def gnd_probe(s):
    """Земляная контрольная точка у корпуса — без неё нечем мерить вывод 21."""
    x = X0 + 6 * PITCH
    pwr(s, "power:GND", x, ROWS[0], 180, "§6.5", show=False, vdy=-5.08)
    s.wire((x, ROWS[0]), (x, ROWS[0] + 6.35))
    s.sym("Connector:TestPoint", "TP802", "GND", x, ROWS[0] + 6.35, 180,
          src=f"{DOC} §6.5", show_value=False, rdx=0.0, rdy=5.08, just=None)


def main():
    s = Sheet(root_uuid(), 8, FRAME)
    at_pins(s)
    rails(s)
    island_a(s)
    island_b(s)
    gnd_probe(s)
    write(s)
    return 0


if __name__ == "__main__":
    sys.exit(main())
